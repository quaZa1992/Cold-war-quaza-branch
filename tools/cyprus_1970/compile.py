    if n['key'] in EXTRA:lines.append(EXTRA[n['key']])
    for target in FOREIGN.get(n['key'],[]):lines.append('country_exists = '+target)
    if n['key'] not in OBSERVED and n['key'] not in REACTIVE:
        for group in n['prerequisite_groups']:
            ready=[]
            for parent in group:
                parentkey=parent[len(P):]
                actual='has_completed_focus = '+parent+'\nNOT = { '+flag('pending_completion_'+parentkey)+' }'
                if parentkey not in OBSERVED:actual+='\n'+flag('applied_'+parentkey)
