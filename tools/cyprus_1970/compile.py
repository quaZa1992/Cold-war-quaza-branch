def base_payload(n):
    lines=[]
    for field,eff in [('political_power','add_political_power'),('stability','add_stability')]:
        if n[field]:lines.append(f'{eff} = {n[field]:g}')
    for field,var in [('tension','communal_tension'),('settlement','settlement_progress'),('coup_pressure_delta','coup_pressure')]:
        val=n.get(field,0)
        if val:lines += [f'add_to_variable = {{ {fid(var)} = {val:g} }}',f'clamp_variable = {{ var = {fid(var)} min = 0 max = 100 }}']
    target=n.get('settlement_credit_target',0)
    if target:
        lines.append(cond(f'check_variable = {{ {fid("party_reform_credit")} < {target} }}',
            f'set_temp_variable = {{ {fid("credit_delta")} = {target} }}\nsubtract_from_temp_variable = {{ {fid("credit_delta")} = {fid("party_reform_credit")} }}\nadd_to_variable = {{ {fid("settlement_progress")} = {fid("credit_delta")} }}\nset_variable = {{ {fid("party_reform_credit")} = {target} }}\nclamp_variable = {{ var = {fid("settlement_progress")} min = 0 max = 100 }}'))
    if n['research']:
        lines.append(f'add_tech_bonus = {{ name = {n["id"]}_research_bonus bonus = 0.25 uses = 1 category = {n["research"]} }}')
        loc(n['id']+'_research_bonus',n['title'])
    if n['modifiers']:
        if n['party'] is not None:
            idx=n['party']
            for k,v in n['modifiers'].items():lines.append(f'add_to_variable = {{ {fid("p"+str(idx)+"_"+k)} = {v:g} }}')
            lines += [f'add_dynamic_modifier = {{ modifier = {fid("p"+str(idx)+"_programme")} }}','force_update_dynamic_modifier = yes']
        elif n.get('duration_days'):
            lines.append(f'add_timed_idea = {{ idea = {fid(n["key"]+"_idea")} days = {n["duration_days"]} }}')
        else:lines.append('add_ideas = '+fid(n['key']+'_idea'))
    return '\n'.join(lines)

