def block(name, body):
    return name + ' = {\n' + '\n'.join('\t' + line if line else '' for line in body.splitlines()) + '\n}'


def cond(test, body, otherwise=''):
    result = block('if', block('limit', test) + '\n' + body)
    if otherwise:
        result += '\n' + block('else', otherwise)
    return result


def previous_day(value):
    y, m, d = map(int, value.split('.'))
    v = date(y, m, d) - timedelta(days=1)
    return f'{v.year}.{v.month}.{v.day}'


def window(start='1970.1.1', end='2000.1.1'):
    return f'date > {previous_day(start)}\ndate < {end}'


def context(tag):
    return f'original_tag = {tag}\nexists = yes\nIMP_is_1970_scenario = yes'


# Definitions deliberately separate recruitment from chief-of-service eligibility.
# Political bans following historical coups are NOT unconditional end dates.
