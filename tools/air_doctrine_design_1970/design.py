def scoped(scopes, **stats):
    return {scope + '.' + key: value for scope in scopes for key, value in stats.items()}


def equipment(frames, **stats):
    return scoped(('equipment_bonus.' + frame for frame in frames), **stats)


def package(ident, name, track, source, description, base, rewards):
    assert len(rewards) == (6 if track == 'grand' else 5)
    return dict(id='mdcw_' + ident, name=name, track=track, sources=source, description=description,
                activation=base, progression=[dict(name=name, effects=effects) for name, effects in rewards])


