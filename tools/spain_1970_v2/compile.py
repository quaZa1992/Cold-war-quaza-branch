def num(x):
    d=Decimal(str(x)).quantize(Decimal('.00001'))
    return format(d,'f').rstrip('0').rstrip('.') if d else '0'
def block(k,s):return k+' = {\n'+s.strip()+'\n}\n'
def quote(s):return '"'+str(s).replace('\\','\\\\').replace('"',"'").replace('\n','\\n')+'"'
def slug(ident):return ident.removeprefix(P)
def applied(ident):return P+'applied_'+slug(ident)
def programme(g):return V+'programme_'+g
def backing(g,k):return V+g+'_'+k
def code(s):return HEADER+format_code(s)
def flag(f):return 'has_country_flag = '+f
def treas(x):return 'set_temp_variable = { treasury_change = '+num(x)+' }\nmodify_treasury_effect = yes\n'
def fund(x):return 'check_variable = { var = treasury value = '+num(x)+' compare = greater_than_or_equals }'

def provider(module,design):
    file=HERE/(module+'.py')
    if not file.exists():raise RuntimeError('Missing scoped provider '+file.name)
    spec=importlib.util.spec_from_file_location('spain_v2_'+module,file);mod=importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod.build(ROOT,design)

