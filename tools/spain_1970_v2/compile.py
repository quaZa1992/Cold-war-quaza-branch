    def asset_gate(self,e):
        kind=e['building'];state=e['state'];amount=e['amount']
        definition=self.buildings[kind];cap=first(definition,'level_cap',[])
        maximum=int(first(cap,'state_max',50))
        shared=first(cap,'shares_slots')=='yes'
        # Shared slots are granted with the building, so do not demand an already-free slot.
        # Native MD uses the building's own numeric state trigger (ENG/Japan/Brazil decisions).
        body=f'is_owned_and_controlled_by = ROOT\n{kind} < {maximum-amount+1}'
        if kind=='dockyard':body+='\nis_coastal = yes'
        return block(str(state),body)
    def decision_preview(self,e):
        for name in ['politics_previews.json','agreements_previews.json']:
            path=HERE/name
            if path.exists():
                data=json.loads(path.read_text(encoding='utf-8-sig'))
                if 'effects' in data:data=data['effects']
                if e['id'] in data:
                    v=data[e['id']]
                    return v if isinstance(v,str) else v['preview']
        raise RuntimeError('Missing numeric/native custom effect preview '+e['id'])
    def native(self,e,n):
        kind=e['type']
        if kind=='treasury':return treas(e['amount'])
        if kind=='building':
            amount=e['amount'];body=''
            if e.get('add_extra_state_shared_building_slots'):body+='add_extra_state_shared_building_slots = '+str(amount)+'\n'
            body+=block('add_building_construction',f'type = {e["building"]}\nlevel = {amount}\ninstant_build = yes')
            return block(str(e['state']),body)
        if kind=='experience':return e['service']+'_experience = '+num(e['amount'])+'\n'
        if kind=='research':return block('add_tech_bonus','name = '+e.get('name',n['id'])+'\nbonus = '+num(e['bonus'])+'\nuses = '+str(e['uses'])+'\ncategory = '+e['category'])
        if kind=='native_effect':
            args=e['args']
            if isinstance(args,dict):return block(e['effect'],'\n'.join(k+' = '+(num(v) if isinstance(v,(float,int)) else str(v)) for k,v in args.items()))
            return e['effect']+' = '+str(args)+'\n'
        if kind=='scripted_effect':
            if e['effect']!='increase_education_budget':raise ValueError(e)
            return block('if','limit = { OR = { has_idea = edu_01 has_idea = edu_02 has_idea = edu_03 has_idea = edu_04 } }\nincrease_education_budget = yes')
        if kind=='decision':return e['id']+'_effect = yes\n'
        if kind=='spirit_swap':return self.spirit_swap(e)
        if kind=='modifier':return ''
        raise ValueError(e)
    def spirit_swap(self,e):
        # Stages are monotone: doing the audit after industrial standards cannot regress the economy.
        chains=[['protected_industry','audited_industry','modern_industry'],['labour_territorial_strain','civil_guarantees_spirit','labour_compact'],['army_of_regime','reformed_armed_forces']]
        add=e['add'];old=e['remove'];result=''
        if add:
            chain=next((a for a in chains if slug(add) in a),None)
            guard=''
            if chain:
                index=chain.index(slug(add));later=chain[index+1:]
                if later:guard='NOT = { OR = { '+' '.join('has_idea = '+P+x for x in later)+' } }\n'
                removals=chain[:index]
            else:removals=[slug(old)]
            for rem in removals:result+=block('if','limit = { has_idea = '+P+rem+' }\nremove_ideas = '+P+rem)
            # Family penalties may already have been cleared by the actual legal settlement.
            if add==P+'managed_succession':guard+='NOT = { COLDWAR_SPR_franco_has_left_office = yes }\n'
            result+='add_ideas = '+add+'\n'
            return block('if','limit = { '+guard+' }\n'+result) if guard else result
        return block('if','limit = { has_idea = '+old+' }\nremove_ideas = '+old)
    def preview(self,n):
        result='';mods=[e for e in n['effects'] if e['type']=='modifier' and n['id'] not in LEGAL_FOCI]
        if mods:
            result+='custom_effect_tooltip = { localization_key = modifies_dynamic_modifier_tt MODIFIER = '+programme(n['group'])+' }\n'
            if n['group'] in POLITICAL_GROUPS:
                result+='custom_effect_tooltip = '+V+'cabinet_duration_tt\n'
            for e in mods:
                key=e['key'];tooltip=V+'mod_'+key+'_tt'
                self.locset(tooltip,LABELS[key]+': $RIGHT|'+('-=' if key in LOW_IS_GOOD else '+=')+'%1$')
                result+='add_to_variable = { '+backing(n['group'],key)+' = '+num(e['amount'])+' tooltip = '+tooltip+' }\n'
        for e in n['effects']:
            if e['type']=='modifier':continue
            if e['type']=='decision':result+=self.decision_preview(e)+'\n'
            elif e['type']=='spirit_swap':
                # Swap semantics shown as the actual named old/new ideas and numeric native modifier display.
                if e['add']:result+=block('swap_ideas','remove_idea = '+e['remove']+'\nadd_idea = '+e['add'])
                else:result+=block('if','limit = { has_idea = '+e['remove']+' }\nremove_ideas = '+e['remove'])
            elif e['type']=='scripted_effect':
                # Preview the actual next funded law; never preview the helper's endpoint PP refund.
                result+=self.native(e,n)
            else:result+=self.native(e,n)
        return result
    def modifier_condition(self,n,e):
        conditions=[flag(applied(n['id']))]
        scope=e.get('scope','national')
        if n['group'] in POLITICAL_GROUPS:conditions.append('COLDWAR_SPR_government_'+n['group']+' = yes')
        elif scope=='cabinet':
            if n['id']==P+'traditionalist_bargain':conditions.append('COLDWAR_SPR_carlist_traditionalists = yes')
            elif n['id']==P+'social_federal_bargain':conditions.append('COLDWAR_SPR_carlist_social_federalists = yes')
            else:raise ValueError('Unrouted cabinet policy '+n['id'])
        if scope=='while_Franco_in_office':conditions.append('COLDWAR_SPR_franco_in_office = yes')
        if scope=='while_outside_NATO':conditions.append('NOT = { has_idea = NATO_member }')
        member=n.get('gate',{}).get('actual_membership_spirit')
        if member:
            conditions.append('has_idea = '+member)
            if member==P+'eec_membership':conditions.append('has_idea = EU_member')
        return '\n'.join(conditions)
    def programmes(self):
        dyn='';sync='';groupkeys={}
        for gid,g in self.groups.items():
            rows=[n for n in self.d['nodes'] if n['group']==gid and n['id'] not in LEGAL_FOCI]
            keys=sorted({e['key'] for n in rows for e in n['effects'] if e['type']=='modifier'})
            if not keys:continue
            groupkeys[gid]=keys
            for k in keys:sync+='set_variable = { '+backing(gid,k)+' = 0 }\n'
            checks=[]
            for n in rows:
                if n['id'] in LABOUR_FOCI:continue
                mod=[e for e in n['effects'] if e['type']=='modifier']
                for e in mod:
                    cond=self.modifier_condition(n,e)
                    sync+=block('if',block('limit',cond)+'add_to_variable = { '+backing(gid,e['key'])+' = '+num(e['amount'])+' }')
                if mod:checks.append(flag(applied(n['id'])))
            if gid=='territorial':
                earned='OR = { '+flag(applied(P+'official_labour'))+' '+flag(applied(P+'free_unions'))+' }'
                for node,condition in [(self.nodes[P+'free_unions'],'COLDWAR_SPR_representative_settlement = yes'),(self.nodes[P+'official_labour'],'COLDWAR_SPR_authoritarian_settlement = yes')]:
                    bdy=''.join('add_to_variable = { '+backing(gid,e['key'])+' = '+num(e['amount'])+' }\n' for e in node['effects'] if e['type']=='modifier')
                    sync+=block('if',block('limit',earned+'\n'+condition)+bdy)
                checks.append(earned)
            gate='COLDWAR_SPR_campaign = yes'
            if gid in POLITICAL_GROUPS:gate+='\nCOLDWAR_SPR_government_'+gid+' = yes'
            enabled=gate+'\nOR = { '+' '.join(checks)+' }'
            dyn+=block(programme(gid),'icon = "GFX_idea_'+V+GROUP_ART[gid]+'"\n'+block('enable',gate)+'\n'.join(k+' = '+backing(gid,k) for k in keys))
            sync+=block('if',block('limit',enabled)+block('if','limit = { NOT = { has_dynamic_modifier = { modifier = '+programme(gid)+' } } }\nadd_dynamic_modifier = { modifier = '+programme(gid)+' }'))
            sync+=block('else',block('if','limit = { has_dynamic_modifier = { modifier = '+programme(gid)+' } }\nremove_dynamic_modifier = { modifier = '+programme(gid)+' }'))
            self.locset(programme(gid),g['label'])
            self.locset(programme(gid)+'_desc',('The governing cabinet\'s enacted programme. Its recurring effects rest when it leaves office and return with the same political mandate.' if gid in POLITICAL_GROUPS else 'The institutions, investment standards and service reforms enacted by the Spanish state.'))
        sync+='force_update_dynamic_modifier = yes\n'
        self.files['common/dynamic_modifiers/COLDWAR_SPR_v2_programmes.txt']=code(dyn)
        return block('COLDWAR_SPR_sync_programmes',block('if',block('limit','COLDWAR_SPR_campaign = yes\n'+flag(V+'core_initialized'))+sync))
