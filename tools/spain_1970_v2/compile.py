def main():
    parser=argparse.ArgumentParser();parser.add_argument('--stage',type=Path);parser.add_argument('--core-only',action='store_true');args=parser.parse_args()
    approved=HERE/'approved_design.json';sha=hashlib.sha256(approved.read_bytes()).hexdigest()
    if sha!=APPROVED_HASH:raise RuntimeError('Approved design changed; do not silently replace owner approval.')
    design=json.loads(approved.read_text(encoding='utf-8'));files={}
    if not args.core_only:
        for mod in ['politics','agreements']:
            out=provider(mod,design)
            if not isinstance(out,dict):raise TypeError(mod+' build must return a file mapping')
            for rel,value in out.items():
                if rel in files:raise RuntimeError('Duplicate generated output '+rel)
                files[rel]=value
    files.update(Compiler(design).build())
    target=args.stage or ROOT
    hashes={}
    for rel,value in files.items():
        if Path(rel).is_absolute() or '..' in Path(rel).parts:raise RuntimeError('Unsafe provider path '+rel)
        blob=value if isinstance(value,bytes) else value.encode('utf-8-sig' if rel.endswith('.yml') else 'utf-8')
        if not rel.endswith('.yml') and blob.startswith(b'\xef\xbb\xbf'):raise RuntimeError('Script BOM '+rel)
        p=target/rel;p.parent.mkdir(parents=True,exist_ok=True);p.write_bytes(blob);hashes[rel]=hashlib.sha256(blob).hexdigest()
    manifest=dict(approved_sha256=sha,focuses=len(design['nodes']),generated=hashes,stage=str(target),scope='Spain only; shared leader/history hooks are narrowly maintained by politics.py.')
    (HERE/'manifest.json').write_text(json.dumps(manifest,indent=2)+'\n',encoding='utf-8')
    print(json.dumps({'focuses':len(design['nodes']),'outputs':len(files),'target':str(target)}))

if __name__=='__main__':main()
