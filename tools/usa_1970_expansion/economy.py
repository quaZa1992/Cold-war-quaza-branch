# IMPERIA COLD WAR — USA 1970 native tax-model calibration.
"""Own only the narrow USA tax calibration effect and its integration contract.

MD's corporate-tax slider controls both receipts and a 1.5-times consumer-goods
base. It cannot be populated with the historical top statutory profits rate.
No global tax formula, sanctions or fiscal streams change. Save correction is
limited to the original 48 default and the explicitly supplied 42 setting.
"""
from __future__ import annotations

from decimal import Decimal, ROUND_CEILING
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
HERE = Path(__file__).resolve().parent
EFFECT_PATH = 'common/scripted_effects/COLDWAR_USA_1970_economy.txt'
FLAG = 'COLDWAR_USA_1970_tax_model_calibrated'
START_RATE = Decimal('20')
LEGACY_RATES = {Decimal('48'): START_RATE, Decimal('42'): Decimal('17.5')}


def compound_factors(factors):
    result = Decimal(1)
    for factor in factors:
        result *= Decimal(str(factor))
    return result


def consumer_goods(rate, multiplier, industries=162, available_civs=100):
    """Source-derived forecast; ceiling is a conservative rounding assumption.

    Native construction uses civilian plus military industries as its base.
    The ledger's separate civ-only estimate is not the construction consumer.
    This function is a model, not a new runtime reader or a native observation.
    ``multiplier`` is the final observed native factor, e.g. 1.62, not a sum of
    the individual idea percentages. Native construction compounds those rows.
    """
    share = Decimal(str(rate)) * Decimal('.015') * Decimal(str(multiplier))
    required = share * Decimal(industries)
    conservative = int(required.to_integral_value(rounding=ROUND_CEILING))
    return dict(share=share, required=required,
                usable_lower_bound=max(0, available_civs - conservative))


def build():
    text = f'''# IMPERIA COLD WAR — USA 1970 native tax-model calibration.
# Generated by tools/usa_1970_expansion/economy.py.
# The historical 48% basic statutory profits rate is not MD's economy-wide tax slider.
# These effects never change sanctions, spending, treasury, debt or income multipliers.

# Country scope. Called only inside the existing fresh-start systems initializer,
# at its corporate-tax assignment and before the ordinary MD fiscal refresh.
COLDWAR_USA_1970_economy_initialize = {{
\tif = {{
\t\tlimit = {{
\t\t\ttag = USA
\t\t\tIMP_is_1970_scenario = yes
\t\t\thas_country_flag = USA_1970_systems_initialized
\t\t\tNOT = {{ has_country_flag = {FLAG} }}
\t\t}}
\t\tset_variable = {{ corporate_tax_rate = 20 }}
\t\tset_country_flag = {FLAG}
\t}}
}}

# Country scope. Call only on startup or the USA daily hook, after the legacy
# initializer has returned. Never call from leader changes or generic reconcile:
# the legacy systems receipt is set before its fiscal assignments finish.
# One migration per save. Recognize only the broken default and
# the supplied 42% save. Preserve its relative 42/48 policy reduction: 20*42/48.
# All other rates, including manually selected 20 or 25, are left unchanged.
COLDWAR_USA_1970_economy_migrate = {{
\tif = {{
\t\tlimit = {{
\t\t\ttag = USA
\t\t\tIMP_is_1970_scenario = yes
\t\t\thas_country_flag = USA_1970_systems_initialized
\t\t\tNOT = {{ has_country_flag = {FLAG} }}
\t\t}}
\t\tset_country_flag = {FLAG}
\t\tset_temp_variable = {{ COLDWAR_USA_1970_tax_model_changed = 0 }}
\t\tif = {{
\t\t\tlimit = {{ check_variable = {{ corporate_tax_rate = 48 }} }}
\t\t\tset_variable = {{ corporate_tax_rate = 20 }}
\t\t\tset_temp_variable = {{ COLDWAR_USA_1970_tax_model_changed = 1 }}
\t\t}}
\t\telse_if = {{
\t\t\tlimit = {{ check_variable = {{ corporate_tax_rate = 42 }} }}
\t\t\tset_variable = {{ corporate_tax_rate = 17.5 }}
\t\t\tset_temp_variable = {{ COLDWAR_USA_1970_tax_model_changed = 1 }}
\t\t}}
\t\tif = {{
\t\t\tlimit = {{ check_variable = {{ COLDWAR_USA_1970_tax_model_changed = 1 }} }}
\t\t\t# Recompute the native tax modifier before its construction/display reader.
\t\t\tcalculate_tax_rate = yes
\t\t\tforce_update_dynamic_modifier = yes
\t\t\t# Ordinary MD recalculation updates the deficit without applying a weekly payment.
\t\t\tingame_update_setup = yes
\t\t}}
\t}}
}}
'''
    specs = dict(project='IMPERIA COLD WAR', effect_path=EFFECT_PATH,
                 initializer='COLDWAR_USA_1970_economy_initialize',
                 migration='COLDWAR_USA_1970_economy_migrate', receipt=FLAG,
                 start_rate=str(START_RATE),
                 migration_rates={str(k): str(v) for k, v in LEGACY_RATES.items()},
                 integration=dict(
                     initialize='Replace only the corporate-tax assignment within USA_1970_initialize_systems. Do not overwrite later player choices.',
                     migrate='Call only from on_startup and on_daily_USA, after the legacy initializer has returned. Never call from generic reconciliation or a leader callback; its early systems receipt precedes the fiscal assignments. Receipt makes later calls inert.'),
                 runtime_effects=dict(sanctions='unchanged', spending='unchanged',
                                     income_multipliers='unchanged', direct_money_transfer=False))
    return text, specs


def generate(root: Path = ROOT):
    text, specs = build()
    outputs = {EFFECT_PATH: text,
               'tools/usa_1970_expansion/economy_hooks.json': json.dumps(specs, ensure_ascii=False, indent=2) + '\n'}
    changed = []
    for relative, content in outputs.items():
        path = root / relative
        path.parent.mkdir(parents=True, exist_ok=True)
        data = content.encode('utf-8')
        if not path.exists() or path.read_bytes() != data:
            path.write_bytes(data)
            changed.append(relative)
    return dict(project='IMPERIA COLD WAR', changed=changed, hooks=specs)


if __name__ == '__main__':
    print(json.dumps(generate(), ensure_ascii=False, indent=2))
