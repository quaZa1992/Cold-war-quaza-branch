def clean(value):
    if isinstance(value, dict):
        return {k: clean(v) for k, v in value.items()}
    if isinstance(value, list):
        return [clean(v) for v in value]
    if isinstance(value, str):
        for char in '—–’‘“”−':
            try:
                value = value.replace(char.encode('utf-8').decode('cp1252'), char)
            except UnicodeDecodeError:
                pass
    return value


def write(relative, source, bom=False):
    path = ROOT/relative
    path.parent.mkdir(parents=True, exist_ok=True)
    if path.suffix == '.txt' and relative.startswith(('common/', 'events/')):
        source = FORMAT.format_script(source)
    payload = source.encode('utf-8-sig' if bom else 'utf-8')
    if not path.exists() or path.read_bytes() != payload:
        with tempfile.NamedTemporaryFile(dir=path.parent, prefix='.__syr70_', delete=False) as stream:
            temporary = Path(stream.name)
            stream.write(payload)
        os.replace(temporary, path)
    OUTPUTS.append(relative)


def loc(key, value):
    assert key not in LOC or LOC[key] == value, key
    LOC[key] = clean(value)


