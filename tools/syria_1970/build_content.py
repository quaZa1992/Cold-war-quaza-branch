def amend_costs(data):
    tiers = {.024: 2, .036: 2.5, .048: 3, .060: 3.5, .072: 4,
             .096: 4.5, .120: 5, .156: 5.5, .192: 6, .216: 6.25,
             .240: 6.5, .252: 6.75, .360: 7}
    for n in data['nodes']:
        previous = round(n['treasury_cost_bn'], 6)
        if not previous:
            continue
        assert previous in tiers, (n['id'], previous)
        n['approved_previous_cost_bn'] = previous
        n['treasury_cost_bn'] = tiers[previous]
        n['available'] = re.sub(r'check_variable\s*=\s*\{\s*treasury\s*>\s*[\d.]+\s*\}',
                               'check_variable = { treasury > '+f'{tiers[previous]-.000001:.6f}'+' }', n['available'])
        n['reward_summary'] = [s for s in n.get('reward_summary', []) if 'treasury cost:' not in s]
        n['reward_summary'].append(f'One-time treasury cost: ${tiers[previous]:.3f} billion.')
        if n['id'] == 'COLDWAR_SYR_fiscal_04':
            old_summary = n['one_time'][0]['summary']
            n['one_time'][0]['summary'] = f'One native corruption-law tier reduction, with 100 political power and ${tiers[previous]:.3f} billion implementation expenditure. Already-clean administrations bypass this focus without a windfall.'
            n['reward_summary'] = [n['one_time'][0]['summary'] if s == old_summary else s for s in n['reward_summary']]
    data['contract']['cost_amendment'] = 'User: paid focus treasury costs $2.000–$7.000 billion; decision and GDP-operation costs retain their separate schedule.'


def apply_english(data):
    entries = {}
    for filename in ('english_politics.json', 'english_national.json'):
        section = json.loads((HERE/filename).read_text(encoding='utf-8'))
        assert not entries.keys() & section.keys(), 'Duplicate English focus descriptions'
        entries.update(section)
    assert set(entries) == {node['id'] for node in data['nodes']}, 'Incomplete English focus description coverage'
    for node in data['nodes']:
        description = entries[node['id']]['description']
        assert len(description.split()) > 30, node['id']
        node['description'] = description


def apply_runtime_policy(data):
    policy = json.loads((HERE/'runtime_policy.json').read_text(encoding='utf-8'))
    assert policy['focus_borrowing_allowed'] is True
    amendments = dict(policy['entry_rewards'])
    additional = HERE/'additional_entry_rewards.json'
    if additional.exists():
        amendments.update(json.loads(additional.read_text(encoding='utf-8')))
    for node in data['nodes']:
        node['available'] = re.sub(r'check_variable\s*=\s*\{\s*treasury\s*>\s*[\d.]+\s*\}', '', node['available'])
        amendment = amendments.get(node['id'])
        if amendment:
            assert not node['modifiers'] and not node['one_time'], node['id']
            node['modifiers'] = amendment['modifiers'].copy()
            node['reward_summary'] = amendment['summary']+[line for line in node['reward_summary'] if not line.startswith('Institutional preparation milestone')]
            node['entry_reward_amended'] = True
            node['description'] += ' '+amendment['rationale']
    data['contract']['focus_financing'] = 'Focus expenditure is charged once through native MD treasury; negative treasury is financed by the existing automatic debt system. No positive-treasury eligibility gate applies.'
    data['contract']['entry_reward_amendments'] = amendments


def modifier_tooltip(modifier, native_keys):
    key = modifier+'_tt'
    if key in native_keys:
        return key
    key = 'COLDWAR_SYR_'+modifier+'_tt'
    name = next((k for k in (modifier, 'modifier_'+modifier, 'MODIFIER_'+modifier.upper(), 'MODIFIERS_'+modifier.upper()) if k in native_keys), None)
    assert name, ('Missing native modifier label', modifier)
    spending = 'cost_multiplier' in modifier or modifier == 'corruption_cost_factor'
    fmt = '-=%1' if spending else '+=%1'
    loc(key, '$'+name+'$: $RIGHT|'+fmt+'$')
    return key


def programmes(data):
    dynamics, init, refresh = [], [], []
    for g in data['groups']:
        keys = sorted({m for n in data['nodes'] if n['group'] == g['id'] for m in n['modifiers']})
        if not keys:
            continue
        owner = g['owner']
        gate = 'IMP_is_1970_scenario = yes'
        if g['kind'] != 'national':
            gate += '\n'+g['gate']
        dynamics.append(owner+' = { icon = GFX_idea_political_establishment enable = { '+gate+' }\n'+
                        '\n'.join(f'{m} = {owner}_{m}' for m in keys)+'\n}')
        init.extend(f'set_variable = {{ {owner}_{m} = 0 }}' for m in keys)
        eligible = gate+'\nhas_country_flag = '+owner+'_earned'
        refresh.append('if = { limit = { '+eligible+' }\n'
                       'if = { limit = { NOT = { has_dynamic_modifier = '+owner+' } } add_dynamic_modifier = { modifier = '+owner+' } }\n'
                       '} else = { if = { limit = { has_dynamic_modifier = '+owner+' } remove_dynamic_modifier = { modifier = '+owner+' } } }')
        loc(owner, g['label'].split(' — ')[-1]+': Programme')
        loc(owner+'_desc', 'Earned policy measures. '+('Durable national programme.' if g['kind'] == 'national' else 'Active only while the corresponding governing party, office holder or coalition remains in authority. Earned measures return with that authority.'))
    for spirit in data['starting_spirits']:
        ident = spirit['id']
        dynamics.append(ident+' = { icon = GFX_idea_political_establishment enable = { IMP_is_1970_scenario = yes }\n'+
                        '\n'.join(f'{m} = {ident}_{m}' for m in spirit['modifiers'])+'\n}')
        loc(ident, spirit['label'])
        loc(ident+'_desc', spirit['treatment'])
    effects = 'COLDWAR_SYR_initialize_programme_variables = {\n'+'\n'.join(init)+'\n}\n'
    effects += 'COLDWAR_SYR_refresh_programmes = {\nif = { limit = { original_tag = SYR IMP_is_1970_scenario = yes has_country_flag = COLDWAR_SYR_initialized }\n'
    effects += '\n'.join(refresh)+'\nCOLDWAR_SYR_recompute_starting_spirits = yes\nforce_update_dynamic_modifier = yes\n'
    effects += 'if = { limit = { has_global_flag = mdcw_cw_initialized has_country_flag = mdcw_cw_initialized } mdcw_cw_recalculate_country = yes mdcw_cw_update_world_market = yes }\nupdate_money_dirty_variable = yes\n}\n}\n'
    write('common/dynamic_modifiers/COLDWAR_SYR_programmes.txt', HEADER+'\n\n'.join(dynamics)+'\n')
    return effects


def starting_spirits(data):
    out = ['COLDWAR_SYR_recompute_starting_spirits = {']
    for s in data['starting_spirits']:
        out += [f'set_variable = {{ {s["id"]}_{k} = {v} }}' for k, v in s['modifiers'].items()]
    def change(condition, ident, changes):
        out.append('if = { limit = { '+condition+' }\n'+'\n'.join(f'set_variable = {{ {ident}_{k} = {v} }}' for k, v in changes.items())+'\n}')
    p = 'COLDWAR_SYR_'
    command_settled = 'OR = { AND = { has_country_flag = '+p+'dual_command_resolved '+implemented(p+'opening_settlement')+' } '+implemented(p+'parliament_05')+' has_country_flag = '+p+'military_transfer_agreed }'
    change(command_settled, p+'divided_command', dict(political_power_factor=0, army_org_factor=0))
    change('has_country_flag = '+p+'emergency_abolished', p+'emergency_state', dict(stability_factor=0, research_speed_factor=0, political_power_factor=0))
    change(implemented(p+'army_05'), p+'legacy_1967', dict(army_org_factor=0))
    change('controls_state = 587', p+'legacy_1967', dict(war_support_factor=0))
    change(implemented(p+'fiscal_09'), p+'uneven_services', dict(research_speed_factor=0))
    change(implemented(p+'infrastructure_12'), p+'uneven_services', dict(production_speed_buildings_factor=0))
    change(implemented(p+'agriculture_05'), p+'state_sector_strain', dict(agricolture_productivity_modifier=0))
    # Independent stages commute; either audit removes four of eight points.
    for focus in ('industry_12', 'fiscal_12'):
        out.append('if = { limit = { '+implemented(p+focus)+' } subtract_from_variable = { '+p+'state_sector_strain_bureaucracy_cost_multiplier_modifier = 0.04 } }')
    change(implemented(p+'agriculture_12'), p+'rain_sensitive_farms', dict(agricolture_productivity_modifier=-.04))
    change(implemented(p+'agriculture_15'), p+'rain_sensitive_farms', dict(agricolture_productivity_modifier=0))
    change('OR = { '+implemented(p+'citizenship_03')+' has_country_flag = '+p+'reopen_citizenship_review }', p+'citizenship_exclusion', dict(stability_factor=-.02))
    change(implemented(p+'citizenship_15'), p+'citizenship_exclusion', dict(stability_factor=0, political_power_factor=0))
    for s in data['starting_spirits']:
        ident = s['id']
        active = 'OR = { '+' '.join(f'NOT = {{ check_variable = {{ {ident}_{m} = 0 }} }}' for m in s['modifiers'])+' }'
        out.append('if = { limit = { '+active+' } if = { limit = { NOT = { has_dynamic_modifier = '+ident+' } } add_dynamic_modifier = { modifier = '+ident+' } } } else = { if = { limit = { has_dynamic_modifier = '+ident+' } remove_dynamic_modifier = { modifier = '+ident+' } } }')
    return '\n'.join(out)+'\n}\n'


def entry_reward_migration(data):
    lines = ['COLDWAR_SYR_migrate_entry_rewards_20261019 = {',
             'if = { limit = { NOT = { has_country_flag = COLDWAR_SYR_entry_variables_20261019 } }']
    variables = sorted({node['owner']+'_'+modifier for node in data['nodes'] for modifier in node['modifiers']})
    for variable in variables:
        lines.append('if = { limit = { NOT = { has_variable = '+variable+' } } set_variable = { '+variable+' = 0 } }')
    lines += ['set_country_flag = COLDWAR_SYR_entry_variables_20261019', '}']
    for node in data['nodes']:
        if not node.get('entry_reward_amended'):
            continue
        signature = node['id']+'_entry_reward_20261019'
        lines.append('if = { limit = { '+implemented(node['id'])+' NOT = { has_country_flag = '+signature+' } }')
        lines += ['set_country_flag = '+signature, 'set_country_flag = '+node['owner']+'_earned']
        lines += [f'add_to_variable = {{ {node["owner"]}_{key} = {value:g} }}' for key, value in node['modifiers'].items()]
        lines.append('}')
    return '\n'.join(lines)+'\n}\n'


