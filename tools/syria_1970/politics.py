def closing_brace(text, opening):
    """Find a Clausewitz block boundary without counting braces in strings/comments."""
    depth, quoted, comment, escape = 0, False, False, False
    for i in range(opening, len(text)):
        char = text[i]
        if comment:
            if char == "\n":
                comment = False
            continue
        if quoted:
            if char == '"' and not escape:
                quoted = False
            escape = char == "\\" and not escape
            continue
        if char == "#":
            comment = True
        elif char == '"':
            quoted = True
        elif char == "{":
            depth += 1
        elif char == "}":
            depth -= 1
            if depth == 0:
                return i
    raise ValueError("Unclosed Clausewitz block")


def patch_modern_syria(root):
    # Preserve the modern 2000 tree, but its periodic faction/BOP routines must
    # not run against uninitialized 1970 systems. Event-level guards also cover
    # the yearly Hafez-death caller and monthly random-event lottery.
    path = Path(root) / "common/on_actions/99_SYR_on_actions.txt"
    if not path.is_file():
        # The user authorized retiring the dedicated modern Syria programme.
        return
    text = path.read_text(encoding="utf-8-sig")
    marker = "# COLDWAR_SYR: modern 2000 systems only."
    for action in ("on_monthly_SYR", "on_weekly_SYR"):
        match = re.search(r"\b" + action + r"\s*=\s*\{", text)
        assert match, f"Native Syria action missing: {action}"
        action_end = closing_brace(text, text.index("{", match.start()))
        effect = re.search(r"\beffect\s*=\s*\{", text[match.end():action_end])
        assert effect, f"Native Syria effect missing: {action}"
        opening = text.index("{", match.end() + effect.start())
        end = closing_brace(text, opening)
        if marker not in text[opening:end]:
            body = text[opening + 1:end]
            wrapped = "\n\t\t\t" + marker + "\n\t\t\tif = { limit = { NOT = { IMP_is_1970_scenario = yes } }" + body + "\n\t\t\t}\n\t\t"
            text = text[:opening + 1] + wrapped + text[end:]
    path.write_text(text, encoding="utf-8")
    path = Path(root) / "events/Syria.txt"
    text = path.read_text(encoding="utf-8-sig")
    guard = "NOT = { IMP_is_1970_scenario = yes } # COLDWAR_SYR: use the historical scenario succession instead."
    for number in (39, 40, 41, 42):
        match = re.search(r"\bid\s*=\s*SyriaFocus\." + str(number) + r"\b", text)
        assert match, f"Native Syrian succession event missing: {number}"
        trigger = re.search(r"\btrigger\s*=\s*\{", text[match.end():])
        assert trigger
        opening = text.index("{", match.end() + trigger.start())
        end = closing_brace(text, opening)
        if "COLDWAR_SYR: use the historical scenario succession" not in text[opening:end]:
            text = text[:opening + 1] + "\n\t\t" + guard + "\n\t\t" + text[opening + 1:]
    path.write_text(text, encoding="utf-8")


