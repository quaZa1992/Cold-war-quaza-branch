def material_option_preview(effect):
    """Keep native material effects visible without exposing state bookkeeping."""
    allowed = {'add_stability', 'add_war_support', 'add_ideas', 'remove_ideas',
               'add_timed_idea', 'modify_treasury_effect'}
    lines = []
    for key, op, value in _FORMAT.read(effect):
        if key == 'set_temp_variable' and isinstance(value, list):
            if value and value[0][0] == 'treasury_change':
                lines.append(f'set_temp_variable = {{ treasury_change = {value[0][2]} }}')
        elif key in allowed:
            if isinstance(value, list):
                lines.append(key+' = { '+' '.join(f'{k} {o} {v}' for k, o, v in value)+' }')
            else:
                lines.append(f'{key} {op} {value}')
    return '\n'.join(lines)


