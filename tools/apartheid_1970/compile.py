def normalisation_preview(host,recipient=False,direction=1):
    scope='' if recipient else 'FROM = '
    # Two country headings, each followed by the exact current opinion change.
    # Temporary variables are confined to effect_tooltip and never execute.
    lines=[]
    for country in ((host,scope or 'THIS = '),('THIS' if recipient else 'FROM',host+' = ')):
        _,wrapper=country
        value='set_temp_variable = { '+P+'preview_opinion = '+host+'.'+P+'political }\nmultiply_temp_variable = { '+P+'preview_opinion = '+num(Decimal('12.5')*direction)+' }\n'
        trade='add_to_variable = { '+P+'regional_trade = '+P+'preview_opinion tooltip = '+P+'regional_trade_tt }'
        if host=='SAF':
            # The customs-union exception suppresses only the trade component.
            guard='NOT = { has_country_flag = '+P+'customs_contact_SAF }' if wrapper!='SAF = ' else ('ROOT' if recipient else 'FROM')+' = { NOT = { has_country_flag = '+P+'customs_contact_SAF } }'
            trade=block('if','limit = { '+guard+' }\n'+trade)
        value+=trade+'\nadd_to_variable = { '+P+'regional_diplomatic = '+P+'preview_opinion tooltip = '+P+'regional_diplomatic_tt }'
        lines.append(wrapper+'{\n'+value+'\n}')
    return block('effect_tooltip','\n'.join(lines))


