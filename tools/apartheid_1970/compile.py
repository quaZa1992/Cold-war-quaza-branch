def patch_money(text):
    if not text.startswith(MARKER):text=MARKER+text
    sys.path.insert(0,str(ROOT/'tools/vietnam_1970'))
    from script_ast import parse,first
    # Locate only the two complete commercial calculations. Preserve every
    # adjacent money formula and the separate subsistence calculation.
    for variable in ('agriculture_district_tax','gdp_from_agriculture_district'):
        match=re.search(r'\b'+variable+r'\s*=\s*\{',text)
        if not match:raise ValueError('Missing commercial consumer: '+variable)
        start=match.start(); at=text.index('{',match.start()); depth=1; end=at+1
        while depth:
            if text[end]=='{':depth+=1
            elif text[end]=='}':depth-=1
            end+=1
        fragment=text[start:end]
        addition='add = modifier@'+AGRI
        if addition not in fragment:
            if variable=='agriculture_district_tax':
                donor='add = modifier@agricolture_productivity_modifier'
                replacement=donor+'\n\t\t\t\t\t# IMPERIA COLD WAR — Commercial agriculture only.\n\t\t\t\t\t'+addition
            else:
                donor='multiply = modifier@agricolture_productivity_modifier'
                replacement='multiply = { value = modifier@agricolture_productivity_modifier '+addition+' } # IMPERIA COLD WAR — Commercial agriculture only.\n'
            if fragment.count(donor)!=1:raise ValueError('Ambiguous commercial factor: '+variable)
            fragment=fragment.replace(donor,replacement)
            text=text[:start]+fragment+text[end:]
    parse(text)
    return text


def focus_positions():
    sys.path.insert(0,str(ROOT/'tools/vietnam_1970'))
    from script_ast import parse,first
    tree=first(parse((ROOT/'common/national_focus/mdcw_1970_generic_focus.txt').read_text(encoding='utf-8')),'focus_tree')
    nodes={first(v,'id'):v for k,o,v in tree if k=='focus'}
    positions={}
    def resolve(key):
        if key in positions:return positions[key]
        row=nodes[key];x=int(first(row,'x',0));y=int(first(row,'y',0));relative=first(row,'relative_position_id')
        if relative in nodes:
            px,py=resolve(relative);x+=px;y+=py
        positions[key]=(x,y)
        return x,y
    for key in nodes:resolve(key)
    return nodes,positions


