# IMPERIA CW — Cold War: usa 1970 quality — apply.
"""Maintained editorial overlay for the live USA1970 tree.

Its historical header references a generator absent from this checkout. This
overlay therefore owns only the declared English descriptions and visible
availability presentation; it never reconstructs or replaces rewards.
"""
import json
from pathlib import Path
import re
import sys
sys.path.insert(0,str(Path(__file__).resolve().parent))
from presentation import patch_usa

ROOT=Path(__file__).resolve().parents[2]
def atomic(path,text,encoding):
    stage=path.with_name(path.name+'.quality-stage')
    stage.write_text(text,encoding=encoding,newline='\n');stage.replace(path)
def apply():
    data=json.loads((Path(__file__).parent/'narrative.json').read_text(encoding='utf-8'))
    target=ROOT/'localisation/english/USA_1970_focus_l_english.yml'
    lines=target.read_text(encoding='utf-8-sig').splitlines();seen=set()
    for i,line in enumerate(lines):
        match=re.match(r'\s*(\S+)_desc:\d*\s*".*"\s*$',line)
        if match and match[1] in data:
            key=match[1];seen.add(key)
            lines[i]=' '+key+'_desc:0 '+json.dumps(data[key],ensure_ascii=False)
    assert seen==set(data),sorted(set(data)-seen)
    term='USA_1970_nixon_first_term_tt'
    if not any(re.match(r'\s*'+term+r':',line) for line in lines):
        lines.append(' '+term+':0 "Nixon is President and the opening administration programme has not ended (20 January 1973)."')
    atomic(target,'\n'.join(lines)+'\n','utf-8-sig')
    tree=ROOT/'common/national_focus/USA_1970.txt'
    text=tree.read_text(encoding='utf-8-sig')
    overlay='# Maintained narrative and availability overlay: tools/usa_1970_quality/apply.py (the historical generator named above is absent from this checkout).\n'
    if overlay not in text:
        anchor='# Generated by tools/generate_usa_1970_focus_tree.py\n'
        assert anchor in text
        text=text.replace(anchor,anchor+overlay,1)
    atomic(tree,patch_usa(text),'utf-8')
    return len(data)

if __name__=='__main__':print('Updated USA English focus narratives:',apply())
