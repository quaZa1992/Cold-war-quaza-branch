"""Emit only the Greek/Cypriot source-owned outputs, without history integration."""
import importlib.util
import json
from pathlib import Path
import re
import sys

ROOT=Path(__file__).resolve().parents[2]
def module(country):
    folder=ROOT/'tools'/f'{country}_1970'
    sys.path.insert(0,str(folder))
    spec=importlib.util.spec_from_file_location('quality_compile',folder/'compile.py')
    c=importlib.util.module_from_spec(spec);sys.modules[spec.name]=c;spec.loader.exec_module(c)
    return c

def emit(country):
    c=module(country);captured={}
    def capture(rel,text,bom=False):
        captured[rel]=(text,bom)
        if hasattr(c,'GENERATED'):c.GENERATED.append(rel)
        elif hasattr(c,'FILES'):c.FILES.append(rel)
    c.write=capture
    if country=='greece':c.main()
    else:
        import runtime
        c.emit_spirits();runtime.generate_runtime(c);c.build_focuses()
        outputs={
            'common/scripted_effects/COLDWAR_CYP_1970_effects.txt':'\n\n'.join(c.block(k,v) for k,v in c.EFFECTS.items())+'\n',
            'common/scripted_triggers/COLDWAR_CYP_1970_triggers.txt':'\n\n'.join(c.block(k,v) for k,v in c.TRIGGERS.items())+'\n',
            'common/ideas/COLDWAR_CYP_1970_ideas.txt':c.block('ideas',c.block('country','\n\n'.join(c.IDEA_BLOCKS)))+'\n',
            'common/dynamic_modifiers/COLDWAR_CYP_1970_modifiers.txt':'\n\n'.join(c.DYNAMIC)+'\n',
            'events/COLDWAR_CYP_1970_events.txt':'add_namespace = COLDWAR_CYP_1970\n\n'+'\n\n'.join(c.EVENTS)+'\n',
            'common/decisions/COLDWAR_CYP_1970_decisions.txt':c.block(c.fid('dossier'),'\n\n'.join(c.DECISIONS))+'\n'+c.block(c.fid('foreign_dossier'),'\n\n'.join(c.FOREIGN_DECISIONS))+'\n',
        }
        for rel,body in outputs.items():capture(rel,c.HEADER+body)
        # Preserve party-registry and NCY integration keys generated by other
        # source owners. Only keys authored by this compiler are replaced.
        rel='localisation/english/COLDWAR_CYP_1970_l_english.yml'
        lines=(ROOT/rel).read_text(encoding='utf-8-sig').splitlines();seen=set()
        for i,line in enumerate(lines):
            m=re.match(r'\s*([^\s:]+):\d*\s*".*"\s*$',line)
            if m and m[1] in c.LOC:
                key=m[1];seen.add(key);lines[i]=' '+key+':0 '+json.dumps(c.LOC[key].replace('\\n','\n'),ensure_ascii=False)
        lines += [' '+k+':0 '+json.dumps(v.replace('\\n','\n'),ensure_ascii=False) for k,v in c.LOC.items() if k not in seen]
        capture(rel,'\n'.join(lines)+'\n',True)
    changed=[]
    for rel,(text,bom) in captured.items():
        if rel.startswith('tools/'):continue
        assert rel.startswith(('common/','interface/','events/','localisation/')),rel
        p=ROOT/rel
        data=text.encode('utf-8-sig' if bom else 'utf-8')
        if p.exists() and p.read_bytes()==data:continue
        p.parent.mkdir(parents=True,exist_ok=True)
        staged=p.with_name(p.name+'.quality-stage')
        staged.write_bytes(data);staged.replace(p);changed.append(rel)
    return changed

if __name__=='__main__':print(json.dumps(emit(sys.argv[1]),indent=2))
