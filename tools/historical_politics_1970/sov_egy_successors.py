# IMPERIA CW — Cold War: Historical parties, leaders and national identities.
"""Build narrowly scoped historical SOV/EGY retirement integrations.

The module preserves each country's authored 1970 setup. Egypt keeps its
24-family selector for every non-manual call; the added selector is reached
only while the existing retire action supplies MDCW_HP_native_retirement.
For Soviet communist leaders, retirement delegates to the Cold War Politburo
succession effects instead of creating a generic MD country leader.
"""
from __future__ import annotations

import re
from collections.abc import Mapping
from pathlib import Path


HEADER = '# IMPERIA CW — Cold War: Historical parties, leaders and national identities.\n# Generated by tools/historical_politics_1970/sov_egy_successors.py.\n'
APPROVED_STATUSES = {
    "visually_reviewed", "edited_visually_reviewed",
    "original_historical_user_approved", "reviewed", "approved",
    "existing_exact_name_md_reference",
}
EXACT_NAME_PROVENANCE = "existing exact-name MD reference"


class GeneratedFiles(dict):
    """Output mapping with explicit categories for the root builder."""

    def __init__(self, *args, helpers=None, triggers=None, provider_patches=None, integration_report=None, **kwargs):
        super().__init__(*args, **kwargs)
        self.new_helper_effects = list(helpers or [])
        self.new_triggers = list(triggers or [])
        self.native_provider_patches = list(provider_patches or [])
        self.integration_report = dict(integration_report or {})


def _approved_portrait(manifest, key: str) -> str | None:
    if not isinstance(manifest, Mapping):
        return None
    candidates = [manifest.get(key)]
    for field in ("portraits", "key_map", "portrait_map"):
        nested = manifest.get(field)
        if isinstance(nested, Mapping):
            candidates.append(nested.get(key))
    for record in candidates:
        if not isinstance(record, Mapping):
            continue
        path = record.get("portrait") or record.get("path")
        status = record.get("status")
        provenance = record.get("provenance")
        approved = status in APPROVED_STATUSES
        approved |= status is None and provenance == EXACT_NAME_PROVENANCE
        if approved and isinstance(path, str) and path:
            return path.replace("\\", "/")
    return None


def _country_map(countries):
    if isinstance(countries, Mapping):
        return dict(countries)
    return {row["tag"]: row for row in countries}


def _leaders(countries, tag):
    country = countries.get(tag)
    if not country:
        return {}
    return {row.get("id"): row for row in country.get("leaders", [])}


def _create(name: str, picture: str, ideology: str) -> str:
    return (
        "create_country_leader = {\n"
        f'\tname = "{name}"\n'
        f'\tpicture = "{picture}"\n'
        f"\tideology = {ideology}\n"
        "}"
    )


def _braced_end(text: str, opening: int) -> int:
    depth = 0
    quoted = escaped = comment = False
    for i in range(opening, len(text)):
        ch = text[i]
        if comment:
            if ch == "\n":
                comment = False
            continue
        if quoted:
            if escaped:
                escaped = False
            elif ch == "\\":
                escaped = True
            elif ch == '"':
                quoted = False
            continue
        if ch == "#":
            comment = True
        elif ch == '"':
            quoted = True
        elif ch == "{":
            depth += 1
        elif ch == "}":
            depth -= 1
            if depth == 0:
                return i + 1
    raise ValueError("Unbalanced HOI4 scripted-effect block")


def _effect_block(text: str, key: str) -> tuple[int, int, str]:
    match = re.search(r"(?m)^\s*" + re.escape(key) + r"\s*=\s*\{", text)
    if not match:
        raise ValueError(f"Could not find native effect {key}")
    opening = text.find("{", match.start(), match.end())
    end = _braced_end(text, opening)
    return match.start(), end, text[match.start():end]


def _strip_generated(text: str, begin: str, end: str) -> str:
    pattern = re.compile(r"(?ms)^[ \t]*" + re.escape(begin) + r"[^\n]*\n.*?^[ \t]*" + re.escape(end) + r"[^\n]*\n?")
    return pattern.sub("", text)


def _restore_generated(text: str, begin: str, end: str, body: str) -> str:
    pattern = re.compile(r"(?ms)^[ \t]*" + re.escape(begin) + r"[^\n]*\n.*?^[ \t]*" + re.escape(end) + r"[^\n]*\n?")
    return pattern.sub(lambda _: body + "\n", text)


def _patch_egy_provider(root: Path, source_texts=None) -> str:
    rel = "common/scripted_effects/EGY_political_leaders.txt"
    text = source_texts.get(rel) if source_texts and rel in source_texts else (root / rel).read_text(encoding="utf-8-sig")
    marker = "# MDCW HP EGY MANUAL SUCCESSORS BEGIN"
    old = "\t\tCOLDWAR_EGY_set_party_leader_1970 = yes"
    text = _restore_generated(text, marker, "# MDCW HP EGY MANUAL SUCCESSORS END", old)
    _, _, effect = _effect_block(text, "set_leader_EGY")
    if effect.count(old) != 1:
        raise ValueError("Expected one Egypt 1970 roster dispatch in set_leader_EGY")
    new = (
        "\t\tif = {\n"
        "\t\t\tlimit = { check_variable = { MDCW_HP_native_retirement = 1 } }\n"
        "\t\t\tMDCW_HP_set_egy_manual_leader = yes\n"
        "\t\t}\n"
        "\t\telse = { COLDWAR_EGY_set_party_leader_1970 = yes }\n"
        "\t\t" + "# MDCW HP EGY MANUAL SUCCESSORS END"
    )
    patched = text.replace(old, marker + "\n# IMPERIA CW — Cold War: Historical Egyptian successor selection.\n" + new, 1)
    return patched


def _patch_sov_provider(root: Path, yeltsin_path: str, source_texts=None) -> str:
    rel = "common/scripted_effects/SOV_political_leaders.txt"
    text = source_texts.get(rel) if source_texts and rel in source_texts else (root / rel).read_text(encoding="utf-8-sig")
    marker = "# MDCW HP SOV CIVILIAN SUCCESSOR BEGIN"
    text = _strip_generated(text, marker, "# MDCW HP SOV CIVILIAN SUCCESSOR END")
    anchor = '\telse_if = { limit = { check_variable = { ruling_party = 2 } }'
    if text.count(anchor) != 1:
        raise ValueError("Expected one native SOV liberal-family selector")
    branch = (
        "\telse_if = {\n"
        "\t\tlimit = { check_variable = { MDCW_HP_native_retirement = 1 } check_variable = { ruling_party = 2 } }\n"
        "\t\tMDCW_HP_set_sov_yeltsin = yes\n"
        "\t}\n"
    )
    return text.replace(anchor, marker + "\n# IMPERIA CW — Cold War: Historical Soviet civilian succession.\n" + branch + "\t" + "# MDCW HP SOV CIVILIAN SUCCESSOR END\n" + anchor, 1)


def _patch_sov_clear_gensec(root: Path, source_texts=None) -> str:
    rel = "common/scripted_effects/COLDWAR_SOV_1970_scripted_effects.txt"
    text = source_texts.get(rel) if source_texts and rel in source_texts else (root / rel).read_text(encoding="utf-8-sig")
    marker = "# MDCW HP SOV PENDING CLEAR BEGIN"
    text = _strip_generated(text, marker, "# MDCW HP SOV PENDING CLEAR END")
    _, _, block = _effect_block(text, "COLDWAR_SOV_clear_gensec")
    close = block.rfind("}")
    # Clearing at the common gensec reset means every normal successful install
    # ends the manual-retirement lock before it appoints the successor.
    insert = "\t" + marker + "\n\t# IMPERIA CW — Cold War: Clear historical Soviet retirement requests.\n\tMDCW_HP_SOV_clear_manual_retirement_pending = yes\n\t# MDCW HP SOV PENDING CLEAR END\n"
    patched_block = block[:close] + insert + block[close:]
    text = text.replace(block, patched_block, 1)
    # The two authored heir shortcuts do not pass through COLDWAR_SOV_clear_gensec.
    for key in ("COLDWAR_SOV_heir_takes_over_aliyev", "COLDWAR_SOV_heir_takes_over_grishin"):
        _, _, current = _effect_block(text, key)
        begin = f"# MDCW HP SOV DIRECT HEIR CLEAR {key} BEGIN"
        end = f"# MDCW HP SOV DIRECT HEIR CLEAR {key} END"
        text = _strip_generated(text, begin, end)
        _, _, current = _effect_block(text, key)
        close = current.rfind("}")
        injected = current[:close] + f"\t{begin}\n\t# IMPERIA CW — Cold War: Clear the direct-heir retirement request.\n\tMDCW_HP_SOV_clear_manual_retirement_pending = yes\n\t{end}\n" + current[close:]
        text = text.replace(current, injected, 1)
    # A failed vote opens COLDWAR_SOV.31. Keep that choice protected from a
    # duplicate retirement request; successful installation clears both flags.
    _, _, tally = _effect_block(text, "COLDWAR_SOV_tally_vote")
    marker_tally = "# MDCW HP SOV VOTE RETIREMENT HANDOFF BEGIN"
    end_tally = "# MDCW HP SOV VOTE RETIREMENT HANDOFF END"
    text = _strip_generated(text, marker_tally, end_tally)
    _, _, tally = _effect_block(text, "COLDWAR_SOV_tally_vote")
    anchor = "\t\tset_variable = { global.COLDWAR_SOV_vote_succession = 0 }"
    if tally.count(anchor) != 1:
        raise ValueError("Could not locate SOV succession vote reset point")
    handoff = (
        "\t\t" + marker_tally + "\n\t\t# IMPERIA CW — Cold War: Preserve the Soviet succession vote handoff.\n"
        "\t\tif = {\n"
            "\t\t\tlimit = { check_variable = { global.COLDWAR_SOV_vote_type = 3 } check_variable = { global.COLDWAR_SOV_vote_succession = 1 } NOT = { has_global_flag = COLDWAR_SOV_vote_passed } has_country_flag = MDCW_HP_SOV_manual_retirement_pending }\n"
        "\t\t\tset_country_flag = MDCW_HP_SOV_manual_retirement_choice_pending\n"
        "\t\t}\n"
        "\t\tMDCW_HP_SOV_clear_manual_retirement_request = yes\n"
        "\t\t" + end_tally + "\n"
    )
    updated_tally = tally.replace(anchor, handoff + anchor, 1)
    text = text.replace(tally, updated_tally, 1)
    return text


