def generate_sov_egy_successors(root, countries, manifest, source_texts=None) -> GeneratedFiles:
    """Return helper effects, triggers, and narrowly scoped native provider edits.

    `countries` is the canonical tag-to-record mapping (or iterable of rows).
    `source_texts` may provide already-patched contents keyed by repository-
    relative path, allowing the root builder to compose independent generators.
    Only portrait-manifest-approved catalogue leaders can enter these pools.
    The function does not write files or alter source inputs.
    """
    root = Path(root)
    catalog = _country_map(countries)
    egypt = _leaders(catalog, "EGY")
    soviet = _leaders(catalog, "SOV")
    if not egypt or not soviet:
        return GeneratedFiles()

    egypt_portraits = {}
    for ident in ("gamal_abdel_nasser", "anwar_sadat", "hosni_mubarak", "khaled_mohieddin"):
        record = egypt.get(ident)
        approved = _approved_portrait(manifest, f"EGY_{ident}")
        if not record or not approved:
            raise ValueError(f"Egypt successor lacks an approved canonical portrait: EGY/{ident}")
        if record.get("portrait") and record["portrait"].replace("\\", "/") != approved:
            # The catalogue's descriptive path can be stale; the approval manifest
            # is authoritative for the installed image.
            pass
        egypt_portraits[ident] = approved

    yeltsin_record = soviet.get("boris_yeltsin")
    yeltsin = _approved_portrait(manifest, "SOV_boris_yeltsin") if yeltsin_record else None
    if yeltsin and int(yeltsin_record.get("party_index", -1)) != 2:
        raise ValueError("Boris Yeltsin's canonical family is not the expected native liberalism slot")

    outputs = {
        "common/scripted_effects/mdcw_historical_sov_egy_successors.txt": _helper_text(egypt_portraits, yeltsin),
        "common/scripted_triggers/mdcw_historical_sov_egy_successors.txt": _trigger_text(),
        "common/scripted_effects/EGY_political_leaders.txt": _patch_egy_provider(root, source_texts),
        "common/scripted_effects/COLDWAR_SOV_1970_scripted_effects.txt": _patch_sov_clear_gensec(root, source_texts),
    }
    if yeltsin:
        outputs["common/scripted_effects/SOV_political_leaders.txt"] = _patch_sov_provider(root, yeltsin, source_texts)
    integration_report = {
        "egypt": {
            "ordinary_provider": "COLDWAR_EGY_set_party_leader_1970 unchanged outside MDCW_HP_native_retirement temporary context",
            "manual_native_families": {"1": ["Zakaria Mohieddin", "Hosni Mubarak"], "18": ["Gamal Abdel Nasser", "Anwar as-Sadat", "Khaled Mohieddin"]},
            "counter_sync": "Before central leader kill, match current ruling leader by has_country_leader name; seed conservatism_leader or neutral_Social_leader to that person's slot. Sadat accepts native alias 'Anwar as-Sadat' and canonical display 'Anwar Sadat'.",
            "native_singleton_families_left_unchanged": [4, 19],
            "portrait_approval": {ident: _approved_portrait(manifest, f"EGY_{ident}") for ident in sorted(egypt_portraits)},
        },
        "soviet": {
            "communist_retirement": "MDCW_HP_SOV_native_retirement delegates to COLDWAR_SOV_succession; vote and pending/choice flags block duplicates; install paths clear pending.",
            "civilian_retirement": "Manual-context native party-index-2 branch offers approved Boris Yeltsin without a one-use gate; the native button requires an alternative to the current leader. Ordinary provider flow unchanged.",
            "portrait_approval": {"boris_yeltsin": yeltsin},
            "other_candidates_not_added": "Existing COLDWAR gensec story chain remains authoritative; unapproved/pending special portrait rows are not inserted by this generator.",
        },
    }
    return GeneratedFiles(
        outputs,
        helpers=["MDCW_HP_SOV_native_retirement", "MDCW_HP_SOV_clear_manual_retirement_request", "MDCW_HP_SOV_clear_manual_retirement_pending", "MDCW_HP_sync_sov_egy_counter", "MDCW_HP_set_egy_manual_leader"] + (["MDCW_HP_set_sov_yeltsin"] if yeltsin else []),
        triggers=["MDCW_HP_SOV_retirement_available", "MDCW_HP_has_sov_egy_successor_pool"],
        provider_patches=list(outputs),
        integration_report=integration_report,
    )
