class GeneratedFiles(dict):
    """Installable text outputs plus a non-installable candidate audit."""

    def __init__(self, *args, report=None, **kwargs):
        super().__init__(*args, **kwargs)
        self.report = report or {}


def _normalize_name(value: str) -> str:
    value = unicodedata.normalize("NFKD", value)
    value = "".join(c for c in value if not unicodedata.combining(c))
    return re.sub(r"[^a-z0-9]+", "", value.casefold())


def _block_end(text: str, opening: int) -> int:
    depth = 0
    quoted = escaped = comment = False
    for i in range(opening, len(text)):
        char = text[i]
        if comment:
            if char == "\n":
                comment = False
            continue
        if quoted:
            if escaped:
                escaped = False
            elif char == "\\":
                escaped = True
            elif char == '"':
                quoted = False
            continue
        if char == "#":
            comment = True
        elif char == '"':
            quoted = True
        elif char == "{":
            depth += 1
        elif char == "}":
            depth -= 1
            if depth == 0:
                return i + 1
    raise ValueError("Unclosed HOI4 script block")


def _assignment_blocks(text: str, key: str, lower: int = 0, upper: int | None = None):
    """Yield (start, opening brace, end) for lexical ``key = {}`` blocks."""
    stop = len(text) if upper is None else upper
    i = lower
    quoted = escaped = comment = False
    while i < stop:
        char = text[i]
        if comment:
            if char == "\n":
                comment = False
            i += 1
            continue
        if quoted:
            if escaped:
                escaped = False
            elif char == "\\":
                escaped = True
            elif char == '"':
                quoted = False
            i += 1
            continue
        if char == "#":
            comment = True
            i += 1
            continue
        if char == '"':
            quoted = True
            i += 1
            continue
        if text.startswith(key, i):
            before_ok = i == lower or not (text[i - 1].isalnum() or text[i - 1] == "_")
            after = i + len(key)
            after_ok = after >= stop or not (text[after].isalnum() or text[after] == "_")
            if before_ok and after_ok:
                j = after
                while j < stop and text[j].isspace():
                    j += 1
                if j < stop and text[j] == "=":
                    j += 1
                    while j < stop and text[j].isspace():
                        j += 1
                    if j < stop and text[j] == "{":
                        end = _block_end(text, j)
                        if end > stop:
                            raise ValueError(f"Unclosed {key} block within parent")
                        yield i, j, end
                        i = end
                        continue
        i += 1


def _one_string(block: str, key: str) -> str | None:
    pattern = re.compile(r"(?m)(?<![A-Za-z0-9_])" + re.escape(key) + r"\s*=\s*\"((?:\\.|[^\"\\])*)\"")
    found = []
    for match in pattern.finditer(block):
        line_start = block.rfind("\n", 0, match.start()) + 1
        if "#" not in block[line_start:match.start()]:
            found.append(match.group(1).replace('\\"', '"').replace("\\\\", "\\"))
    if len(found) > 1:
        raise ValueError(f"Ambiguous quoted {key} assignments: {found}")
    return found[0] if found else None


def _one_atom(block: str, key: str) -> str | None:
    matches = re.findall(r"(?m)(?<![A-Za-z0-9_])" + re.escape(key) + r"\s*=\s*([A-Za-z][A-Za-z0-9_]*)", block)
    return matches[0] if len(matches) == 1 else None


def _function_body(text: str, function: str) -> str:
    blocks = list(_assignment_blocks(text, function))
    if len(blocks) != 1:
        raise ValueError(f"Expected one {function} definition, found {len(blocks)}")
    _, opening, end = blocks[0]
    return text[opening + 1:end - 1]


def _native_leaders(root: Path, tag: str) -> list[dict]:
    files_and_functions = {
        "USA": [("common/scripted_effects/USA_1970_scripted_effects.txt", "USA_1970_set_scenario_leader")],
        # Keep the scenario provider first. Aznar and other documented modern
        # entries can be found in SPR's normal setter after those scenario rows.
        "SPR": [
            ("common/scripted_effects/COLDWAR_SPR_politics.txt", "COLDWAR_SPR_set_scenario_leader"),
            ("common/scripted_effects/SPR_political_leaders.txt", "set_leader_SPR"),
        ],
    }[tag]
    result = []
    source_index = 0
    for relative, function in files_and_functions:
        path = root / relative
        if not path.is_file():
            raise ValueError(f"Missing native provider source: {relative}")
        function_text = _function_body(path.read_text(encoding="utf-8-sig"), function)
        for _, opening, end in _assignment_blocks(function_text, "create_country_leader"):
            block = function_text[opening + 1:end - 1]
            name = _one_string(block, "name")
            ideology = _one_atom(block, "ideology")
            if not name or not ideology:
                continue
            family = IDEOLOGY_INDEX.get(ideology.casefold())
            if family is None:
                continue
            traits_matches = list(_assignment_blocks(block, "traits"))
            traits = "traits = { }"
            if traits_matches:
                _, trait_open, trait_end = traits_matches[0]
                traits = "traits = {" + block[trait_open + 1:trait_end - 1] + "}"
            result.append({
                "name": name,
                "normalized": _normalize_name(name),
                "family": family,
                "ideology": ideology,
                "traits": traits,
                "source": relative,
                "source_index": source_index,
            })
            source_index += 1
    return result


def _catalogue_records(root: Path, countries) -> dict[str, dict[str, list[dict]]]:
    """Collect world records and existing SPECIAL-provider inventory rows."""
    result: dict[str, dict[str, list[dict]]] = {tag: defaultdict(list) for tag in SPECIAL_TAGS}
    for tag in SPECIAL_TAGS:
        country = countries.get(tag) if isinstance(countries, Mapping) else None
        if country:
            for row in country.get("leaders", []):
                result[tag][_normalize_name(row.get("name", ""))].append({**row, "_source_kind": "world"})
    special_path = root / "tools/historical_politics_1970/special_portraits.json"
    if special_path.is_file():
        payload = json.loads(special_path.read_text(encoding="utf-8-sig"))
        for country in payload.get("countries", []):
            tag = country.get("tag")
            if tag not in SPECIAL_TAGS:
                continue
            for row in country.get("leaders", []):
                name = row.get("native_name") or row.get("name", "")
                result[tag][_normalize_name(name)].append({**row, "name": name, "_source_kind": "special"})
    return result


def _manifest_record(manifest, tag: str, records: list[dict], native_name: str):
    keys = []
    for row in records:
        ident = row.get("id")
        if ident:
            keys.append(f"{tag}_{ident}")
    # Exact native spelling is a fallback when the catalogues do not agree on
    # accents or a native_name alias.
    keys.append(f"{tag}_{re.sub(r'[^a-z0-9]+', '_', _normalize_name(native_name))}")
    for key in dict.fromkeys(keys):
        value = manifest.get(key) if isinstance(manifest, Mapping) else None
        if not isinstance(value, Mapping):
            continue
        status = value.get("status")
        provenance = value.get("provenance")
        accepted = status in REVIEWED_STATUSES or (status is None and provenance == EXACT_NAME_PROVENANCE)
        portrait = value.get("portrait") or value.get("path")
        if accepted and isinstance(portrait, str) and portrait:
            return key, value, portrait
    return None


def _quote(value: str) -> str:
    if any(c in value for c in "\r\n\x00"):
        raise ValueError(f"Invalid multiline/control value {value!r}")
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def _counter(tag: str, family: int) -> str:
    return f"mdcw_hp_{tag.casefold()}_special_retire_{family}"


def _current_match_block(tag: str, family: int, candidates: list[dict], depth: str = "\t") -> str:
    variable = _counter(tag, family)
    lines = [
        f"{depth}if = {{",
        f"{depth}\tlimit = {{ NOT = {{ has_variable = {variable} }} }}",
        f"{depth}\tset_variable = {{ {variable} = 0 }}",
        f"{depth}}}",
    ]
    for slot, row in enumerate(candidates):
        kind = "if" if slot == 0 else "else_if"
        lines.extend([
            f"{depth}{kind} = {{",
            f"{depth}\tlimit = {{ has_country_leader = {{ name = {_quote(row['name'])} ruling_only = yes }} }}",
            f"{depth}\tif = {{",
            f"{depth}\t\tlimit = {{ has_country_flag = do_not_retire }}",
            f"{depth}\t\tset_variable = {{ {variable} = {slot} }}",
            f"{depth}\t}}",
            f"{depth}\telse = {{",
            f"{depth}\t\tset_variable = {{ {variable} = {(slot + 1) % len(candidates)} }}",
            f"{depth}\t}}",
            f"{depth}}}",
        ])
    return "\n".join(lines)


def _create_candidate(tag: str, row: dict, variable: str, slot: int, count: int) -> list[str]:
    selected = row["name"]
    picture = row["portrait"]
    ideology = row["ideology"]
    traits = row["traits"]
    next_slot = (slot + 1) % count
    lines = [
        "create_country_leader = {",
        f"\tname = {_quote(selected)}",
        f"\tpicture = {_quote(picture)}",
        f"\tideology = {ideology}",
        "\t" + traits,
        "}",
        "if = {",
        "\tlimit = { has_country_flag = do_not_retire }",
        f"\tset_variable = {{ {variable} = {slot} }}",
        "}",
        "else = {",
        f"\tset_variable = {{ {variable} = {next_slot} }}",
        "}",
    ]
    if tag == "USA" and _normalize_name(selected) == "richardnixon":
        lines.append("set_country_flag = USA_1970_nixon_presidency")
    return lines


def _candidate_effect(tag: str, family: int, rows: list[dict]) -> str:
    variable = _counter(tag, family)
    lines = [f"MDCW_HP_special_retire_{tag}_{family} = {{"]
    if tag == "USA":
        lines.append("\tclr_country_flag = USA_1970_nixon_presidency")
    for slot, row in enumerate(rows):
        kind = "if" if slot == 0 else "else_if"
        lines.extend([
            f"\t{kind} = {{",
            f"\t\tlimit = {{ check_variable = {{ {variable} = {slot} }} }}",
        ])
        lines.extend("\t\t" + item for item in _create_candidate(tag, row, variable, slot, len(rows)))
        lines.extend(["\t}"])
    lines.append("\telse = {")
    lines.extend("\t\t" + item for item in _create_candidate(tag, rows[0], variable, 0, len(rows)))
    lines.append("\t}")
    if tag == "SPR":
        lines.append("\tCOLDWAR_SPR_refresh_politics = yes")
    lines.append("}")
    return "\n".join(lines)


def _pool_files(grouped: dict[tuple[str, int], list[dict]]) -> tuple[str, str]:
    helpers = []
    trigger_rows = []
    sync_rows = []
    for (tag, family), rows in sorted(grouped.items()):
        helpers.append(_candidate_effect(tag, family, rows))
        trigger_rows.append(
            f"AND = {{ original_tag = {tag} check_variable = {{ ruling_party = {family} }} }}"
        )
        variable = _counter(tag, family)
        sync_rows.extend([
            "\tif = {",
            f"\t\tlimit = {{ original_tag = {tag} check_variable = {{ ruling_party = {family} }} }}",
            *_current_match_block(tag, family, rows, "\t\t").splitlines(),
            "\t}",
        ])
    trigger = "\n".join([
        HEADER,
        "MDCW_HP_has_special_successor_pool = {",
        "\tIMP_is_1970_scenario = yes",
        "\tcheck_variable = { MDCW_HP_native_retirement = 1 }",
        "\tOR = {",
        *["\t\t" + row for row in trigger_rows],
        "\t}",
        "}",
        "",
    ])
    effect = "\n".join([
        HEADER,
        "MDCW_HP_sync_special_counter = {",
        "\tif = {",
        "\t\tlimit = {",
        "\t\t\tIMP_is_1970_scenario = yes",
        "\t\t\tcheck_variable = { MDCW_HP_native_retirement = 1 }",
        "\t\t\tMDCW_HP_has_special_successor_pool = yes",
        "\t\t}",
        *sync_rows,
        "\t}",
        "}",
        "",
        *helpers,
        "",
    ])
    return effect, trigger


def _restore_wrapper(text: str, tag: str) -> str:
    begin = f"# MDCW HISTORICAL SPECIAL SUCCESSORS {tag} BEGIN"
    end = f"# MDCW HISTORICAL SPECIAL SUCCESSORS {tag} END"
    start = text.find(begin)
    if start < 0:
        return text
    finish = text.find(end, start)
    if finish < 0:
        raise ValueError(f"Unclosed special successor wrapper for {tag}")
    wrapper = text[start:finish]
    else_match = re.search(r"\belse\s*=\s*\{", wrapper)
    if not else_match:
        raise ValueError(f"Special successor wrapper for {tag} lost native fallback")
    opening = wrapper.find("{", else_match.start(), else_match.end())
    end_offset = _block_end(wrapper, opening)
    native = wrapper[opening + 1:end_offset - 1]
    # `_patch_setter` inserts one newline between the setter's opening brace
    # and the BEGIN marker. Drop that separator when recovering the native
    # body so repeated generation is byte-stable (apart from universal
    # newline normalization performed by Path.read_text/write_text).
    prefix = text[:start]
    if prefix.endswith("\n"):
        prefix = prefix[:-1]
    suffix = text[finish + len(end):]
    if suffix.startswith("\n"):
        suffix = suffix[1:]
    return prefix + native + suffix


def _patch_setter(root: Path, tag: str, families: dict[int, list[dict]]) -> str:
    path = root / f"common/scripted_effects/{tag}_political_leaders.txt"
    text = path.read_text(encoding="utf-8-sig")
    # IMPERIA CW — Cold War: Spain1970 authoritative provider preservation.
    # COLDWAR_SPR authoritative provider preservation
    if tag == "SPR" and "# COLDWAR_SPR AUTHORITATIVE SETTER BEGIN" in text:
        return text
    text = _restore_wrapper(text, tag)
    declaration = f"set_leader_{tag} = {{"
    matches = list(re.finditer(r"(?m)^\s*" + re.escape(declaration), text))
    if len(matches) != 1:
        raise ValueError(f"Expected one set_leader_{tag}, found {len(matches)}")
    match = matches[0]
    opening = text.find("{", match.start(), match.end())
    close = _block_end(text, opening)
    native = text[opening + 1:close - 1]
    begin = f"# MDCW HISTORICAL SPECIAL SUCCESSORS {tag} BEGIN"
    end = f"# MDCW HISTORICAL SPECIAL SUCCESSORS {tag} END"
    branches = []
    for position, family in enumerate(sorted(families)):
        branches.extend([
            ("if" if position == 0 else "else_if") + " = {",
            f"\tlimit = {{ MDCW_HP_has_special_successor_pool = yes check_variable = {{ ruling_party = {family} }} }}",
            f"\tMDCW_HP_special_retire_{tag}_{family} = yes",
            "}",
        ])
    wrapper_head = "\n".join([
        begin + '\n# IMPERIA CW — Cold War: Historical national successor selection.',
        *branches,
        "else = {",
    ])
    # `native` already carries the original body's leading and trailing
    # newlines. Keep it byte-for-byte inside the fallback instead of adding
    # join separators on either side.
    wrapper = wrapper_head + native + "}" + "\n" + end
    return text[:opening + 1] + "\n" + wrapper + "\n" + text[close - 1:]


def _candidate_rows(root: Path, tag: str, records: dict[str, list[dict]], native_rows: list[dict], manifest) -> tuple[dict[int, list[dict]], list[dict]]:
    by_normalized = records
    included: dict[tuple[int, str], dict] = {}
    skipped = []
    seen_native = set()
    for native in native_rows:
        key = (native["family"], native["normalized"])
        if key in seen_native:
            continue
        seen_native.add(key)
        candidates = by_normalized.get(native["normalized"], [])
        if not candidates:
            # The native setter contains many leaders outside the curated
            # historical catalogue. They are intentionally out of scope and
            # should not inflate the candidate rejection report.
            continue
        approved = _manifest_record(manifest, tag, candidates, native["name"])
        if not approved:
            statuses = sorted({str(row.get("status") or "unreviewed") for row in candidates})
            skipped.append({"name": native["name"], "family": native["family"], "reason": "no approved portrait", "portrait_statuses": statuses})
            continue
        key_name, manifest_row, portrait = approved
        portrait_path = Path(portrait.replace("\\", "/"))
        if portrait_path.is_absolute() or ".." in portrait_path.parts or not (root / portrait_path).is_file():
            skipped.append({"name": native["name"], "family": native["family"], "reason": "approved portrait missing or unsafe", "portrait": portrait})
            continue
        world_rows = [row for row in candidates if row.get("_source_kind") == "world"]
        world_families = sorted({row.get("party_index") for row in world_rows if isinstance(row.get("party_index"), int)})
        if world_families and native["family"] not in world_families:
            skipped_note = f"native family {native['family']} overrides catalogue family {world_families}"
        else:
            skipped_note = None
        # Same person may be authored in more than one native family (e.g.
        # Suárez in Spain's conservative and liberal outcomes). The native
        # setter supplies the authoritative family for each distinct block.
        candidate = {
            **native,
            "portrait": portrait_path.as_posix(),
            "manifest_key": key_name,
            "portrait_status": manifest_row.get("status") or manifest_row.get("provenance"),
            "world_available_from": next((row.get("available_from") for row in world_rows if row.get("available_from")), None),
            "native_family_overrides_world": skipped_note,
        }
        included[key] = candidate

    # Report curated candidates that could not be matched to a native setter
    # block. Do not report every unrelated native leader as a rejected row.
    native_names = {row["normalized"] for row in native_rows}
    reported_missing = set()
    for normalized, rows in records.items():
        if normalized in native_names:
            continue
        for row in rows:
            name = row.get("native_name") or row.get("name")
            if not name or normalized in reported_missing:
                continue
            reported_missing.add(normalized)
            skipped.append({
                "name": name,
                "family": row.get("party_index"),
                "reason": "no native leader binding",
                "source_kind": row.get("_source_kind"),
            })

    grouped: dict[int, list[dict]] = defaultdict(list)
    for row in sorted(included.values(), key=lambda item: item["source_index"]):
        grouped[row["family"]].append(row)
    return dict(grouped), skipped


def generate_special_successors(root, countries, manifest) -> GeneratedFiles:
    """Return approved USA/SPR manual-retirement pools and native setter hooks.

    `countries` is the loaded historical world catalogue. Only native named
    leader blocks whose portrait is approved by `manifest` are emitted.
    """
    root = Path(root)
    special_records = _catalogue_records(root, countries)
    grouped: dict[tuple[str, int], list[dict]] = {}
    report = {"countries": {}, "candidate_order_source": "native setter order; no date gates"}
    outputs = {}
    for tag in sorted(SPECIAL_TAGS):
        native = _native_leaders(root, tag)
        groups, skipped = _candidate_rows(root, tag, special_records[tag], native, manifest)
        if not groups:
            report["countries"][tag] = {"included": [], "skipped": skipped}
            continue
        for family, rows in groups.items():
            grouped[(tag, family)] = rows
        report["countries"][tag] = {
            "included": [
                {"family": family, "name": row["name"], "portrait": row["portrait"],
                 "portrait_status": row["portrait_status"],
                 "world_available_from": row["world_available_from"],
                 "native_family_overrides_world": row["native_family_overrides_world"]}
                for family, rows in sorted(groups.items()) for row in rows
            ],
            "skipped": skipped,
        }
        outputs[f"common/scripted_effects/{tag}_political_leaders.txt"] = _patch_setter(root, tag, groups)

    if grouped:
        effect, trigger = _pool_files(grouped)
        outputs["common/scripted_effects/mdcw_historical_special_successors.txt"] = effect
        outputs["common/scripted_triggers/mdcw_historical_special_successors.txt"] = trigger
    return GeneratedFiles(outputs, report=report)
