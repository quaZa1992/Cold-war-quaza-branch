# IMPERIA CW — Cold War: Historical parties, leaders and national identities.
"""Build reviewed historical leaders into MD's native country leader pools.

The generated branch is scoped to the 1970 scenario and the current ruling
party family. It has no per-person date gate: dated historical evidence orders
the finite pool, while MD's native family counter selects the next entry.
"""
from __future__ import annotations

import re
import unicodedata
from collections import defaultdict
from collections.abc import Mapping
from datetime import date
from pathlib import Path


SPECIAL = {"CYP", "NCY", "GRE", "TUR", "EGY", "ISR", "SOV", "SPR", "USA"}
SETUP_GUARD = {"DDR", "PAK"}
IDEOLOGIES = [
    "Western_Autocracy", "conservatism", "liberalism", "socialism",
    "communist_state", "anarchist_communism", "Conservative", "Autocracy",
    "Mod_Vilayat_e_Faqih", "Vilayat_e_Faqih", "Kingdom", "Caliphate",
    "Neutral_Muslim_Brotherhood", "Neutral_Autocracy", "Neutral_conservatism",
    "oligarchism", "Neutral_Libertarian", "Neutral_green", "neutral_Social",
    "Neutral_Communism", "Nat_Populism", "Nat_Fascism", "Nat_Autocracy",
    "Monarchist",
]

POOL_FILE = "common/scripted_effects/mdcw_historical_native_pools.txt"
POOL_TRIGGER_FILE = "common/scripted_triggers/mdcw_historical_native_pools.txt"
POOL_MARKER_BEGIN = "# MDCW HISTORICAL NATIVE POOLS BEGIN"
POOL_MARKER_END = "# MDCW HISTORICAL NATIVE POOLS END"
SYNC_EFFECT = "MDCW_HP_sync_native_counter"
POOL_TRIGGER = "MDCW_HP_has_native_pool"
SETTER_MARKER_BEGIN = "# MDCW HISTORICAL NATIVE POOL "
SETTER_MARKER_END = "# MDCW HISTORICAL NATIVE POOL END "
OLD_ROUTE_BEGIN = "# MDCW HISTORICAL LEADER ROUTE BEGIN"
OLD_ROUTE_END = "# MDCW HISTORICAL LEADER ROUTE END"
OLD_BUTTON_BEGIN = "# MDCW HISTORICAL RETIRE REQUEST BEGIN"
OLD_BUTTON_END = "# MDCW HISTORICAL RETIRE REQUEST END"
SYNC_MARKER_BEGIN = "# MDCW HISTORICAL NATIVE COUNTER SYNC BEGIN"
SYNC_MARKER_END = "# MDCW HISTORICAL NATIVE COUNTER SYNC END"
HEADER = '# IMPERIA CW — Cold War: Historical parties, leaders and national identities.\n# Generated by tools/historical_politics_1970/dispatch.py.\n'


def _date(value: str) -> date:
    return date(*map(int, value.split(".")))


def _quote(value: str) -> str:
    if any(c in value for c in "\r\n\x00"):
        raise ValueError(f"Invalid multiline or control-character value: {value!r}")
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def _country_tags(countries) -> set[str]:
    if isinstance(countries, Mapping):
        return set(countries)
    return {c["tag"] if isinstance(c, Mapping) else str(c) for c in countries}


def _validated_people(root: Path, countries, ready_people: list[dict]) -> list[dict]:
    tags = _country_tags(countries)
    people = []
    seen_ids = set()
    for original in ready_people:
        p = dict(original)
        tag = p["tag"]
        if tag in SPECIAL:
            continue
        if tag not in tags or not re.fullmatch(r"[A-Z0-9]{3}", tag):
            raise ValueError(f"Unknown or invalid country tag for {p.get('id')}: {tag!r}")
        if not re.fullmatch(r"[a-z0-9_]+", p["id"]):
            raise ValueError(f"Invalid leader id: {p['id']!r}")
        index = int(p["party_index"])
        if not 0 <= index < len(IDEOLOGIES):
            raise ValueError(f"Invalid MD party index for {tag}/{p['id']}")
        if _date(p["available_from"]) >= _date(p["available_until"]):
            raise ValueError(f"Invalid historical ordering date for {tag}/{p['id']}")
        portrait = p.get("portrait")
        if not isinstance(portrait, str) or not portrait:
            raise ValueError(f"Ready leader {tag}/{p['id']} has no approved portrait")
        portrait_path = Path(portrait.replace("\\", "/"))
        if portrait_path.is_absolute() or ".." in portrait_path.parts or not (root / portrait_path).is_file():
            raise ValueError(f"Missing or unsafe approved portrait for {tag}/{p['id']}: {portrait}")
        key = (tag, p["id"])
        if key in seen_ids:
            raise ValueError(f"Duplicate ready leader: {tag}/{p['id']}")
        seen_ids.add(key)
        p["party_index"] = index
        p["portrait"] = portrait_path.as_posix()
        people.append(p)

    # Period-split canonical records can yield the same person more than once
    # in the same MD family. A native pool should offer that person only once.
    deduped = {}
    for p in sorted(people, key=lambda r: (_date(r["available_from"]), r["tag"], r["party_index"], r["id"])):
        key = (p["tag"], p["party_index"], p["name"].casefold())
        deduped.setdefault(key, p)
    return sorted(deduped.values(), key=lambda r: (r["tag"], r["party_index"], _date(r["available_from"]), r["id"]))


def _find_block_end(text: str, open_brace: int) -> int:
    depth = 0
    quoted = escaped = comment = False
    for i in range(open_brace, len(text)):
        c = text[i]
        if comment:
            if c == "\n":
                comment = False
            continue
        if quoted:
            if escaped:
                escaped = False
            elif c == "\\":
                escaped = True
            elif c == '"':
                quoted = False
            continue
        if c == "#":
            comment = True
        elif c == '"':
            quoted = True
        elif c == "{":
            depth += 1
        elif c == "}":
            depth -= 1
            if depth == 0:
                return i + 1
    raise ValueError("Unclosed HOI4 script block")


def _normalized_person_name(value: str) -> str:
    return "".join(
        char for char in unicodedata.normalize("NFKD", value).casefold()
        if char.isalnum()
    )


def _history_starting_name(root: Path, tag: str) -> str | None:
    """Read a single 1970.1.1 history starter name for conservative aliases."""
    files = list((root / "history/countries").glob(f"{tag} - *.txt"))
    if len(files) != 1:
        return None
    text = files[0].read_text(encoding="utf-8-sig")
    date_block = re.search(r"(?m)^\s*1970\.1\.1\s*=\s*\{", text)
    if not date_block:
        return None
    open_brace = text.find("{", date_block.start(), date_block.end())
    end = _find_block_end(text, open_brace)
    body = text[open_brace + 1:end - 1]
    names = []
    for declaration in re.finditer(r"\bcreate_country_leader\s*=\s*\{", body):
        leader_open = body.find("{", declaration.start(), declaration.end())
        leader_end = _find_block_end(body, leader_open)
        name = re.search(r"\bname\s*=\s*\"([^\"]+)\"", body[leader_open + 1:leader_end - 1])
        if name:
            names.append(name.group(1))
    unique_names = sorted(set(names), key=str.casefold)
    return unique_names[0] if len(unique_names) == 1 else None


def _starter_name_aliases(root: Path, grouped: dict[tuple[str, int], list[dict]]) -> dict[tuple[str, int, str], str]:
    """Map a canonical pool person to a uniquely matching 1970 history name."""
    by_tag: dict[str, list[tuple[int, dict]]] = defaultdict(list)
    for (tag, index), rows in grouped.items():
        by_tag[tag].extend((index, row) for row in rows)
    aliases = {}
    for tag, candidates in by_tag.items():
        starter = _history_starting_name(root, tag)
        if not starter:
            continue
        normalized = _normalized_person_name(starter)
        matches = [
            (index, row) for index, row in candidates
            if _normalized_person_name(row["name"]) == normalized
        ]
        unique_matches = {(index, row["id"], row["name"].casefold()) for index, row in matches}
        if len(unique_matches) != 1:
            continue
        index, row = matches[0]
        if starter != row["name"]:
            aliases[(tag, index, row["name"])] = starter
    return aliases


def _strip_marked(text: str, begin: str, end: str) -> str:
    pattern = re.compile(r"(?ms)^[ \t]*" + re.escape(begin) + r"[^\n]*\n.*?^[ \t]*" + re.escape(end) + r"[^\n]*\n?")
    return pattern.sub("", text)


def _restore_setter(text: str, tag: str) -> str:
    begin = SETTER_MARKER_BEGIN + tag + " BEGIN"
    end = SETTER_MARKER_END + tag
    start = text.find(begin)
    if start < 0:
        return text
    finish = text.find(end, start)
    if finish < 0:
        raise ValueError(f"Unclosed native pool wrapper for {tag}")
    wrapper = text[start:finish]
    else_match = re.search(r"\belse\s*=\s*\{", wrapper)
    if else_match:
        open_brace = wrapper.find("{", else_match.start(), else_match.end())
        block_end = _find_block_end(wrapper, open_brace)
        original_body = wrapper[open_brace + 1:block_end - 1]
        # The wrapper is assembled with line separators around the preserved
        # body. Drop those two separators (and only those) when unwrapping.
        if not original_body.startswith("\n") or not original_body.endswith("\n"):
            raise ValueError(f"Malformed native pool fallback wrapper for {tag}")
        original_body = original_body[1:-1]
    else:
        # This is one of our synthetic setters, which intentionally has no
        # native fallback. Remove the whole generated effect so it is rebuilt
        # from its canonical template on each pass.
        declaration = re.search(r"(?m)^\s*set_leader_" + re.escape(tag) + r"\s*=\s*\{", text)
        if not declaration:
            raise ValueError(f"Could not locate synthetic setter declaration for {tag}")
        open_brace = text.find("{", declaration.start(), declaration.end())
        block_end = _find_block_end(text, open_brace)
        return text[:declaration.start()] + text[block_end:]
    # The wrapper adds one newline immediately before its begin marker. Remove
    # that exact byte too, then restore the captured native body unchanged.
    line_start = text.rfind("\n", 0, start) + 1
    restore_start = line_start - 1 if line_start > 0 and text[line_start - 1] == "\n" else line_start
    suffix = text[finish + len(end):]
    # New wrappers separate the comment marker from the original brace.
    # Old wrappers put that brace on the marker line. Accept both layouts.
    if suffix.startswith("\n"):
        suffix = suffix[1:]
    return text[:restore_start] + original_body + suffix


def _native_counter(path: Path, ideology: str) -> str:
    if path.exists():
        text = path.read_text(encoding="utf-8-sig")
        candidates = re.findall(r"\b([A-Za-z][A-Za-z0-9_]*_leader)\s*=\s*\d+", text)
        matches = sorted({name for name in candidates if name.casefold() == (ideology + "_leader").casefold()})
        if len(matches) == 1:
            return matches[0]
        if len(matches) > 1:
            exact = [name for name in matches if name == ideology + "_leader"]
            if len(exact) == 1:
                return exact[0]
            raise ValueError(f"Ambiguous native counter names in {path.name}: {matches}")
    return ideology + "_leader"


def _counter_set(counter: str, selected: int, next_slot: int, pool_size: int) -> str:
    """Keep MD's do_not_retire rollback: protected leaders repeat on the next call."""
    return "\n".join([
        "if = {",
        "\tlimit = { has_country_flag = do_not_retire }",
        f"\tset_variable = {{ {counter} = {selected} }}",
        "}",
        "else = {",
        f"\tset_variable = {{ {counter} = {next_slot % pool_size} }}",
        "}",
    ])


def _candidate_effect(tag: str, index: int, counter: str, rows: list[dict]) -> str:
    def traits_text(person: dict) -> str:
        traits = person.get("traits", [])
        if not isinstance(traits, list) or any(
            not isinstance(trait, str) or not re.fullmatch(r"[A-Za-z][A-Za-z0-9_]*", trait)
            for trait in traits
        ):
            raise ValueError(f"Invalid explicit leader traits for {tag}/{person['id']}")
        return "traits = { " + (" ".join(dict.fromkeys(traits)) + " " if traits else "") + "}"

    rows = sorted(rows, key=lambda r: (_date(r["available_from"]), r["id"]))
    lines = [f"MDCW_HP_native_pool_{tag}_{index} = {{"]
    for slot, p in enumerate(rows):
        kind = "if" if slot == 0 else "else_if"
        lines.extend([
            f"\t{kind} = {{",
            f"\t\tlimit = {{ check_variable = {{ {counter} = {slot} }} }}",
            "\t\thidden_effect = { kill_country_leader = yes }",
            "\t\tcreate_country_leader = {",
            f"\t\t\tname = {_quote(p['name'])}",
            f"\t\t\tpicture = {_quote(p['portrait'])}",
            f"\t\t\tideology = {IDEOLOGIES[index]}",
            "\t\t\t" + traits_text(p),
            "\t\t}",
            "\t\t" + _counter_set(counter, slot, slot + 1, len(rows)).replace("\n", "\n\t\t"),
            "\t\tset_correct_ideology_trait = yes",
            "\t}",
        ])
    # Corrupt/out-of-range counters still select the beginning of the reviewed
    # historical pool instead of falling through to MD's modern candidates.
    first = rows[0]
    lines.extend([
        "\telse = {",
        "\t\thidden_effect = { kill_country_leader = yes }",
        "\t\tcreate_country_leader = {",
        f"\t\t\tname = {_quote(first['name'])}",
        f"\t\t\tpicture = {_quote(first['portrait'])}",
        f"\t\t\tideology = {IDEOLOGIES[index]}",
        "\t\t\t" + traits_text(first),
        "\t\t}",
        "\t\t" + _counter_set(counter, 0, 1, len(rows)).replace("\n", "\n\t\t"),
        "\t\tset_correct_ideology_trait = yes",
        "\t}",
        "}",
    ])
    return "\n".join(lines)


def _pool_text(root: Path, grouped: dict[tuple[str, int], list[dict]]) -> tuple[str, str]:
    helpers = []
    triggers = []
    sync_rows = []
    starter_aliases = _starter_name_aliases(root, grouped)
    for (tag, index), rows in sorted(grouped.items()):
        path = root / f"common/scripted_effects/{tag}_political_leaders.txt"
        counter = _native_counter(path, IDEOLOGIES[index])
        helpers.append(_candidate_effect(tag, index, counter, rows))
        triggers.append(f"AND = {{ original_tag = {tag} check_variable = {{ ruling_party = {index} }} }}")
        sync_branches = []
        for slot, p in enumerate(sorted(rows, key=lambda r: (_date(r["available_from"]), r["id"]))):
            next_slot = (slot + 1) % len(rows)
            names = [p["name"]]
            alias = starter_aliases.get((tag, index, p["name"]))
            if alias and alias != p["name"]:
                names.append(alias)
            leader_matches = " ".join(
                f"has_country_leader = {{ name = {_quote(name)} ruling_only = yes }}"
                for name in names
            )
            match_condition = leader_matches if len(names) == 1 else f"OR = {{ {leader_matches} }}"
            sync_branches.append("\n".join([
                "\t\t\t" + ("if" if slot == 0 else "else_if") + " = {",
                f"\t\t\t\tlimit = {{ {match_condition} }}",
                "\t\t\t\tif = {",
                "\t\t\t\t\tlimit = { has_country_flag = do_not_retire }",
                f"\t\t\t\t\tset_variable = {{ {counter} = {slot} }}",
                "\t\t\t\t}",
                "\t\t\t\telse = {",
                f"\t\t\t\t\tset_variable = {{ {counter} = {next_slot} }}",
                "\t\t\t\t}",
                "\t\t\t}",
            ]))
        sync_rows.append("\n".join([
            "\tif = {",
            f"\t\tlimit = {{ original_tag = {tag} check_variable = {{ ruling_party = {index} }} }}",
            *sync_branches,
            "\t}",
        ]))

    trigger = "\n".join([
        HEADER.rstrip(),
        f"{POOL_TRIGGER} = {{",
        "\tIMP_is_1970_scenario = yes",
        "\thas_variable = ruling_party",
        "\tOR = {",
        *["\t\t" + row for row in triggers],
        "\t}",
        "}",
    ]) + "\n"
    effect = "\n".join([
        HEADER.rstrip(),
        POOL_MARKER_BEGIN,
        *helpers,
        f"{SYNC_EFFECT} = {{",
        "\tif = {",
        f"\t\tlimit = {{ IMP_is_1970_scenario = yes {POOL_TRIGGER} = yes }}",
        *sync_rows,
        "\t}",
        "}",
        POOL_MARKER_END,
    ]) + "\n"
    return effect, trigger


def _wrap_native_setter(root: Path, tag: str, families: dict[int, list[dict]]) -> str:
    path = root / f"common/scripted_effects/{tag}_political_leaders.txt"
    text = path.read_text(encoding="utf-8-sig") if path.exists() else ""
    text = _restore_setter(text, tag)
    declaration = f"set_leader_{tag} = {{"
    match = re.search(r"(?m)^\s*" + re.escape(declaration), text)
    begin = SETTER_MARKER_BEGIN + tag + " BEGIN"
    end = SETTER_MARKER_END + tag
    branch_lines = []
    for position, index in enumerate(sorted(families)):
        branch_lines.extend([
            ("if" if position == 0 else "else_if") + " = {",
            f"\tlimit = {{ IMP_is_1970_scenario = yes check_variable = {{ ruling_party = {index} }} }}",
            f"\tMDCW_HP_native_pool_{tag}_{index} = yes",
            "}",
        ])
    if not match:
        return "\n".join([
            HEADER.rstrip(),
            declaration,
            f"\t{begin}",
            *["\t" + line for line in branch_lines],
            f"\t{end}",
            "}",
            "",
        ])

    open_brace = text.find("{", match.start(), match.end())
    close = _find_block_end(text, open_brace)
    body = text[open_brace + 1:close - 1]
    wrapper = "\n".join([
        begin + '\n# IMPERIA CW — Cold War: Historical national leader selection.',
        *branch_lines,
        "else = {",
        body,
        "}",
        end,
    ])
    # Keep the original closing brace off the END marker's comment line.
    wrapped = text[:open_brace + 1] + "\n" + wrapper + "\n" + text[close - 1:]
    return wrapped


def _central_hook(root: Path, has_pools: bool) -> str:
    path = root / "common/scripted_effects/00_leader_setup_scripted_effects.txt"
    text = path.read_text(encoding="utf-8-sig")
    old_route = re.compile(r"(?ms)^[ \t]*# MDCW HISTORICAL LEADER ROUTE BEGIN\n.*?^[ \t]*# MDCW HISTORICAL LEADER ROUTE END\n?")
    text = old_route.sub("", text)
    sync_block = re.compile(r"(?ms)^[ \t]*" + re.escape(SYNC_MARKER_BEGIN) + r"\n.*?^[ \t]*" + re.escape(SYNC_MARKER_END) + r"\n?")
    text = sync_block.sub("", text)
    text = re.sub(r"(?m)^([ \t]*)MDCW_HP_sync_native_counter\s*=\s*yes\s*\n", "", text)
    setter = re.search(r"(?m)^set_leader\s*=\s*\{", text)
    if not setter:
        raise ValueError("Could not locate central set_leader effect")
    open_brace = text.find("{", setter.start(), setter.end())
    sync_call = "\n\t" + SYNC_MARKER_BEGIN + "\n\t# IMPERIA CW — Cold War: Synchronise historical leader selection.\n\tMDCW_HP_sync_native_counter = yes\n\t" + SYNC_MARKER_END
    text = text[:open_brace + 1] + sync_call + text[open_brace + 1:]
    if has_pools:
        old = re.compile(
            r"NOT\s*=\s*\{\s*AND\s*=\s*\{\s*OR\s*=\s*\{\s*original_tag\s*=\s*DDR\s+original_tag\s*=\s*PAK\s*\}\s*IMP_is_1970_scenario\s*=\s*yes\s*\}\s*\}"
        )
        new = "NOT = { AND = { OR = { original_tag = DDR original_tag = PAK } IMP_is_1970_scenario = yes NOT = { MDCW_HP_has_native_pool = yes } } }"
        text, count = old.subn(new, text)
        updated = re.compile(
            r"NOT\s*=\s*\{\s*AND\s*=\s*\{\s*OR\s*=\s*\{\s*original_tag\s*=\s*DDR\s+original_tag\s*=\s*PAK\s*\}\s*IMP_is_1970_scenario\s*=\s*yes\s*NOT\s*=\s*\{\s*MDCW_HP_has_native_pool\s*=\s*yes\s*\}\s*\}\s*\}"
        )
        updated_count = len(updated.findall(text))
        if count > 1 or updated_count != 1:
            raise ValueError(f"Expected one DDR/PAK native setup guard, found old={count} updated={updated_count}")
    return text


def _restore_retire_button(root: Path) -> str:
    path = root / "common/scripted_guis/00_MD_politicsview_scripted_guis.txt"
    text = path.read_text(encoding="utf-8-sig")
    pattern = re.compile(r"(?ms)^[ \t]*" + re.escape(OLD_BUTTON_BEGIN) + r"\n.*?^[ \t]*" + re.escape(OLD_BUTTON_END) + r"\n?")

    def restore(match: re.Match) -> str:
        setter = re.search(r"(?m)^([ \t]*)set_leader = yes\s*$", match.group(0))
        if not setter:
            raise ValueError("Historical retire wrapper lost its set_leader call")
        return setter.group(1) + "set_leader = yes\n"

    text, count = pattern.subn(restore, text)
    if count > 1:
        raise ValueError("Expected at most one old historical retire wrapper")
    return text


def generate_dispatch(root, countries, ready_people: list[dict]) -> dict[str, str]:
    """Return 1970-only native-pool helpers and idempotent per-country patches."""
    root = Path(root)
    people = _validated_people(root, countries, ready_people)
    grouped: dict[tuple[str, int], list[dict]] = defaultdict(list)
    by_tag: dict[str, dict[int, list[dict]]] = defaultdict(lambda: defaultdict(list))
    for person in people:
        grouped[(person["tag"], person["party_index"])].append(person)
        by_tag[person["tag"]][person["party_index"]].append(person)
    if not grouped:
        return {}

    effect, trigger = _pool_text(root, grouped)
    outputs = {POOL_FILE: effect, POOL_TRIGGER_FILE: trigger}
    for tag, families in sorted(by_tag.items()):
        outputs[f"common/scripted_effects/{tag}_political_leaders.txt"] = _wrap_native_setter(root, tag, families)
    outputs["common/scripted_effects/00_leader_setup_scripted_effects.txt"] = _central_hook(root, bool(grouped))
    outputs["common/scripted_guis/00_MD_politicsview_scripted_guis.txt"] = _restore_retire_button(root)
    return outputs
