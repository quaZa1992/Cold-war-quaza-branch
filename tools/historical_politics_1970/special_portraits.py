# IMPERIA CW — Cold War: Historical parties, leaders and national identities.
"""Patch reviewed portraits into existing SPECIAL country-leader entries.

Only ``picture`` fields inside exact, explicitly referenced native leader
functions may change. This helper does not create leaders or alter appointment,
party, popularity, ideology, trait, or government logic.
"""
from __future__ import annotations

import json
import re
from collections import defaultdict
from collections.abc import Mapping
from pathlib import Path


HEADER = '# IMPERIA CW — Cold War: Historical parties, leaders and national identities.\n# Generated by tools/historical_politics_1970/special_portraits.py.\n'
REVIEWED_STATUSES = {
    "visually_reviewed", "edited_visually_reviewed",
    "original_historical_user_approved", "reviewed", "approved",
    "existing_exact_name_md_reference",
}
EXACT_NAME_PROVENANCE = "existing exact-name MD reference"


class GeneratedFiles(dict):
    """Generated source text plus non-installable diagnostics for the caller."""

    def __init__(self, *args, pending=None, **kwargs):
        super().__init__(*args, **kwargs)
        self.pending = list(pending or [])


def _brace_end(text: str, open_brace: int, upper: int | None = None) -> int:
    """Return the index after a balanced block, skipping comments and strings."""
    depth = 0
    quoted = False
    escaped = False
    comment = False
    stop = len(text) if upper is None else upper
    for i in range(open_brace, stop):
        char = text[i]
        if comment:
            if char == "\n":
                comment = False
            continue
        if quoted:
            if escaped:
                escaped = False
            elif char == "\\":
                escaped = True
            elif char == '"':
                quoted = False
            continue
        if char == "#":
            comment = True
        elif char == '"':
            quoted = True
        elif char == "{":
            depth += 1
        elif char == "}":
            depth -= 1
            if depth == 0:
                return i + 1
    raise ValueError("Unbalanced HOI4 brace block")


def _assignments(text: str, key: str, lower: int = 0, upper: int | None = None):
    """Yield (assignment start, opening brace, end) for lexical block keys."""
    stop = len(text) if upper is None else upper
    i = lower
    quoted = False
    escaped = False
    comment = False
    while i < stop:
        char = text[i]
        if comment:
            if char == "\n":
                comment = False
            i += 1
            continue
        if quoted:
            if escaped:
                escaped = False
            elif char == "\\":
                escaped = True
            elif char == '"':
                quoted = False
            i += 1
            continue
        if char == "#":
            comment = True
            i += 1
            continue
        if char == '"':
            quoted = True
            i += 1
            continue
        if text.startswith(key, i):
            before_ok = i == lower or not (text[i - 1].isalnum() or text[i - 1] == "_")
            after = i + len(key)
            after_ok = after >= stop or not (text[after].isalnum() or text[after] == "_")
            if before_ok and after_ok:
                j = after
                while j < stop and text[j].isspace():
                    j += 1
                if j < stop and text[j] == "=":
                    j += 1
                    while j < stop and text[j].isspace():
                        j += 1
                    if j < stop and text[j] == "{":
                        end = _brace_end(text, j, stop)
                        yield i, j, end
                        i = end
                        continue
        i += 1


def _unquote(value: str) -> str:
    return value.replace('\\"', '"').replace("\\\\", "\\")


def _quoted_assignments(block: str, key: str):
    pattern = re.compile(r"(?<![A-Za-z0-9_])" + re.escape(key) + r"\s*=\s*\"((?:\\.|[^\"\\])*)\"")
    for match in pattern.finditer(block):
        line_start = block.rfind("\n", 0, match.start()) + 1
        if "#" in block[line_start:match.start()]:
            continue
        yield match, _unquote(match.group(1))


def _flatten_entries(entries) -> list[dict]:
    if isinstance(entries, Mapping):
        if "countries" in entries:
            countries = entries["countries"]
            rows = []
            for country in countries:
                for person in country.get("leaders", []):
                    rows.append({"tag": country.get("tag"), **person})
            return rows
        if "leaders" in entries and "tag" in entries:
            return [{"tag": entries["tag"], **person} for person in entries["leaders"]]
        rows = []
        for key, value in entries.items():
            if isinstance(value, Mapping) and "leaders" in value:
                rows.extend({"tag": value.get("tag", key), **person} for person in value["leaders"])
            elif isinstance(value, Mapping):
                rows.append(dict(value, tag=value.get("tag", key)))
        return rows
    rows = []
    for value in entries:
        if "leaders" in value and "tag" in value:
            rows.extend({"tag": value["tag"], **person} for person in value["leaders"])
        else:
            rows.append(dict(value))
    return rows


def _manifest_value(manifest, tag: str, ident: str):
    if not isinstance(manifest, Mapping):
        return None
    key = f"{tag}_{ident}"
    candidates = [manifest.get(key)]
    for field in ("portraits", "key_map", "portrait_map"):
        nested = manifest.get(field)
        if isinstance(nested, Mapping):
            candidates.append(nested.get(key))
    for value in candidates:
        if isinstance(value, Mapping):
            portrait = value.get("portrait") or value.get("path")
            status = value.get("status")
            provenance = value.get("provenance")
            approved_status = status in REVIEWED_STATUSES
            legacy_exact_name_reference = status is None and provenance == EXACT_NAME_PROVENANCE
            if isinstance(portrait, str) and portrait and (approved_status or legacy_exact_name_reference):
                return portrait
    return None


def _portrait_path(root: Path, entry: dict, manifest, pending: list[dict]):
    # Portrait paths in the research catalogue are descriptive only. Every
    # usable assignment must also carry an approved manifest record.
    value = _manifest_value(manifest, entry.get("tag", ""), entry.get("id", ""))
    if not value:
        pending.append({"tag": entry.get("tag"), "id": entry.get("id"), "name": entry.get("name"),
                        "reason": "no reviewed exact-person portrait"})
        return None
    value = str(value).replace("\\", "/")
    path = Path(value)
    if path.is_absolute() or ".." in path.parts or not (root / path).is_file():
        pending.append({"tag": entry.get("tag"), "id": entry.get("id"), "name": entry.get("name"),
                        "portrait": value, "reason": "portrait path missing or outside repository"})
        return None
    return path.as_posix()


def _function_range(text: str, function: str):
    blocks = list(_assignments(text, function))
    if len(blocks) != 1:
        return None, f"expected one native function definition, found {len(blocks)}"
    _, opening, end = blocks[0]
    return (opening + 1, end - 1), None


def _leader_matches(text: str, region: tuple[int, int], name: str):
    lower, upper = region
    results = []
    for _, opening, end in _assignments(text, "create_country_leader", lower, upper):
        block = text[opening + 1:end - 1]
        names = [value for _, value in _quoted_assignments(block, "name")]
        if names == [name]:
            results.append((opening, end, block))
    return results


def _picture_edit(block: str, portrait: str):
    desired = '"' + portrait.replace("\\", "\\\\").replace('"', '\\"') + '"'
    pictures = list(_quoted_assignments(block, "picture"))
    if len(pictures) > 1:
        return None, "multiple picture fields in exact leader block"
    if pictures:
        match, current = pictures[0]
        if current == portrait:
            return None, None
        start, end = match.span(1)
        replacement = desired[1:-1]
        return (start, end, replacement), None

    name_fields = list(_quoted_assignments(block, "name"))
    if len(name_fields) != 1:
        return None, "exact leader block has ambiguous name field"
    name_match = name_fields[0][0]
    line_end = block.find("\n", name_match.end())
    if line_end < 0:
        return (name_match.end(), name_match.end(), " picture = " + desired), None
    tail = block[name_match.end():line_end]
    if tail.strip() and not tail.lstrip().startswith("#"):
        return (name_match.end(), name_match.end(), " picture = " + desired), None
    next_line = line_end + 1
    indent_match = re.match(r"[ \t]*", block[block.rfind("\n", 0, name_match.start()) + 1:name_match.start()])
    indent = indent_match.group(0) if indent_match else ""
    return (next_line, next_line, indent + "picture = " + desired + "\n"), None


def generate_special_portraits(root, entries, manifest=None) -> GeneratedFiles:
    """Return source-file updates for reviewed portrait assignments.

    ``entries`` accepts the research artifact payload or a flattened list.
    ``manifest`` may be the portrait manifest or an explicit ``TAG_id`` key
    map. The returned dict carries a non-installable ``pending`` diagnostic
    list for entries without a reviewed image or a unique native target.
    """
    root = Path(root)
    rows = _flatten_entries(entries)
    pending: list[dict] = []
    source_texts: dict[str, str] = {}
    edits: dict[str, list[tuple[int, int, str]]] = defaultdict(list)
    seen_refs = set()

    for entry in rows:
        tag, ident, name = entry.get("tag"), entry.get("id"), entry.get("name")
        native_name = entry.get("native_name", name)
        if not (tag and ident and name):
            pending.append({"tag": tag, "id": ident, "name": name, "reason": "entry missing tag, id, or exact name"})
            continue
        portrait = _portrait_path(root, entry, manifest, pending)
        refs = entry.get("native_sources") or []
        if isinstance(refs, str):
            refs = [refs]
        if not refs:
            pending.append({"tag": tag, "id": ident, "name": name, "reason": "no scoped native_sources reference"})
            continue
        for ref in refs:
            if not isinstance(ref, str) or "#" not in ref:
                pending.append({"tag": tag, "id": ident, "name": name, "native_source": ref,
                                "reason": "native source must be relative/path.txt#function_name"})
                continue
            source, function = ref.rsplit("#", 1)
            source_path = Path(source.replace("\\", "/"))
            if source_path.is_absolute() or ".." in source_path.parts or not re.fullmatch(r"[A-Za-z0-9_]+", function):
                pending.append({"tag": tag, "id": ident, "name": name, "native_source": ref,
                                "reason": "unsafe or malformed native source reference"})
                continue
            relpath = source_path.as_posix()
            source_file = root / source_path
            if relpath not in source_texts:
                if not source_file.is_file():
                    pending.append({"tag": tag, "id": ident, "name": name, "native_source": ref,
                                    "reason": "native source file missing"})
                    continue
                source_texts[relpath] = source_file.read_text(encoding="utf-8-sig")
            text = source_texts[relpath]
            region, error = _function_range(text, function)
            if error:
                pending.append({"tag": tag, "id": ident, "name": name, "native_source": ref, "reason": error})
                continue
            matches = _leader_matches(text, region, native_name)
            if not matches:
                pending.append({"tag": tag, "id": ident, "name": name, "native_source": ref,
                                "native_name": native_name, "matches": 0,
                                "reason": "no exact name match in scoped function; provide native_name if spelling differs"})
                continue
            if portrait is None:
                continue
            for block_start, block_end, block in matches:
                edit = _picture_edit(block, portrait)
                if edit[1]:
                    pending.append({"tag": tag, "id": ident, "name": name, "native_source": ref, "reason": edit[1]})
                    continue
                if edit[0] is None:
                    continue
                local_start, local_end, replacement = edit[0]
                absolute = (block_start + 1 + local_start, block_start + 1 + local_end, replacement)
                identity = (relpath, absolute[0], absolute[1], replacement)
                if identity not in seen_refs:
                    edits[relpath].append(absolute)
                    seen_refs.add(identity)

    outputs = GeneratedFiles(pending=pending)
    for relpath, changes in edits.items():
        text = source_texts[relpath]
        for start, end, replacement in sorted(changes, reverse=True):
            text = text[:start] + replacement + text[end:]
        outputs[relpath] = text
    return outputs


def load_entries(path: Path):
    """Small convenience for direct CLI/test use; the parent builder may pass parsed JSON."""
    return json.loads(Path(path).read_text(encoding="utf-8-sig"))
