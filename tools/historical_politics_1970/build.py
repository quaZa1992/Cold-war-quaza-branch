def block(key, body):
    return key + ' = {\n' + '\n'.join('\t' + x if x else '' for x in body.splitlines()) + '\n}'


def previous(value):
    d = date(*map(int, value.split('.'))) - timedelta(days=1)
    return f'{d.year}.{d.month}.{d.day}'


def window(start='1970.1.1', end='2001.1.1'):
    return 'date > ' + previous(start) + ('\ndate < ' + end if end else '')


def quote(text):
    assert '\n' not in text and '\r' not in text, text
    return '"' + text.replace('\\', '\\\\').replace('"', '\\"') + '"'


def loc_quote(text):
    # HOI localization uses a single literal \n escape for a rendered newline.
    return '"' + text.replace('\r\n', '\n').replace('\r', '\n').replace('\n', '\\n').replace('"', '\\"') + '"'


def slug(value):
    assert re.fullmatch(r'[a-z0-9_]+', value), value
    return value


def context(tag):
    return f'original_tag = {tag}\nIMP_is_1970_scenario = yes'


def party_periods(parties, index):
    """MD has ideological families, not one extra vote slot per real party.

    Concurrent organizations in the same family must all remain visible. A
    later row must not silently erase an unrelated party sharing its MD slot.
    """
    rows = [p for p in parties if p['index'] == index and not p.get('extra_trigger')]
    first, last = date(1970, 1, 1), date(2001, 1, 1)
    parse = lambda value: date(*map(int, value.split('.')))
    fmt = lambda value: f'{value.year}.{value.month}.{value.day}'
    cuts = {first, last}
    for p in rows:
        cuts.add(max(first, min(last, parse(p.get('from', '1970.1.1')))))
        if p.get('until'):
            cuts.add(max(first, min(last, parse(p['until']))))
    output = []
    cuts = sorted(cuts)
    for start, end in zip(cuts, cuts[1:]):
        active = [p for p in rows if parse(p.get('from', '1970.1.1')) <= start and (not p.get('until') or start < parse(p['until']))]
        if not active:
            continue
        names = list(dict.fromkeys(p['name'] for p in active))
        icons = {p.get('icon_id') for p in active if p.get('icon_id')}
        descriptions = list(dict.fromkeys(p.get('description', '') for p in active if p.get('description')))
        output.append({'index': index, 'name': ' / '.join(names), 'from': fmt(start), 'until': fmt(end),
            'icon_id': next(iter(icons)) if len(icons) == 1 else None,
            'members': active,
            'description': '\\n\\n'.join(descriptions) if descriptions else 'Historical organizations represented together within this MD political family. This display does not change their popularity or merge their organizations.'})
    return output


def load_catalog():
    countries = {}
    for source in sorted((HERE / 'data').glob('*.json')):
        payload = json.loads(source.read_text(encoding='utf-8-sig'))
        for c in payload['countries']:
            tag = c['tag']
            assert tag not in countries, ('duplicate country', tag, source)
            assert re.fullmatch('[A-Z0-9]{3}', tag), tag
            for p in c.get('parties', []):
                assert 0 <= p['index'] < 24 and p['source_urls'], (tag, p)
                date(*map(int, p.get('from', '1970.1.1').split('.')))
            ids = set()
            for person in c.get('leaders', []):
                ident = slug(person['id'])
                assert ident not in ids, (tag, ident)
                ids.add(ident)
                assert person['source_urls'], (tag, ident, 'missing source')
                assert 0 <= person['party_index'] < 24, (tag, ident, 'party index')
                assert date(*map(int, person['available_from'].split('.'))) < date(*map(int, person['available_until'].split('.'))), (tag, ident)
            # Validate segment windows, MD indices, slugs, overlaps, and
            # canonical-person ID collisions before any output is generated.
            expand_country(c)
            countries[tag] = apply_country(c)
    assert countries, 'No reviewed country catalogues'
    return countries


class Builder:
    def __init__(self, countries):
        self.countries = countries
        self.outputs = {}
        self.loc = {}
        text = (ROOT / 'localisation/english/0_political_system_l_english.yml').read_text(encoding='utf-8-sig')
        self.icons = dict(re.findall(r'generic\.([^\s:]+)_icon:\s*"([^"]*)"', text))
        self.asset_manifest = json.loads((HERE / 'portrait_manifest.json').read_text(encoding='utf-8')) if (HERE / 'portrait_manifest.json').exists() else {}
        self.party_icons = json.loads((HERE / 'party_icon_manifest.json').read_text(encoding='utf-8')) if (HERE / 'party_icon_manifest.json').exists() else {}
        self.ready = []
        self.delegated = []
        self.pending = []
        self.special_pending = []
        self._pending_people = set()
        self._ready_people = set()
        self._delegated_people = set()

    def text(self, key, value):
        assert key not in self.loc or self.loc[key] == value, key
        self.loc[key] = value

    def write(self, path, text):
        assert path not in self.outputs, path
        self.outputs[path] = text

    def approved_portrait(self, key):
        """Return a portrait only when the manifest records an approved source."""
        record = self.asset_manifest.get(key)
        if not isinstance(record, dict):
            return None
        status = record.get('status')
        provenance = record.get('provenance')
        approved_status = status in APPROVED_PORTRAIT_STATUSES
        legacy_exact_name_reference = status is None and provenance == EXACT_NAME_PORTRAIT_PROVENANCE
        if not (approved_status or legacy_exact_name_reference):
            return None
        portrait = record.get('portrait') or record.get('path')
        return portrait if isinstance(portrait, str) and portrait else None

    def parties(self):
        presentation = PartyPresentation(self.countries, self.party_icons, self.icons)
        party_countries = dict(self.countries)
        for tag in set(presentation.names) - set(party_countries):
            party_countries[tag] = {'tag': tag, 'parties': []}
        old_path = ROOT / 'common/scripted_localisation/mdcw_historical_parties.txt'
        authored = retained_branches(old_path.read_text(encoding='utf-8-sig')) if old_path.exists() else {}
        definitions = []
        self.write('common/scripted_triggers/mdcw_historical_party_countries.txt', HEADER + block('MDCW_HP_has_country',
            'IMP_is_1970_scenario = yes\ndate < 2001.1.1\n' + block('OR', '\n'.join('original_tag = ' + tag for tag in sorted(party_countries)))) + '\n')
        for index, ideology in enumerate(IDEOLOGIES):
            presentation.family_loc(self, index, ideology)
            rows = []
            for tag, c in sorted(party_countries.items()):
                parties = presentation.parties(tag, c.get('parties', []))
                flagged = [p for p in parties if p['index'] == index and p.get('extra_trigger')]
                choices = party_periods(parties, index) + flagged
                # Later dated names take precedence; simultaneous members are
                # intentionally supplied as one reviewed political-family label.
                for n, p in reversed(list(enumerate(choices))):
                    k = f'MDCW_HP_{tag}_party_{index}_{n}'
                    label, icon = presentation.render(tag, ideology, p)
                    self.text(k, label)
                    self.text(k + '_desc', presentation.description(index, p.get('description', '')))
                    self.text(k + '_icon', icon)
                    tests = context(tag) + '\n' + window(p.get('from', '1970.1.1'), p.get('until'))
                    if p.get('extra_trigger'):
                        tests += '\n' + p['extra_trigger']
                    rows.append((tests, k))
                # Every country has a named local current even between dated
                # parties. The final global fallback is never used by these
                # countries while the historical registry is active.
                k = f'MDCW_HP_{tag}_current_{index}'
                self.text(k, self.icons[ideology] + ' ' + presentation.names[tag]['labels'][index])
                self.text(k + '_desc', presentation.description(index) + '\\n\\nAn alternative political current; this name does not imply that a separate registered party existed in 1970.')
                self.text(k + '_icon', self.icons[ideology])
                rows.append((context(tag), k))
            for suffix in ('', '_desc', '_icon'):
                name = f'MDCW_HP_{ideology}{suffix}'
                texts = [block('text', block('trigger', tests) + '\nlocalization_key = ' + key + suffix) for tests, key in rows]
                fallback = f'MDCW_HP_generic_{index}{suffix}'
                family = presentation.reference['families'][ideology]
                value = self.icons[ideology] if suffix == '_icon' else (presentation.description(index) if suffix == '_desc' else self.icons[ideology] + ' ' + family['name'])
                self.text(fallback, value)
                texts.append(block('text', 'localization_key = ' + fallback))
                definitions.append(block('defined_text', 'name = ' + name + '\n' + '\n'.join(texts)))
        ruling = []
        for index, ideology in enumerate(IDEOLOGIES):
            ruling.append(block('text', block('trigger', f'has_variable = ruling_party\ncheck_variable = {{ ruling_party = {index} }}') + f'\nlocalization_key = "[{ideology}_L]"'))
        ruling.append(block('text', 'localization_key = MDCW_HP_generic_0'))
        definitions.append(block('defined_text', 'name = MDCW_HP_ruling_party\n' + '\n'.join(ruling)))
        registry = restore_branches(HEADER + '\n\n'.join(definitions) + '\n', authored)
        self.write('common/scripted_localisation/mdcw_historical_parties.txt', registry)
        source = (ROOT / 'common/scripted_localisation/00_MD_politicsview_scripted_localisation.txt').read_text(encoding='utf-8-sig')
        source = hook_native(source, IDEOLOGIES, MARKER)
        source, regional_files = presentation.bespoke(source, IDEOLOGIES, registry)
        for path, text in regional_files.items():
            self.write(path, text)
        self.write('common/scripted_localisation/00_MD_politicsview_scripted_localisation.txt', source)

    def leaders(self):
        for tag, c in sorted(self.countries.items()):
            for person in expand_country(c):
                canonical_id = person['catalogue_id']
                portrait_key = person['portrait_key']
                portrait = self.approved_portrait(portrait_key)
                if not portrait or not (ROOT / portrait).is_file():
                    pending_key = (tag, canonical_id)
                    if pending_key not in self._pending_people:
                        self.pending.append({'tag': tag, 'id': canonical_id, 'name': person['name'], 'reason': 'portrait not reviewed/installed'})
                        self._pending_people.add(pending_key)
                    continue
                if person.get('managed_by_existing_system') or tag in SPECIAL:
                    self.delegated.append({'tag': tag, **person, 'portrait': portrait, 'appointment': 'native country provider requires separate verification'})
                    self._delegated_people.add((tag, canonical_id))
                    continue
                self.ready.append({'tag': tag, **person, 'portrait': portrait, 'appointment': 'native_party_pool'})
                self._ready_people.add((tag, canonical_id))

    def build(self):
        # COLDWAR | Party names, descriptions, icons and the MDCW_HP registry are now owned by
        # tools/party_registry_1970/generate.py (curated data per country). Do not regenerate
        # them here, otherwise the curated 1970 parties are overwritten with generic labels.
        if not (ROOT / 'tools/party_registry_1970/generate.py').exists():
            self.parties()
        self.leaders()
        sprites = []
        for ident, row in sorted(self.party_icons.items()):
            if row.get('binding', {}).get('install_action') == 'add_staged':
                texture = row['texture_path']
                assert (ROOT / texture).is_file(), texture
                sprites.append(f'\tspriteType = {{ name = "GFX_{ident}" texturefile = "{texture}" legacy_lazy_load = no }}')
        self.write('interface/mdcw_historical_parties.gfx', HEADER + 'spriteTypes = {\n' + '\n'.join(sprites) + '\n}\n')
        for path, value in generate_dispatch(ROOT, self.countries, self.ready).items():
            self.write(path, value)
        special_source = HERE / 'special_portraits.json'
        if special_source.exists():
            patches = generate_special_portraits(ROOT, json.loads(special_source.read_text(encoding='utf-8')), self.asset_manifest)
            self.special_pending = patches.pending
            for path, value in patches.items():
                self.write(path, value)
        special = generate_special_successors(ROOT, self.countries, self.asset_manifest)
        for path, value in special.items():
            self.write(path, value)
        sov_egy = generate_sov_egy_successors(ROOT, self.countries, self.asset_manifest, source_texts=self.outputs)
        for path, value in sov_egy.items():
            # Compose pending-vote cleanup with exact portrait replacements.
            # All other specialist paths must be new to this builder.
            if path in self.outputs:
                assert path == 'common/scripted_effects/COLDWAR_SOV_1970_scripted_effects.txt', path
                self.outputs[path] = value
            else:
                self.write(path, value)
        yeltsin_available = 'MDCW_HP_set_sov_yeltsin' in sov_egy.get('common/scripted_effects/mdcw_historical_sov_egy_successors.txt', '')
        self.write('common/scripted_triggers/mdcw_historical_retirement_alternatives.txt',
                   alternative_trigger(ROOT, self.ready, special.report, yeltsin_available))
        self.text('MDCW_HP_retirement_no_alternative_tt', 'Another historical party leader is available.')
        wire_retirement(self.outputs)
        self.write('localisation/english/mdcw_historical_politics_1970_l_english.yml', '\ufeffl_english:\n# IMPERIA CW — Cold War: historical politics 1970 English localisation.\n' + '\n'.join(' ' + key + ':0 ' + loc_quote(value) for key, value in self.loc.items()) + '\n')
        catalogue_records = [
            (tag, person)
            for tag, country in self.countries.items()
            for person in country.get('leaders', [])
        ]
        return {
            'countries': len(self.countries),
            'named_parties': sum(len(x.get('parties', [])) for x in self.countries.values()),
            'catalogue_person_records': len(catalogue_records),
            'catalogue_people': len({(tag, str(person.get('name', '')).casefold()) for tag, person in catalogue_records}),
            'catalogue_candidate_periods': sum(len(expand_country(c)) for c in self.countries.values()),
            'ready_leaders': len(self.ready),
            'ready_candidate_periods': len(self.ready),
            'ready_catalogue_records': len(self._ready_people),
            'ready_unique_people': len({(row['tag'], str(row.get('name', '')).casefold()) for row in self.ready}),
            'delegated_references': len(self._delegated_people),
            'delegated_candidate_periods': len(self.delegated),
            'delegated_catalogue_records': len(self._delegated_people),
            'delegated_unique_people': len({(row['tag'], str(row.get('name', '')).casefold()) for row in self.delegated}),
            'pending_unique_people': len(self.pending),
            'pending_catalogue_records': len(self.pending),
            'pending_leaders': self.pending,
            'pending_native_portraits': self.special_pending,
            'special_successors': special.report,
            'sov_egy_successors': getattr(sov_egy, 'integration_report', {}),
            'files': {p: hashlib.sha256(t.encode()).hexdigest() for p, t in self.outputs.items()},
        }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, required=True)
    parser.add_argument('--install', action='store_true')
    args = parser.parse_args()
    if args.install:
        # Use the same current-input checks and recoverable writes as the
        # dedicated installer; never install an unvalidated build directly.
        from install_runtime import run
        print(json.dumps(run(args.output, True), ensure_ascii=False))
        return
    builder = Builder(load_catalog())
    report = builder.build()
    destination = args.output / 'staged'
    for name, value in builder.outputs.items():
        f = destination / name
        f.parent.mkdir(parents=True, exist_ok=True)
        f.write_text(value, encoding='utf-8', newline='\n')
    args.output.mkdir(parents=True, exist_ok=True)
    (args.output / 'build_report.json').write_text(json.dumps(report, indent=2, ensure_ascii=False), encoding='utf-8')
    print(json.dumps({k: v for k, v in report.items() if k not in {'files', 'pending_leaders', 'pending_native_portraits'}}, ensure_ascii=False))
    print('Pending portraits:', len(report['pending_leaders']))
    print('Pending native portraits:', len(report['pending_native_portraits']))


if __name__ == '__main__':
    main()
