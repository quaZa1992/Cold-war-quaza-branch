# IMPERIA CW — Cold War: Historical party registry.
"""COLDWAR | Generate the 1970 party registry (names, descriptions, icons) from curated data.

Input : tools/party_registry_1970/data/<TAG>.json   (one file per country, 24 MD slots)
        tools/party_registry_1970/logo_icons.json   (optional: TAG|slot|period -> sprite)
Output: common/scripted_localisation/mdcw_historical_parties.txt
        localisation/english/mdcw_1970_party_registry_l_english.yml
        localisation/english/mdcw_historical_politics_1970_l_english.yml (leader key only)

Display rules follow Millennium Dawn:
  name  = "£icon (ABBR) - English name"  (real organizations)
          "£icon Native label"            (catchy factions, catchy = true)
  desc  = "(Ideology) - English name (Language: Native name, ABBR)\\n\\nText"

Usage: python3 generate.py --root <mod root> [--out <dir>]
"""
from __future__ import annotations

import argparse
import json
import re
from datetime import date, timedelta
from pathlib import Path

HERE = Path(__file__).resolve().parent
IDEOLOGIES = ['Western_Autocracy', 'conservatism', 'liberalism', 'socialism',
    'communist_state', 'anarchist_communism', 'Conservative', 'Autocracy',
    'Mod_Vilayat_e_Faqih', 'Vilayat_e_Faqih', 'Kingdom', 'Caliphate',
    'Neutral_Muslim_Brotherhood', 'Neutral_Autocracy', 'Neutral_conservatism',
    'oligarchism', 'Neutral_Libertarian', 'Neutral_green', 'neutral_Social',
    'Neutral_Communism', 'Nat_Populism', 'Nat_Fascism', 'Nat_Autocracy', 'Monarchist']
FAMILY = ['Pro-Western Autocrats', 'Conservatives', 'Liberals', 'Social Democrats',
    'Communists', 'Left-Wing Radicals', 'Reactionaries', 'Autocrats',
    'Moderate Shiite Revolutionaries', 'Hardline Shiite Revolutionaries',
    'Pro-Establishment Salafism', 'Salafi Jihadism', 'Moderate Islamists',
    'Non-Aligned Autocrats', 'Non-Aligned Conservatives', 'Oligarchs', 'Libertarians',
    'Greens', 'Socialist Democrats', 'Non-Aligned Communists', 'Right-Wing Populists',
    'Fascists', 'Military Junta', 'Monarchists']
HEADER = '# IMPERIA CW — Cold War: Historical party registry.\n# COLDWAR | Generated by tools/party_registry_1970/generate.py - edit data/<TAG>.json, not this file.\n'
# Slots authored by regional builders whose own entries are flag-gated: the
# registry falls back to the same authored key so nothing generic can appear.
AUTHORED_FALLBACK = {
    'SPR': {1: 'COLDWAR_SPR_registry_reformists', 2: 'COLDWAR_SPR_registry_liberal',
            3: 'COLDWAR_SPR_registry_psoe', 4: 'COLDWAR_SPR_registry_pce',
            21: 'COLDWAR_SPR_registry_movimiento', 22: 'COLDWAR_SPR_registry_armed_forces',
            23: 'COLDWAR_SPR_registry_crown'},
    'LBA': {7: 'LBA_1970.Autocracy_rcc'},
    'IRQ': {n: f'COLDWAR_IRQ_party_{n}' for n in (2, 3, 4, 6, 8, 9, 12, 18, 19, 21, 22, 23)},
}
ALLOWED = set('–—―‘’‚“”„')


def char_ok(ch):
    o = ord(ch)
    return (32 <= o < 127) or (0xA0 <= o <= 0x17F) or ch in ALLOWED


def block(key, body):
    return key + ' = {\n' + '\n'.join('\t' + x if x else '' for x in body.splitlines()) + '\n}'


def day_before(value):
    d = date(*map(int, value.split('.'))) - timedelta(days=1)
    return f'{d.year}.{d.month}.{d.day}'


def loc_value(text):
    text = text.replace('\r\n', '\n').replace('\n', '\\n').replace('"', "'")
    bad = {c for c in text if not char_ok(c) and c not in '£§'}
    assert not bad, (text[:80], bad)
    return '"' + text + '"'


def display_name(p):
    if p.get('catchy'):
        return p['name']
    return f"({p['abbr']}) - {p['english']}" if p.get('abbr') else p['english']


def description(p):
    parts = []
    native = p.get('native_full') or (p['name'] if p.get('catchy') else None)
    if p.get('language') and native and native.casefold() != p['english'].casefold():
        parts.append(f"{p['language']}: {native}")
    if p.get('abbr') and not p['english'].endswith(f"({p['abbr']})"):
        parts.append(p['abbr'])
    head = f"({p['ideology']}) - {p['english']}" + (f" ({', '.join(parts)})" if parts else '')
    return head + '\n\n' + p['text'].strip()


def retained_branches(source):
    """Hand-authored DDR/VIE/IRQ lines marked '# COLDWAR' stay first in each block."""
    branches, name, inside = {}, None, False
    for line in source.splitlines():
        m = re.match(r'\s*name\s*=\s*(MDCW_HP_\w+)', line)
        if m:
            name = m[1]
        if not name:
            continue
        # Regional builders (e.g. the UAE campaign) own marker-delimited blocks.
        if re.match(r'\s*# COLDWAR .*\bBEGIN\s*$', line):
            inside = True
        if inside:
            branches.setdefault(name, []).append(line.strip() if line.strip().startswith('#') else line.strip())
            if re.match(r'\s*# COLDWAR .*\bEND\s*$', line):
                inside = False
            continue
        if re.match(r'\s*text\s*=\s*\{.*# COLDWAR', line):
            branches.setdefault(name, []).append(line.strip())
    return branches


def ruling_block(source):
    m = re.search(r'(?ms)^defined_text = \{\n\tname = MDCW_HP_ruling_party\n.*?^\}', source)
    assert m, 'MDCW_HP_ruling_party missing'
    return m[0]


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--root', type=Path, required=True)
    ap.add_argument('--out', type=Path)
    args = ap.parse_args()
    root, out = args.root, args.out or args.root
    data_dir = HERE / 'data'
    countries = {p.stem: json.loads(p.read_text(encoding='utf-8')) for p in sorted(data_dir.glob('*.json'))}
    logos = json.loads((HERE / 'logo_icons.json').read_text(encoding='utf-8')) if (HERE / 'logo_icons.json').exists() else {}
    polsys = (root / 'localisation/english/0_political_system_l_english.yml').read_text(encoding='utf-8-sig')
    generic_icon = dict(re.findall(r'generic\.([^\s:.]+)_icon:\d*\s*"([^"]*)"', polsys))
    generic_desc = dict(re.findall(r'generic\.([^\s:.]+)_desc:\d*\s*"([^"]*)"', polsys))
    old = (root / 'common/scripted_localisation/mdcw_historical_parties.txt').read_text(encoding='utf-8-sig')
    retained = retained_branches(old)
    ruling = ruling_block(old)

    loc = {}
    for i, ide in enumerate(IDEOLOGIES):
        loc[f'MDCW_HP_MD_{ide}_desc'] = generic_desc[ide]
        loc[f'MDCW_HP_family_{i}_desc'] = f'({FAMILY[i]})\n\n$MDCW_HP_MD_{ide}_desc$'
        loc[f'MDCW_HP_generic_{i}'] = generic_icon[ide] + ' ' + FAMILY[i]
        loc[f'MDCW_HP_generic_{i}_desc'] = f'({FAMILY[i]})\n\n' + generic_desc[ide]
        loc[f'MDCW_HP_generic_{i}_icon'] = generic_icon[ide]

    rows = {i: [] for i in range(24)}
    for tag, c in sorted(countries.items()):
        assert c['tag'] == tag, tag
        for slot, periods in c['slots'].items():
            i = int(slot)
            keys = []
            for n, p in enumerate(periods):
                key = f'MDCW_HP_{tag}_{i}_{n}'
                icon = '£' + p['icon'] if p.get('icon') else logos.get(f'{tag}|{i}|{n}') or generic_icon[IDEOLOGIES[i]]
                if not icon.startswith('£'):
                    icon = '£' + icon
                loc[key] = icon + ' ' + display_name(p)
                loc[key + '_desc'] = description(p)
                loc[key + '_icon'] = icon
                keys.append((p.get('from'), key))
            for start, key in reversed(keys[1:]):
                rows[i].append((f'original_tag = {tag}\nIMP_is_1970_scenario = yes\ndate > {day_before(start)}', key))
            rows[i].append((f'original_tag = {tag}\nIMP_is_1970_scenario = yes', keys[0][1]))
        for owner, slots in AUTHORED_FALLBACK.items():
            pass
    for owner, slots in AUTHORED_FALLBACK.items():
        for i, key in slots.items():
            rows[i].append((f'original_tag = {owner}\nIMP_is_1970_scenario = yes', key))

    definitions = []
    for i, ide in enumerate(IDEOLOGIES):
        for suffix in ('', '_desc', '_icon'):
            name = f'MDCW_HP_{ide}{suffix}'
            body = ['name = ' + name]
            body += retained.get(name, [])
            for trig, key in rows[i]:
                body.append(block('text', block('trigger', trig) + '\nlocalization_key = ' + key + suffix))
            body.append(block('text', f'localization_key = MDCW_HP_generic_{i}{suffix}'))
            definitions.append(block('defined_text', '\n'.join(body)))
    registry = HEADER + '\n\n'.join(definitions) + '\n\n' + ruling + '\n'
    assert registry.count('{') == registry.count('}')

    files = {
        'common/scripted_localisation/mdcw_historical_parties.txt': registry,
        'localisation/english/mdcw_1970_party_registry_l_english.yml':
            '\ufeffl_english:\n# IMPERIA CW — Cold War: party registry 1970 English localisation.\n # COLDWAR | 1970 party registry, generated by tools/party_registry_1970/generate.py\n'
            + ''.join(f' {k}:0 {loc_value(v)}\n' for k, v in loc.items()),
        'localisation/english/mdcw_historical_politics_1970_l_english.yml':
            '\ufeffl_english:\n# IMPERIA CW — Cold War: party registry 1970 English localisation.\n MDCW_HP_retirement_no_alternative_tt:0 "Another historical party leader is available."\n',
    }
    for rel, text in files.items():
        path = out / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding='utf-8', newline='\n')
    print(json.dumps({'countries': len(countries), 'loc_keys': len(loc),
                      'registry_bytes': len(registry)}))


if __name__ == '__main__':
    main()
