def wrap_native_body(text,name,key,condition,yes_body):
    marker='# COLDWAR KOR '+key+' BEGIN'
    if marker in text:return text
    match=re.search(r'(?m)^'+re.escape(name)+r'\s*=\s*\{',text);assert match,name
    end=matching_close(text,match.end());original=text[match.end():end]
    new='\n# IMPERIA CW — Cold War: South Korea1970 national programme.\n'+marker+'\nif = { limit = { '+condition+' }\n'+yes_body+'\n} else = {\n# COLDWAR KOR '+key+' NATIVE BODY\n'+original+'\n}\n# COLDWAR KOR '+key+' END\n'
    return text[:match.end()]+new+text[end:]

def marked(text,key,body,anchor=None,function=None):
    start='# COLDWAR KOR '+key+' BEGIN';end='# COLDWAR KOR '+key+' END'
    insert='# IMPERIA CW — Cold War: South Korea1970 national programme.\n'+start+'\n'+body.rstrip()+'\n'+end+'\n'
    pattern=r'(?m)^# IMPERIA CW — Cold War: South Korea1970 national programme\.\n'+re.escape(start)+r'\n[\s\S]*?'+re.escape(end)+r'\n'
    if start in text:return re.sub(pattern,lambda _:insert,text,count=1)
    if function:
        pos=function_end(text,function);return text[:pos]+insert+text[pos:]
    assert anchor and anchor in text,(key,anchor)
    return text.replace(anchor,insert+anchor,1)

