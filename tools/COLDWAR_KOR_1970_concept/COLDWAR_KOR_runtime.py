    def visible_trigger(self,rows):
        result=[]
        for k,op,v in rows:
            if k in ('tag','original_tag','IMP_is_1970_scenario'):continue
            if k=='has_country_flag' and v.startswith(P):
                result.append(('custom_trigger_tooltip','=',[('tooltip','=',self.requirement(v)),(k,op,v)]))
            elif k=='check_variable' and first(v,'ruling_party') is not None:
                slot=first(v,'ruling_party');key=P+'party_'+slot+'_tt'
                names={'0':'The DRP or its civilian conservative successor','1':'The New Democratic Party','2':'The reform movement of the Two Kims','3':'The Unification Socialist Party','4':'The Revolutionary Party for Reunification','5':'A student civic coalition','7':'The authorized security caretaker','19':'The independent southern left','22':'The Army/DJP political organization'}
                self.loc[key]=names.get(slot,'The required political party')+' leads the government.'
                self.loc[key+'_NOT']='The required political party does not lead the government.'
                result.append(('custom_trigger_tooltip','=',[('tooltip','=',key),(k,op,v)]))
            elif k=='check_variable' and any(a.startswith('party_banned_array^') for a,o,b in v):
                key=P+'legal_party_tt';self.loc[key]='The relevant political party may participate legally.';self.loc[key+'_NOT']='The relevant political party is prohibited from participation.'
                result.append(('custom_trigger_tooltip','=',[('tooltip','=',key),(k,op,v)]))
            elif k==P+'has_vietnam_commitment':
                key=P+'vietnam_commitment_tt';self.loc[key]='An actual Korean commitment in Vietnam remains to be settled.';self.loc[key+'_NOT']='No Korean commitment in Vietnam remains to be settled.'
                result.append(('custom_trigger_tooltip','=',[('tooltip','=',key),(k,op,v)]))
            elif isinstance(v,list) and k in ('OR','AND','NOT'):
                result.append((k,op,self.visible_trigger(v)))
            else:result.append((k,op,v))
        return result

