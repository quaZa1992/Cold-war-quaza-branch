    @staticmethod
    def reconcile_modifier(id,trigger):
        return 'if = { limit = { '+trigger+' = yes } if = { limit = { NOT = { has_dynamic_modifier = { modifier = '+id+' } } } add_dynamic_modifier = { modifier = '+id+' } } } else = { if = { limit = { has_dynamic_modifier = { modifier = '+id+' } } remove_dynamic_modifier = { modifier = '+id+' } } }'

    def start_changes(self,n):
        entries=set(n.get('start_replacements',[]))|{a['value'] for a in n['effects']['actions'] if a['type']=='start_replace'}
        result=[]
        for key in sorted(entries):
            if n['key']=='freight_corridors' and key=='rural':flag=P+'start_rural_intermediate'
            elif n['key']=='energy_planning' and key=='energy':flag=P+'start_energy_intermediate'
            elif key=='political_command':continue # actual order/control reader
            else:flag=P+'start_'+key+'_resolved'
            result.append('set_country_flag = '+flag)
        return result

