def matching_close(text,start):
    depth=1;quoted=False;comment=False;escape=False
    for pos in range(start,len(text)):
        c=text[pos]
        if comment:
            if c=='\n':comment=False
            continue
        if quoted:
            if escape:escape=False
            elif c=='\\':escape=True
            elif c=='"':quoted=False
            continue
        if c=='#':comment=True
        elif c=='"':quoted=True
        elif c=='{':depth+=1
        elif c=='}':
            depth-=1
            if depth==0:return pos
    raise ValueError('Unclosed native block')

def function_end(text,name):
    match=re.search(r'(?m)^'+re.escape(name)+r'\s*=\s*\{',text);assert match,name
    return matching_close(text,match.end())

