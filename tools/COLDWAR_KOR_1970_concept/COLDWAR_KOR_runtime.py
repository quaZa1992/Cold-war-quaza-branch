def num(v):
    s=f'{v:.5f}'.rstrip('0').rstrip('.')
    return s if s and s!='-0' else '0'

def safe(s):return re.sub('[^A-Za-z0-9_]+','_',s).strip('_')
def pretty(s):return s.replace('_',' ').strip().capitalize()
def block(name,body):return name+' = {\n'+body+'\n}\n'
def formatted(s):return HEADER+emit(parse(s))+'\n'

def hide_routing_checks(rows):
    # IMPERIA CW — Cold War: retain scenario/initialization guards without
    # exposing the native "game initially started" tooltip to players.
    result=[]
    for k,op,v in rows:
        technical=k in ('tag','original_tag','IMP_is_1970_scenario') or (k=='has_country_flag' and (v==P+'initialized' or v.endswith(('_terms_v3','_offer_v3'))))
        if technical:result.append(('hidden_trigger','=',[(k,op,v)]))
        elif k=='hidden_trigger':result.append((k,op,v))
        elif isinstance(v,list):result.append((k,op,hide_routing_checks(v)))
        else:result.append((k,op,v))
    return result
def owner_body(owner):
    if owner=='national':return ''
    if owner.startswith('party:'):return 'check_variable = { ruling_party = '+owner.split(':',1)[1]+' }'
    return 'has_country_leader = { name = "'+owner[7:]+'" ruling_only = yes }'

