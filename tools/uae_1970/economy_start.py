# IMPERIA CW — Cold War: uae 1970 — economy start.
"""Pure, bounded UAE industrial-start integration for the 1970 campaign.

Only build(data)'s caller installs files. Existing oil setup, GDP calibration,
weekly economy and all unrelated state-history bytes remain outside this module.
"""
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[2]
P = 'COLDWAR_UAE_'
EFFECT_PATH = 'common/scripted_effects/COLDWAR_UAE_1970_starting_industry.txt'
STATES = {179: ('history/states/179-Dubai.txt', {'aluminium': 19}, 1),
          180: ('history/states/180-Abu Dhabi.txt', {'aluminium': 22, 'steel': 5}, 0)}
HEADER = '# IMPERIA CW — Cold War: uae 1970 — economy start.\n# COLDWAR | UAE 1970 industrial baseline. Generated by tools/uae_1970/economy_start.py.\n'
TOKEN = re.compile(r'"(?:\\.|[^"\\])*"|#[^\r\n]*|[{}]')
MARKER = re.compile(
    r'(?m)^[\t ]*# COLDWAR UAE INDUSTRY (1970 SNAPSHOT|2000 SNAPSHOT|2000 HISTORY) BEGIN\r?\n'
    r'[\s\S]*?^[\t ]*# COLDWAR UAE INDUSTRY \1 END(?:\r?\n|$)')


def strip_owned(text):
    """Reverse only this module's marked additions, preserving other bytes."""
    result = MARKER.sub('', text)
    if '# COLDWAR UAE INDUSTRY ' in result:
        raise ValueError('Unbalanced or unknown UAE industry history marker')
    return result


def _end(text, opening):
    depth = 0
    for token in TOKEN.finditer(text, opening):
        if token[0] == '{':
            depth += 1
        elif token[0] == '}':
            depth -= 1
            if depth == 0:
                return token.start()
    raise ValueError('Unclosed state history block')


def _find(text, key, start=0, end=None):
    end = len(text) if end is None else end
    pattern = re.compile(r'(?m)^([\t ]*)'+re.escape(key)+r'\s*=\s*\{')
    matches = list(pattern.finditer(text, start, end))
    if len(matches) > 1:
        raise ValueError('Ambiguous state history block: '+key)
    if not matches:
        return None
    match = matches[0]
    opening = text.index('{', match.start(), match.end())
    closing = _end(text, opening)
    if closing > end:
        raise ValueError('History block escapes its parent: '+key)
    return match, opening, closing


def _snapshot(text, date, level, required):
    newline = '\r\n' if '\r\n' in text else '\n'
    history = _find(text, 'history')
    if not history:
        raise ValueError('Missing state history')
    history_match, opening, closing = history
    dated = _find(text, date, opening+1, closing)
    number = date.split('.')[0]
    if dated:
        match, _, end = dated
        prefix = match[1]+'\t'
        marker = 'COLDWAR UAE INDUSTRY '+number+' SNAPSHOT'
        insertion = newline.join([
            prefix+'# '+marker+' BEGIN\n'+prefix+'# IMPERIA CW — Cold War: Dated UAE industrial baseline.',
            prefix+'buildings = { composite_plant = '+str(level)+' }',
            prefix+'# '+marker+' END', ''])
        line = text.rfind('\n', 0, end)+1
        return text[:line]+insertion+text[line:]
    if required:
        raise ValueError('Missing existing authored '+date+' state snapshot')
    prefix = history_match[1]+'\t'
    marker = 'COLDWAR UAE INDUSTRY '+number+' HISTORY'
    insertion = newline.join([
        prefix+'# '+marker+' BEGIN\n'+prefix+'# IMPERIA CW — Cold War: Later-bookmark UAE industrial baseline.',
        prefix+'# Later bookmark snapshot; never a scheduled campaign reset.',
        prefix+date+' = {',
        prefix+'\tbuildings = { composite_plant = '+str(level)+' }',
        prefix+'}',
        prefix+'# '+marker+' END', ''])
    line = text.rfind('\n', 0, closing)+1
    return text[:line]+insertion+text[line:]


def state_history(text, state_id):
    """Add exact 1970 zero and later native composite snapshots, idempotently."""
    baseline = strip_owned(text)
    _, metals, modern_composites = STATES[state_id]
    resources = _find(baseline, 'resources')
    if not resources:
        raise ValueError('Missing canonical state resources: '+str(state_id))
    _, opening, closing = resources
    entries = dict(re.findall(r'(?m)^\s*(\w+)\s*=\s*(-?\d+)\s*$', baseline[opening+1:closing]))
    for resource, amount in metals.items():
        if entries.get(resource) != str(amount):
            raise ValueError(f'Unexpected canonical {state_id} {resource}; fixed startup subtraction requires review')
    result = _snapshot(baseline, '1970.1.1', 0, required=True)
    result = _snapshot(result, '2000.1.1', modern_composites, required=False)
    if strip_owned(result) != baseline:
        raise AssertionError('UAE industry patch changed unrelated state bytes')
    return result


def _remove_composites():
    # Native composite plants have state_max=5. The additional counter stops
    # even if removal makes no progress; no unbounded startup loop is possible.
    return '''set_temp_variable = { COLDWAR_UAE_start_composite_removals = 0 }
while_loop_effect = {
 limit = {
  composite_plant > 0
  check_variable = { var = COLDWAR_UAE_start_composite_removals value = 5 compare = less_than }
 }
 remove_building = { type = composite_plant level = 1 }
 add_to_temp_variable = { COLDWAR_UAE_start_composite_removals = 1 }
}'''


def _block(key, text):
    return key+' = {\n'+'\n'.join('\t'+line if line else '' for line in text.strip().splitlines())+'\n}'


def effect_text():
    guards = '''original_tag = UAE
is_dynamic_country = no
IMP_is_1970_scenario = yes
COLDWAR_UAE_1970_campaign = yes
date < 1970.1.3
NOT = { has_country_flag = IMP_1970_gdp_profile_applied }
NOT = { has_country_flag = COLDWAR_UAE_industry_start_applied }
owns_state = 179
controls_state = 179
owns_state = 180
controls_state = 180'''
    body = [_block('limit', guards)]
    for state_id, (_, metals, _) in STATES.items():
        rows = [f'add_resource = {{ type = {resource} amount = {-amount} }}' for resource, amount in metals.items()]
        rows.append(_remove_composites())
        body.append(_block(str(state_id), '\n'.join(rows)))
    body.append('set_country_flag = '+P+'industry_start_applied')
    return HEADER+_block(P+'startup_industry', _block('if', '\n'.join(body)))+'\n'


def build(data):
    """Return three complete output strings without writing or recalibrating GDP."""
    outputs = {EFFECT_PATH: effect_text()}
    for state_id, (relative, _, _) in STATES.items():
        # decode() preserves existing LF/CRLF and any UTF-8 BOM. The compiler
        # therefore receives every original byte outside the owned additions.
        source = (ROOT/relative).read_bytes().decode('utf-8')
        outputs[relative] = state_history(source, state_id)
    return outputs
