def build(data):
    """Return only this module's owned outputs; do not write from an import."""
    assert data['country'] in ('UAE', 'United Arab Emirates') or 'UAE' in str(data['country'])
    outputs = {}
    for group in [trigger_outputs(), effect_outputs(), identity_outputs()]:
        group = {path: md_tabs(text) if path.endswith('.txt') else text for path, text in group.items()}
        assert not set(outputs) & set(group)
        outputs.update(group)
    outputs.update(shared_outputs())
    return outputs
