def block(name, body):
    return name + ' = {\n' + '\n'.join('\t' + s if s else '' for s in body.strip().splitlines()) + '\n}\n'


def loc(entries):
    return 'l_english:\n# IMPERIA CW — Cold War: uae 1970 English localisation.\n' + ''.join(' ' + k + ':0 "' + v.replace('\\', '\\\\').replace('"', '\\"').replace('\n', '\\n') + '"\n' for k, v in entries.items())


def md_tabs(text):
    """Literal templates use one space per nesting level; emit native MD tabs."""
    return re.sub(r'(?m)^[ \t]+', lambda m: m.group().replace(' ', '\t'), text)


