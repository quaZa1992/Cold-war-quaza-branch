def native_party_text_icons():
    """Use MD's registered case-sensitive text sprites, not ideology spelling."""
    source = (ROOT / 'interface/MD_texticons.gfx').read_text(encoding='utf-8-sig')
    native = dict(re.findall(r'name\s*=\s*"([^"]+)"[^}]*?texturefile\s*=\s*"([^"]+)"', source, re.I))
    assert set(PARTY_TEXT_ICONS) == set(SLOTS)
    icons = {}
    for slot, sprite in PARTY_TEXT_ICONS.items():
        assert sprite in native, 'Missing native inline party sprite: ' + sprite
        texture = native[sprite].replace('\\', '/')
        assert texture.startswith('gfx/texticons/'), texture
        path = ROOT / texture
        assert path.is_file() and path.read_bytes()[:4] == b'DDS ', path
        icons[slot] = '\u00a3' + sprite.removeprefix('GFX_')
    return icons


