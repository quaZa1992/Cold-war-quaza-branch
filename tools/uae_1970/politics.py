def replace_marked(text, name, content, anchor, before=False):
    start, end = '# COLDWAR UAE ' + name + ' BEGIN', '# COLDWAR UAE ' + name + ' END'
    marked = start + '\n# IMPERIA CW — Cold War: UAE political integration.\n' + content.rstrip() + '\n' + end + '\n'
    pattern = re.compile(re.escape(start) + r'.*?' + re.escape(end) + r'\n?', re.S)
    if pattern.search(text):
        return pattern.sub(lambda _: marked, text, count=1)
    assert text.count(anchor) == 1, (name, 'integration anchor not unique', text.count(anchor))
    return text.replace(anchor, marked + '\n' + anchor if before else anchor + '\n' + marked, 1)


def shared_outputs():
    outputs, records = {}, []
    old_log = HERE / 'politics_shared_integrations.json'
    previous = json.loads(old_log.read_text(encoding='utf-8')) if old_log.exists() else {}
    descriptions = {}

    def patch(rel, transform, reason):
        path = ROOT / rel
        raw = path.read_bytes()
        current = raw.decode('utf-8-sig').replace('\r\n', '\n')
        changed = transform(current)
        assert changed != '', rel
        outputs[rel] = changed
        prior = previous.get(rel, {})
        descriptions[rel] = {'before_sha256': prior.get('before_sha256', hashlib.sha256(raw).hexdigest()),
                             'after_sha256': hashlib.sha256(changed.encode('utf8')).hexdigest(), 'purpose': reason}

