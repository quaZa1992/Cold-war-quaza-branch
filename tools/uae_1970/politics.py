def dynastic_leader(name, picture, council=False):
    """Keep the same historical office holder in the actual governing subtype."""
    out = []
    for keyword, slot, trait in [('if', 0, 'western_Western_Autocracy'),
                                 ('else', 23, 'nationalist_Monarchist')]:
        traits = (trait,) if council else ('king', trait)
        body = '' if keyword == 'else' else 'limit = { check_variable = { ruling_party = 0 } }\n'
        out.append(block(keyword, body + country_leader(name, SLOTS[slot], picture, traits)))
    return '\n'.join(out)


