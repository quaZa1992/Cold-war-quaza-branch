def build():
    approved = json.loads((HERE / 'approval.json').read_text())
    assert hashlib.sha256((HERE / 'approved_design.json').read_bytes()).hexdigest() == approved['sha256'], 'Approved snapshot changed'
    outputs = {}
    for chunk in [focus_outputs(DATA), programme_outputs(DATA), lifecycle_outputs()]:
        outputs.update(chunk)
    for module in ['politics', 'diplomacy', 'art', 'economy_start', 'decision_routes']:
        chunk = importlib.import_module(module).build(DATA)
        assert not set(outputs) & set(chunk), 'Overlapping generated ownership: ' + module
        outputs.update(chunk)
    manifest = {'approved_sha256': approved['sha256'], 'focuses': len(DATA['nodes']), 'decisions': len(DATA['decisions']), 'outputs': {}}
    for rel, text in outputs.items():
        path = ROOT / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        # IMPERIA CW — Cold War: Keep module-owned generated scripts marked on every build.
        if path.name.startswith('COLDWAR_') and path.suffix in {'.txt', '.gui', '.gfx'} and not text.lstrip('\ufeff').startswith('# IMPERIA CW'):
            text = '# IMPERIA CW — Cold War: UAE 1970 generated content.\n' + text
        encoding = 'utf-8-sig' if path.suffix == '.yml' else 'utf-8'
        payload = text.encode('utf-8') if rel.startswith('history/states/') else text.lstrip('\ufeff').replace('\r\n', '\n').encode(encoding)
        if not path.exists() or path.read_bytes() != payload:
            path.write_bytes(payload)
        manifest['outputs'][rel] = hashlib.sha256(path.read_bytes()).hexdigest()
    from flags import install as install_flags
    for rel, payload in install_flags().items():
        manifest['outputs'][rel] = hashlib.sha256(payload).hexdigest()
    (HERE / 'manifest.json').write_text(json.dumps(manifest, indent=2), encoding='utf-8')
    print(json.dumps({'outputs': len(outputs), 'focuses': len(DATA['nodes']), 'decisions': len(DATA['decisions'])}))


if __name__ == '__main__':
    build()
