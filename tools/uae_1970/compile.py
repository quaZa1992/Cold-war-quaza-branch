def native_leaves(n, preview=False):
    key = suffix(n)
    out = []
    if key in PRODUCTIVITY:
        state, value = PRODUCTIVITY[key]
        if state:
            out.append(block(str(state), f'set_temp_variable = {{ temp_productivity_change = {value} }}\nstate_flat_productivity_change_effect = yes'))
        else:
            out.append(f'set_temp_variable = {{ temp_productivity_change = {value} }}\nflat_productivity_change_effect = yes')
    if key in PROJECTS:
        state, building = PROJECTS[key]
        slots = 'add_extra_state_shared_building_slots = 1\n' if building in {'industrial_complex', 'offices'} else ''
        instant = 'yes' if key in COMMISSIONED_PROJECTS else 'no'
        out.append(block(str(state), slots + f'add_building_construction = {{ type = {building} level = 1 instant_build = {instant} }}'))
    if key == 'port_planning':
        # Native MD province-specific building test (05_libya, Tripoli docks).
        # A level-ten port elsewhere must not suppress Dubai's fishing harbour.
        port_guard = 'owns_state = 179\ncontrols_state = 179\ncontrols_province = 3725\n179 = { NOT = { any_province_building_level = { province = { id = 3725 } building = naval_base level > 9 } } }'
        out.append(block('if', block('limit', port_guard) +
                         block('179', 'add_building_construction = { type = naval_base province = 3725 level = 1 instant_build = no }')))
    out += [f'{effect} = {value}' for effect, value in EXPERIENCE.get(key, {}).items()]
    for change in n.get('resource_changes', []):
        out.append(block(str(change['state']), f'add_resource = {{ type = {change["resource"]} amount = {change["base_amount"]} }}'))
    if n.get('resource_changes') and not preview:
        out.append('set_country_flag = ' + n['one_time_delivery_flag'])
        out.append('ingame_update_setup = yes')
    if key == 'proclaim_federation' and not preview:
        out.append('COLDWAR_UAE_form_federation = yes')
    if key == 'dirham' and not preview:
        out.append('COLDWAR_UAE_establish_dirham = yes')
    if key == 'rak_accession' and not preview:
        out.append('set_country_flag = COLDWAR_UAE_rak_accession_settled')
    if key in {'renew_protection', 'british_friendship'} and not preview:
        call = {'renew_protection': 'protection', 'british_friendship': 'friendship'}[key]
        leaf = f'COLDWAR_UAE_send_{call}_offer = yes'
        if key == 'british_friendship':
            # A mutually accepted British counterproposal may already have
            # established friendship before this institutional focus is taken.
            leaf = block('if', 'limit = { NOT = { has_country_flag = COLDWAR_UAE_friendship_accepted } }\n' + leaf)
        out.append(leaf)
    out.append(focus_leaves(key, preview))
    out.append(focus_only_leaves(key, preview))
    # Foreign partners answer offers issued by the actual focus transaction.
    # The preview is non-executing and uses the same frozen-price providers.
    out.append(focus_action(key, preview))
    if key == 'gulf_cooperation':
        out.append('COLDWAR_GCC_UAE_petition_preview = yes' if preview else 'COLDWAR_GCC_UAE_petition = yes')
    return '\n'.join(out)



