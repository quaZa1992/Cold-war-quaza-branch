def suffix(node):
    return node['id'].removeprefix(PREFIX)


def indent(text, level=1):
    return '\n'.join('\t' * level + line if line else '' for line in text.splitlines())


def block(name, body):
    return name + ' = {\n' + indent(body.strip()) + '\n}\n'


def done(key):
    return PREFIX + 'done_' + key


def money(amount):
    return f'set_temp_variable = {{ treasury_change = {amount:g} }}\nmodify_treasury_effect = yes'


def runtime_condition(text):
    # User-requested native MD revision: historical pro-Western ruling houses
    # use Western_Autocracy; the alternative Monarchist wing remains supported.
    return text.replace('nationalist_monarchists_are_in_power = yes',
                        'COLDWAR_UAE_monarchy_government = yes')


def localise(entries):
    lines = ['l_english:\n# IMPERIA CW — Cold War: uae 1970 English localisation.']
    for key, value in entries.items():
        value = str(value).replace('\\', '\\\\').replace('"', '\\"').replace('\n', '\\n')
        lines.append(f' {key}:0 "{value}"')
    return '\n'.join(lines) + '\n'


def base_available(n):
    text = runtime_condition(n['available'])
    text = re.sub(r'check_variable\s*=\s*\{[^{}]*\btreasury\b[^{}]*\}', '', text)
    if n.get('one_time_delivery_flag'):
        text = text.replace('NOT = { has_country_flag = ' + n['one_time_delivery_flag'] + ' }', '')
    for flag in VISIBLE_FLAGS:
        text = text.replace('has_country_flag = ' + flag, 'custom_trigger_tooltip = { tooltip = ' + flag + '_tt has_country_flag = ' + flag + ' }')
    return text.strip()


def parent_guard(n, by_id):
    rows = []
    for row in n['prerequisites']:
        choices = []
        for parent in row:
            key = parent.removeprefix(PREFIX)
            condition = 'has_country_flag = ' + done(key)
            if by_id[parent].get('bypass'):
                condition = block('OR', condition + '\n' + by_id[parent]['bypass']).strip()
            choices.append(condition)
        rows.append(choices[0] if len(choices) == 1 else block('OR', '\n'.join(choices)).strip())
    return '\n'.join(rows)


