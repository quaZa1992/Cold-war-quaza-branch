def programme_outputs(data):
    definitions, refresh, loc = [], [scale_effect(LIVE_SCALE)], {}
    flavour = importlib.import_module('flavour')
    # Every UAE tree growth contribution shares this capped national pool.
    # Refuse an uncapped new source rather than silently exceed the total cap.
    assert all(n['group'] == 'society' for n in data['nodes']
               if 'monthly_population' in n['modifiers'] or any('monthly_population' in c['modifiers'] for c in n.get('conditional_contributions', [])))
    assert not any('monthly_population' in s['modifiers'] for s in data['starting_spirits'])
    for g in data['groups']:
        ns = [n for n in data['nodes'] if n['group'] == g['id']]
        keys = sorted(set(k for n in ns for k in n['modifiers']) | set(k for n in ns for c in n.get('conditional_contributions', []) for k in c['modifiers']))
        mod_id = PREFIX + g['id'] + '_programme'
        active = PREFIX + g['id'] + '_programme_active'
        definition = ['icon = GFX_idea_' + mod_id, 'enable = { COLDWAR_UAE_1970_campaign = yes has_country_flag = ' + active + ' }']
        definition += [f'{k} = {PREFIX}{g["id"]}_{k}' for k in keys]
        definitions.append(block(mod_id, '\n'.join(definition)))
        refresh.append('clr_country_flag = ' + active)
        refresh += [f'set_variable = {{ {PREFIX}{g["id"]}_{k} = 0 }}' for k in keys]
        positive = PREFIX + g['id'] + '_positive_stability'
        if g['id'] in POLITICAL:
            refresh.append(f'set_variable = {{ {positive} = 0 }}')
        for n in ns:
            key = suffix(n)
            if not n['modifiers'] and not n.get('conditional_contributions'):
                continue
            guards = ['has_country_flag = ' + done(key), runtime_condition(n['active_condition'])]
            if n['temporary_days']:
                guards.append('has_country_flag = ' + PREFIX + 'temporary_' + key)
            contribution = ['set_country_flag = ' + active]
            for k, v in n['modifiers'].items():
                var = positive if g['id'] in POLITICAL and k == 'stability_factor' and v > 0 else PREFIX + g['id'] + '_' + k
                leaf = f'add_to_variable = {{ {var} = {v:g} }}'
                if key in MARITIME_FOCUSES and k in SCALED_MODIFIERS:
                    amount = PREFIX+'maritime_contribution'
                    leaf = scaled_value(amount, v, LIVE_SCALE)+'\n'+f'add_to_variable = {{ {var} = {amount} }}'
                if key == 'citizen_republic' and k == 'stability_factor' and v < 0:
                    leaf = block('if', 'limit = { NOT = { has_country_flag = COLDWAR_UAE_court_settled } }\n' + leaf)
                contribution.append(leaf)
            if key == 'charitable_network':
                contribution.append(block('if', 'limit = { has_country_flag = COLDWAR_UAE_charity_registered }\nadd_to_variable = { COLDWAR_UAE_islah_bureaucracy_cost_multiplier_modifier = -0.03 }'))
            for c in n.get('conditional_contributions', []):
                # state_participation duplicates its main modifiers in the concept to mark the gate.
                extra = {k: v for k, v in c['modifiers'].items() if k not in n['modifiers']}
                if extra:
                    contribution.append(block('if', 'limit = { ' + c['condition'] + ' }\n' + '\n'.join(f'add_to_variable = {{ {PREFIX}{g["id"]}_{k} = {v:g} }}' for k, v in extra.items())))
            refresh.append(block('if', block('limit', '\n'.join(guards)) + '\n' + '\n'.join(contribution)))
        if g['id'] in POLITICAL and 'stability_factor' in keys:
            refresh += [f'clamp_variable = {{ var = {positive} max = 0.15 }}', f'add_to_variable = {{ {PREFIX}{g["id"]}_stability_factor = {positive} }}']
        if 'monthly_population' in keys:
            refresh.append(f'clamp_variable = {{ var = {PREFIX}{g["id"]}_monthly_population max = {POPULATION_GROWTH_CAP:g} }}')
        refresh.append(block('if', 'limit = { has_country_flag = ' + active + ' }\n' + block('if', 'limit = { NOT = { has_dynamic_modifier = { modifier = ' + mod_id + ' } } }\nadd_dynamic_modifier = { modifier = ' + mod_id + ' }')))
        refresh.append(block('else', 'remove_dynamic_modifier = { modifier = ' + mod_id + ' }'))
        loc[mod_id] = g['label'].replace(' · ALT', '')
        loc[mod_id + '_desc'] = 'The institutions and policies already enacted under this programme. Contributions apply only while the qualifying government is in office. Positive stability contributions are capped at +15 percentage points; negative contributions remain.' if g['id'] in POLITICAL else 'The institutions and policies enacted under this national programme. Individual treaty and temporary terms apply where required.'
        if 'monthly_population' in keys:
            loc[mod_id + '_desc'] += ' Total population-growth bonuses from this focus tree are capped at +200%.'
    originals = {s['id']: s for s in data['starting_spirits']}
    for sid, spirit in originals.items():
        if sid == PREFIX + 'treaty_dependence':
            continue  # Diplomacy owns the single displayed bilateral spirit and its −10% PP carrier.
        definition = ['icon = GFX_idea_' + sid, 'enable = { COLDWAR_UAE_1970_campaign = yes }']
        for k, base in spirit['modifiers'].items():
            var = sid + '_' + k
            definition.append(k + ' = ' + var)
            refresh.append(f'set_variable = {{ {var} = {base:g} }}')
            families = defaultdict(list)
            for n in data['nodes']:
                for c in n.get('spirit_changes', []):
                    if c['spirit'] == sid and c['component'] == k:
                        relief = abs(base - c['value']) if c['operation'] == 'set' else abs(c['value'])
                        families[c['family']].append((relief, suffix(n)))
            for family, values in families.items():
                credit = PREFIX + 'relief_' + family + '_' + k
                refresh.append(f'set_variable = {{ {credit} = 0 }}')
                for value, key in sorted(values):
                    refresh.append(block('if', 'limit = { has_country_flag = ' + done(key) + ' }\n' + f'set_variable = {{ {credit} = {value:g} }}'))
                operation = 'subtract_from_variable' if base > 0 else 'add_to_variable'
                refresh.append(f'{operation} = {{ {var} = {credit} }}')
            if sid == PREFIX + 'unequal_development' and k == 'stability_factor':
                refresh.append(block('if', 'limit = { has_country_flag = COLDWAR_UAE_mediate_settled }\n' + f'set_variable = {{ {var} = 0 }}'))
            if sid == PREFIX + 'fragmented_authority' and k == 'bureaucracy_cost_multiplier_modifier':
                refresh.append(block('if', 'limit = { has_country_flag = COLDWAR_UAE_cabinet_settled }\n' + f'subtract_from_variable = {{ {var} = 0.03 }}'))
            refresh.append(f'clamp_variable = {{ var = {var} ' + ('min = 0' if base > 0 else 'max = 0') + ' }')
            if sid == PREFIX+'maritime_livelihoods' and k in SCALED_MODIFIERS:
                refresh.append(f'multiply_variable = {{ {var} = {LIVE_SCALE} }}')
        definitions.append(block(sid, '\n'.join(definition)))
        remaining = '\n'.join(f'check_variable = {{ var = {sid}_{k} value = 0 compare = {"greater_than" if v > 0 else "less_than"} }}' for k, v in spirit['modifiers'].items())
        refresh.append(block('if', block('limit', block('OR', remaining)) + '\n' + block('if', 'limit = { NOT = { has_dynamic_modifier = { modifier = ' + sid + ' } } }\nadd_dynamic_modifier = { modifier = ' + sid + ' }')))
        refresh.append(block('else', 'remove_dynamic_modifier = { modifier = ' + sid + ' }'))
        loc[sid] = spirit['label']
        loc[sid + '_desc'] = getattr(flavour, 'SPIRIT_DESCRIPTIONS', {}).get(sid, spirit['description'])
    refresh.append('force_update_dynamic_modifier = yes')
    return {'common/dynamic_modifiers/COLDWAR_UAE_1970_programmes.txt': HEADER + '\n'.join(definitions),
            'common/scripted_effects/COLDWAR_UAE_1970_programmes.txt': HEADER + block('COLDWAR_UAE_refresh_programmes', block('if', 'limit = { COLDWAR_UAE_1970_campaign = yes }\n' + '\n'.join(refresh))),
            'localisation/english/COLDWAR_UAE_1970_programmes_l_english.yml': localise(loc)}


