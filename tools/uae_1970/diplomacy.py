def b(key: str, body: str) -> str:
    return f"{key} = {{\n{indent(body.strip(), chr(9))}\n}}"


def flag(name: str) -> str:
    return P + name


def funded(price: str) -> str:
    return f"check_variable = {{ var = treasury value = {price} compare = greater_than_or_equals }}"


def cash(amount: str | float) -> str:
    return f"set_temp_variable = {{ treasury_change = {amount} }}\nmodify_treasury_effect = yes"


def debit(price: str) -> str:
    return f"set_temp_variable = {{ treasury_change = {price} }}\nmultiply_temp_variable = {{ treasury_change = -1 }}\nmodify_treasury_effect = yes"


def prod() -> str:
    return "set_temp_variable = { temp_productivity_change = 10 }\nflat_productivity_change_effect = yes"


def earned(suffix: str) -> str:
    return f"has_country_flag = {P}done_{suffix}"


