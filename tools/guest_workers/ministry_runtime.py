# IMPERIA CW — Cold War: Guest Worker Administration
"""Emit a GUI adapter for the existing native targeted-decision contracts.

The adapter substitutes FROM with the country-local selected partner. ROOT stays
the receiving player, including when a request schedules the sender's event.
There is no bridge event, shared target, global selection, or second transaction.
"""
from pathlib import Path
