import validate as V

HEADER = '# IMPERIA CW — Cold War: Guest Worker Administration\n# Generated by tools/guest_workers/build_dashboard.py.\n'


def emit(rows, level=0):
    out=[]
    for key,op,value in rows:
        if isinstance(value,list):out += ['\t'*level+f'{key} {op} {{',emit(value,level+1),'\t'*level+'}']
        else:out.append('\t'*level+f'{key} {op} {value}')
    return '\n'.join(out)


def adapter(root):
    triggers={}
    for name in ('mdcw_guest_workers_triggers','mdcw_diaspora_triggers'):
        triggers.update({k:v for k,_,v in V.read_script('common/scripted_triggers/'+name+'.txt')})
    needed=set()
    def collect(name):
        if name in needed:return
        needed.add(name)
        for key,_,value in V.walk(triggers[name]):
            if key in triggers:collect(key)
    for size in (25000,50000,100000):collect('mdcw_gw_request_available_'+str(size))
    aliases={name:name.replace('mdcw_gw_','mdcw_gw_ui_',1) for name in needed}
    tooltips=set()
    def replace_atom(value):
        if value == 'FROM':return 'var:ROOT.gw_ui_partner'
        if value == 'FROM.id':return 'ROOT.gw_ui_partner'
        if value.startswith('FROM.'):return 'var:ROOT.gw_ui_partner.'+value[5:]
        return aliases.get(value,value)
    def adapt(rows):
        result=[]
        for key,op,value in rows:
            if key in ('tooltip','not_tooltip'):
                tooltips.add(value);value='gw_ui_'+value
            result.append((replace_atom(key),op,adapt(value) if isinstance(value,list) else replace_atom(value)))
        return result
    trigger_rows=[]
    for k in sorted(needed):
        body=adapt(triggers[k])
        if k=='mdcw_gw_income_advantage':
            # Explicit native country scopes avoid a chained dynamic scope in a
            # numeric operand, and safely leave a missing selection at zero.
            body=[('set_temp_variable','=',[('gw_required_receiver_gdpc','=','0')]),
                  ('var:ROOT.gw_ui_partner','=',[('ROOT','=',[
                      ('set_temp_variable','=',[('gw_required_receiver_gdpc','=','PREV.gdp_per_capita')])])]),*body[1:]]
        trigger_rows.append((aliases[k],'=',body))
    for size,pp in ((25000,75),(50000,125),(100000,200)):
        trigger_rows += [(f'mdcw_gw_ui_can_recruit_{size}','=',[
            ('check_variable','=',[('gw_ui_partner','>','-1')]),
            (aliases[f'mdcw_gw_request_available_{size}'],'=','yes'),
            ('NOT','=',[('check_variable','=',[('political_power','<',str(pp))])]),
            ('NOT','=',[('has_country_flag','=','gw_dialog_window')])])]
    effects=dict((k,v) for k,_,v in V.read_script('common/scripted_effects/mdcw_guest_workers_effects.txt'))
    generated=[]
    for size,pp in ((25000,75),(50000,125),(100000,200)):
        # Existing no-argument effect retains its validation/refund branch. The
        # UI pays the same native PP fee before calling that exact authored body.
        body=adapt(effects[f'mdcw_gw_request_agreement_{size}'])
        generated.append((f'mdcw_gw_ui_recruit_{size}','=',[
            ('if','=',[('limit','=',[(f'mdcw_gw_ui_can_recruit_{size}','=','yes')]),
                       ('add_political_power','=',str(-pp)),*body])]))
    assert not any(re.search(r'\bFROM\b',str(n)) for n in trigger_rows+generated)
    return HEADER+emit(trigger_rows)+'\n',HEADER+emit(generated)+'\n',tooltips


