"""Keep existing Sinai geography and restore the superseded canal split.

The saved source only restores state 214; Sinai needs no new state boundary.
"""
from pathlib import Path
import json

SINAI = 213
CANAL = 214


def apply(root, write, loc):
    spec = json.loads((Path(__file__).parent / 'policy_map_source.json').read_text(encoding='utf-8'))
    path = root / 'history/states/214-Suez.txt'
    current = path.read_text(encoding='utf-8-sig')
    original = spec['original_state_214']
    if not current.startswith('# Canal split generated by tools/israel_1970/policy_map.py.'):
        assert current == original, 'State 214 changed independently; inspect before restoring'
    # Register the preserved original on every build, including after restoration.
    write('history/states/214-Suez.txt', original, normalize=False)
    obsolete = {
        'history/states/1252-Suez Canal.txt': '# Narrow canal district.',
        'common/state_category/ISR70_delta_remainder.txt': '# Preserve the old combined 40-slot capacity:',
    }
    for rel, marker in obsolete.items():
        target = root / rel
        if target.exists():
            assert target.read_text(encoding='utf-8-sig').startswith(marker), rel
            target.unlink()
    models = (root / 'map/buildings.txt').read_text(encoding='utf-8-sig')
    restored = '\n'.join('214;' + line[5:] if line.startswith('1252;') else line for line in models.split('\n'))
    write('map/buildings.txt', restored, normalize=False)
    return {'id': SINAI, 'existing_state': True, 'borders_changed': False,
            'population_reallocated': False, 'canal_state': CANAL}
