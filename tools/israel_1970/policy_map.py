# IMPERIA CW — Cold War: israel 1970 — policy map.
"""Keep existing Sinai geography and restore the superseded canal split.

The saved source only restores state 214; Sinai needs no new state boundary.
"""
from pathlib import Path
import json,re

SINAI = 213
CANAL = 214

def without_buildings(source):
    """Allow the native 1970 economy generator to own its building history."""
    source=re.sub(r'#[^\n]*','',source)
    while match:=re.search(r'\bbuildings\s*=\s*\{',source):
        end=match.end();depth=1
        while depth:
            depth+=(source[end]=='{')-(source[end]=='}');end+=1
        source=source[:match.start()]+source[end:]
    return re.sub(r'\s+','',source)


def apply(root, write, loc):
    spec = json.loads((Path(__file__).parent / 'policy_map_source.json').read_text(encoding='utf-8'))
    path = root / 'history/states/214-Suez.txt'
    current = path.read_text(encoding='utf-8-sig')
    original = spec['original_state_214']
    if not current.startswith('# Canal split generated by tools/israel_1970/policy_map.py.'):
        assert without_buildings(current)==without_buildings(original), 'State 214 geography or non-building history changed independently; inspect before restoring'
        # The old snapshot predates the native 1970 economy pass. A focus-tree
        # rebuild must preserve its independently authored building levels.
        original=current
    obsolete = {
        'history/states/1252-Suez Canal.txt': '# Narrow canal district.',
        'common/state_category/ISR70_delta_remainder.txt': '# Preserve the old combined 40-slot capacity:',
    }
    # IMPERIA COLD WAR — A reused state number is not evidence of a canal remnant.
    # Preflight all removals before writing or deleting anything.
    legacy_canal = root / 'history/states/1252-Suez Canal.txt'
    migrate_locators = legacy_canal.exists()
    if migrate_locators:
        occupants = [p for p in (root / 'history/states').glob('1252*.txt') if p != legacy_canal]
        assert not occupants, 'State 1252 is also used by an independent map feature'
    for rel, marker in obsolete.items():
        target = root / rel
        if target.exists():
            assert target.read_text(encoding='utf-8-sig').startswith(marker), rel
    # Register the preserved original on every build, including after restoration.
    write('history/states/214-Suez.txt', original, normalize=False)
    for rel in obsolete:
        target = root / rel
        if target.exists():
            target.unlink()
    models = (root / 'map/buildings.txt').read_text(encoding='utf-8-sig')
    restored = ('\n'.join('214;' + line[5:] if line.startswith('1252;') else line for line in models.split('\n'))
                if migrate_locators else models)
    write('map/buildings.txt', restored, normalize=False)
    return {'id': SINAI, 'existing_state': True, 'borders_changed': False,
            'population_reallocated': False, 'canal_state': CANAL}
