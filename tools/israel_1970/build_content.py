def patch(rel,transform):
    path=ROOT/rel;old=path.read_text(encoding='utf-8-sig');new=transform(old)
    if old!=new:path.write_text(new,encoding='utf-8',newline='\n')
def wrap_effect(rel,key,gate,reward=None):
    source=(ROOT/rel).read_text(encoding='utf-8-sig')
    # Prefix a wrapper only once; preserve all the existing scripts inside the else.
    marker='# ISR70 | 1970 scenario dispatch'
    if marker in source:return
    match=re.search(r'(?m)^'+re.escape(key)+r'\s*=\s*\{',source);assert match,(rel,key)
    start=match.end();clean=re.sub(r'"(?:\\.|[^"\\])*"|#[^\n]*',lambda m:' '*len(m[0]),source);depth=1;end=start
    while depth:
        depth+=(clean[end]=='{')-(clean[end]=='}');end+=1
    body=source[start:end-1]
    replacement='\n\t'+marker+'\n'
    if reward:replacement+='\tif = { limit = { '+gate+' } '+reward+' }\n\telse = {\n'+ind(body.strip(),2)+'\n\t}\n'
    else:replacement+='\tif = { limit = { '+gate+' }\n'+ind(body.strip(),2)+'\n\t}\n'
    patch(rel,lambda s:s[:start]+replacement+s[end-1:])

