def readable_conditions(source):
    def replace(match):
        flag=match[1];short=flag.removeprefix('ISR70_')
        if re.fullmatch(r'party_\d+_founded',short):label=PARTIES[int(short.split('_')[1])][0]+' has an independent political organization.'
        elif flag.startswith('ISR70_policy_'):label=POLICY.flag_label(flag)
        else:
            assert short in FLAG_LABELS,('Missing condition text',flag)
            label=FLAG_LABELS[short]
        key=flag+'_condition_tt';loc(key,label)
        return f'custom_trigger_tooltip = {{ tooltip = {key} has_country_flag = {flag} }}'
    return re.sub(r'\bhas_country_flag\s*=\s*(ISR70_\w+)\b',replace,source)

def unique_conditions(parts):
    """Deduplicate complete top-level clauses without changing nested AND/OR."""
    source='\n'.join(parts)
    tokens=list(re.finditer(r'"(?:\\.|[^"\\])*"|[{}]|>=|<=|!=|=|<|>|[^\s{}<>=!"#]+',source))
    clauses=[];seen=set();i=0
    while i<len(tokens):
        start=i
        assert i+2<len(tokens) and tokens[i+1][0] in ('=','>','<','>=','<=','!='),source
        i+=2
        if tokens[i][0]=='{':
            depth=1;i+=1
            while depth:
                depth+=(tokens[i][0]=='{')-(tokens[i][0]=='}');i+=1
        else:i+=1
        signature=tuple(token[0] for token in tokens[start:i])
        if signature not in seen:
            seen.add(signature);clauses.append(source[tokens[start].start():tokens[i-1].end()])
    return clauses
