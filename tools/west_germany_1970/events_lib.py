"""Tiny event DSL for the West/East Germany 1970 events."""
from cw_lib import P, EVG, EVD, L, fmt
from tooltips import hide_vars

GER_T = "original_tag = GER exists = yes IMP_is_1970_scenario = yes"
DDR_T = "original_tag = DDR exists = yes IMP_is_1970_scenario = yes"
SOV_T = "original_tag = SOV exists = yes IMP_is_1970_scenario = yes"
SCOPE_T = {"GER": GER_T, "DDR": DDR_T, "SOV": SOV_T, "ANY": "exists = yes"}

EVENTS = []          # (namespace, script)
EVENT_IDS = set()
PICTURES = set()
EXTRA_EFFECTS = []   # scripted effects authored next to the events


def O(text, eff="", ai=10, trig="", tt=None):
    """An event option. ai may be an int or a raw ai_chance body."""
    return dict(text=text, eff=eff, ai=ai, trig=trig, tt=tt)


def E(evid, title, desc, pic, opts, scope="GER", trig="", imm="", hidden=False, descs=None, mtth=None, fire_only_once=False):
    from roster import requirement
    if evid == 'COLDWAR_GER.93': trig = requirement('greens') + ' ' + trig
    if evid == 'COLDWAR_GER.94': trig = requirement('rep') + ' ' + trig
    ns, num = evid.split(".")
    if evid in EVENT_IDS:
        raise ValueError("duplicate event " + evid)
    EVENT_IDS.add(evid)
    out = ["country_event = {", f"\tid = {evid}"]
    if hidden:
        out.append("\thidden = yes")
    else:
        out.append(f"\ttitle = {L(evid + '.t', title)}")
        if descs:
            for i, (dtrig, text) in enumerate(descs):
                k = L(f"{evid}.desc{i + 1}", text)
                if dtrig:
                    out.append(f"\tdesc = {{ trigger = {{ {dtrig} }} text = {k} }}")
                else:
                    out.append(f"\tdesc = {{ text = {k} }}")
        else:
            out.append(f"\tdesc = {L(evid + '.desc', desc)}")
        PICTURES.add(pic)
        out.append(f"\tpicture = {pic}")
    if mtth is None:
        out.append("\tis_triggered_only = yes")
    if fire_only_once:
        out.append("\tfire_only_once = yes")
    out.append(f"\ttrigger = {{ {SCOPE_T[scope]} {trig} }}")
    if mtth is not None:
        out.append(f"\tmean_time_to_happen = {{ days = {mtth} }}")
    if imm:
        out.append("\timmediate = {\n" + fmt(imm, 2) + "\n\t}")
    for i, o in enumerate(opts):
        letter = "abcdefgh"[i]
        key = f"{evid}.{letter}"
        L(key, o["text"])
        out.append("\toption = {")
        out.append(f"\t\tname = {key}")
        if o["trig"]:
            out.append(f"\t\ttrigger = {{ {o['trig']} }}")
        if isinstance(o["ai"], int):
            out.append(f"\t\tai_chance = {{ base = {o['ai']} }}")
        else:
            out.append("\t\tai_chance = { " + o["ai"] + " }")
        out.append(f'\t\tlog = "[GetDateText]: [Root.GetName]: event {evid} option {letter}"')
        if o["tt"]:
            k = L(f"{evid}.{letter}.tt", o["tt"])
            out.append(f"\t\tcustom_effect_tooltip = {k}")
        if o["eff"]:
            out.append(fmt(hide_vars(o["eff"]), 2))
        out.append("\t}")
    out.append("}")
    EVENTS.append((ns, "\n".join(out)))


def gov(ruling, cols=(), elections=True):
    """Form a government with MD's change_ruling_party_effect."""
    s = [f"set_temp_variable = {{ rul_party_temp = {ruling} }}"]
    names = ["col_one", "col_two", "col_three"]
    for n, c in zip(names, cols):
        s.append(f"set_temp_variable = {{ {n} = {c} }}")
    s.append(f"set_temp_variable = {{ disable_elections = {0 if elections else 1} }}")
    s.append("change_ruling_party_effect = yes")
    s.append(f"{P}_update_bundestag = yes")
    from roster import slot_available
    if not all(slot_available(slot) for slot in (ruling, *cols)):
        return ''  # Preserve the current roster rather than govern through another organisation.
    return "\n".join(s)


def ger(eff):
    return f"if = {{ limit = {{ country_exists = GER }} GER = {{ {eff} }} }}"


def ddr(eff):
    return f"if = {{ limit = {{ country_exists = DDR }} DDR = {{ {eff} }} }}"


def fire(evid, days=1, target=None):
    s = f"country_event = {{ id = {evid} days = {days} }}"
    if target:
        return f"if = {{ limit = {{ country_exists = {target} }} {target} = {{ {s} }} }}"
    return s


def news(evid, title, desc, pic, ok="Interesting times.", trig=""):
    """A news event shown to everyone except the source (fired with every_country)."""
    E(evid, title, desc, pic, [O(ok)], scope="ANY", trig=trig)


def all_events_file():
    by_ns = {}
    for ns, txt in EVENTS:
        by_ns.setdefault(ns, []).append(txt)
    out = ["## Generated by tools/west_germany_1970/compile.py. Edit the generator, not this file.\n"]
    for ns in by_ns:
        out.append(f"add_namespace = {ns}")
    out.append("")
    for ns, items in by_ns.items():
        out.append(f"# ================================================================ {ns}")
        out.extend(x + "\n" for x in items)
    return "\n".join(out)
