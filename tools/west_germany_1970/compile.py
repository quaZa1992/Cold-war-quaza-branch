def focus_block(fc):
    lines = ["\tfocus = {", f"\t\tid = {fc['id']}", f"\t\ticon = GFX_{P}_{fc['icon']}"]
    if fc["rel"]:
        lines.append(f"\t\trelative_position_id = {P}_{fc['rel']}")
    lines += [f"\t\tx = {fc['dx']}", f"\t\ty = {fc['dy']}", f"\t\tcost = {tree.focus_cost(fc['cost'])}",
              "\t\tcancel_if_invalid = yes", "\t\tcontinue_if_invalid = no", "\t\tavailable_if_capitulated = no"]
    for group in fc["pre"]:
        lines.append("\t\tprerequisite = { " + " ".join(f"focus = {P}_{k}" for k in group) + " }")
    if fc["mutex"]:
        lines.append("\t\tmutually_exclusive = { " + " ".join(f"focus = {P}_{k}" for k in fc["mutex"]) + " }")
    if fc["wargoal"]:
        lines.append(f"\t\twill_lead_to_war_with = {fc['wargoal']}")
    lines.append(f"\t\tsearch_filters = {{ {fc['filt']} }}")
    lines.append(f"\t\tavailable = {{ hidden_trigger = {{ original_tag = GER IMP_is_1970_scenario = yes }} {nice(fc['avail'])} }}")
    if fc["bypass"]:
        lines.append(f"\t\tbypass = {{ {fc['bypass']} }}")
    body = f'log = "[GetDateText]: [Root.GetName]: focus {fc["id"]}"\n' + hide_vars(fc["reward"])
    lines.append("\t\tcompletion_reward = {\n" + cw_lib.fmt(body, 3) + "\n\t\t}")
    lines.append(f"\t\tai_will_do = {{ base = {fc['ai']} {fc['ai_mod']} }}")
    lines.append("\t}")
    return "\n".join(lines)


def focus_file():
    hooks.apply()
    tree.mutex_symmetric()
    tree.auto_layout()
    problems = tree.check_layout()
    if problems:
        raise ValueError("focus layout: " + "; ".join(problems))
    import re
    for fc in FOCUSES:
        m = re.search(r"date < (\S+)", fc["avail"])
        if m and not fc["bypass"]:
            fc["bypass"] = f"date > {m.group(1)}"
    out = [HEADER, "focus_tree = {", f"\tid = {P}_focus", "\tdefault = no", "\treset_on_civilwar = no",
           "\tcountry = { factor = 0 modifier = { add = 100 original_tag = GER IMP_is_1970_scenario = yes } }",
           f"\tinitial_show_position = {{ focus = {P}_{tree.ROOT_KEY} }}",
           "\tcontinuous_focus_position = { x = 50 y = 2200 }"]
    for fc in FOCUSES:  # names first: availability tooltips quote them
        L(fc["id"], fc["name"])
        L(fc["id"] + "_desc", fc["desc"])
    for key, name in SHORTCUTS:
        sid = f"{P}_shortcut_{key}"
        L(sid, name)
        out.append(f"\tshortcut = {{ name = {sid} target = {P}_{key} scroll_wheel_factor = 0.80 }}")
    out.extend(focus_block(fc) for fc in FOCUSES)
    out.append("}")
    return "\n".join(out) + "\n"


