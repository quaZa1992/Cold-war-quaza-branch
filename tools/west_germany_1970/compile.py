    used = sorted({fc["icon"] for fc in FOCUSES})
    plain, shine = [HEADER, "spriteTypes = {"], [HEADER, "spriteTypes = {"]
    for k in used:
        tex = "gfx/interface/goals/" + ICONS[k]
        plain.append(f'\tspriteType = {{\n\t\tname = "GFX_{P}_{k}"\n\t\ttexturefile = "{tex}"\n\t}}')
        shine.append(
            f'\tspriteType = {{\n\t\tname = "GFX_{P}_{k}_shine"\n\t\ttexturefile = "{tex}"\n\t\teffectFile = "gfx/FX/buttonstate.lua"\n'
            f'\t\tanimation = {{ animationmaskfile = "{tex}" animationtexturefile = "gfx/interface/goals/shine_overlay.dds" animationrotation = -90.0 '
            'animationlooping = no animationtime = 0.75 animationdelay = 0.0 animationblendmode = "add" animationtype = "scrolling" '
            'animationrotationoffset = { x = 0.0 y = 0.0 } animationtexturescale = { x = 1.0 y = 1.0 } }\n'
            f'\t\tanimation = {{ animationmaskfile = "{tex}" animationtexturefile = "gfx/interface/goals/shine_overlay.dds" animationrotation = 90.0 '
            'animationlooping = no animationtime = 0.75 animationdelay = 0.0 animationblendmode = "add" animationtype = "scrolling" '
            'animationrotationoffset = { x = 0.0 y = 0.0 } animationtexturescale = { x = 1.0 y = 1.0 } }\n'
            '\t\tlegacy_lazy_load = no\n\t}')
    plain.append("}")
    shine.append("}")
    return "\n".join(plain) + "\n", "\n".join(shine) + "\n"


