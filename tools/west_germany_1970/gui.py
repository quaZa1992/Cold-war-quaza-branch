def DT(name, entries, default_key=None, persistent=False):
    """Scripted localisation: entries = [(trigger, loc_key)]."""
    lines = [f"defined_text = {{\n\tname = {name}"]
    for trig, key in entries:
        lines.append(f"\ttext = {{\n\t\ttrigger = {{ {trig} }}\n\t\tlocalization_key = {key}\n\t}}")
    if default_key:
        lines.append(f"\ttext = {{\n\t\tlocalization_key = {default_key}\n\t}}")
    lines.append("}")
    (PERSISTENT_LOC if persistent else SCRIPTED_LOC).append("\n".join(lines))
    return name


