    # -------------------------------------------------------------- elements
    def n(self, name):
        return f"{self.id}_{name}"

    def sk(self, sprite):
        """Map the mod's generic Cold War window pieces onto the file-folder skin."""
        suffix = "_bka" if self.skin == "bka" else ""
