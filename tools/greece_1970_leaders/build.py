def broaden_party_representatives(content):
    """Party programmes accept the party's chosen candidate; personal junta paths stay personal."""
    def leader(name):
        return r'has_country_leader\s*=\s*\{\s*name\s*=\s*"' + re.escape(name) + r'"\s*ruling_only\s*=\s*yes\s*\}'
    patterns = [
        (r'OR\s*=\s*\{\s*' + leader('Panagiotis Kanellopoulos') + r'\s*' + leader('Konstantinos Karamanlis') + r'\s*\}', PARTY_TRIGGERS[1]),
        (leader('Georgios Mavros'), PARTY_TRIGGERS[2]),
        (leader('Andreas Papandreou'), PARTY_TRIGGERS[3]),
        (r'OR\s*=\s*\{\s*' + leader('Kostas Koligiannis') + r'\s*' + leader('Charilaos Florakis') + r'\s*\}', PARTY_TRIGGERS[4]),
    ]
    for pattern, trigger in patterns:
        content = re.sub(pattern, trigger + ' = yes', content)
    return content


def patch_party_programmes(c):
    for relative in ('common/national_focus/COLDWAR_GRE_1970_focus.txt',
                     'common/scripted_effects/COLDWAR_GRE_1970_tree_effects.txt'):
        path = c.root / relative
        if path.exists():
            original = path.read_text(encoding='utf-8')
            content = broaden_party_representatives(original)
            content = re.sub(r'\A#[^\n]*', '# IMPERIA COLD WAR — Greek party leadership compatibility in existing national programmes.', content, count=1)
            # Keep the source generator and all unrelated focus content intact.
            if content != original:
                path.write_text(content, encoding='utf-8', newline='\n')
            c.files.append(relative)


