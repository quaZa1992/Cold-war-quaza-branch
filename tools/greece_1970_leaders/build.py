def install_party_labels(c):
    path = c.root / 'common/scripted_localisation/00_MD_politicsview_scripted_localisation.txt'
    content = path.read_text(encoding='utf-8-sig')
    content = re.sub(r'(?m)^.*# COLDWAR GRE LEADERSHIP PARTY\n', '', content)
    # Preserve each native party index, while displaying the actual chosen left tradition.
    rows = [('renewal', ('drakopoulos', 'kyrkos'), 'KKE Interior / Greek Left',
             'The communist renewal tradition associated with KKE Interior and the Greek Left, distinct from the orthodox KKE leadership.'),
            ('coalition', ('damanaki', 'konstantopoulos'), 'Synaspismos',
             'The coalition of the democratic and renewal left, represented by its selected political leadership.')]
    loc = {}
    for suffix in ('', '_desc'):
        anchor = 'name = communist_state_L' + suffix + '\n'
        assert anchor in content
        additions = []
        for key, people, name, desc in rows:
            gate = CONTEXT.replace('\n', ' ') + ' OR = { ' + ' '.join('has_country_flag = ' + P + 'preference_4_' + who for who in people) + ' }'
            ident = P + 'party_left_' + key + suffix
            loc[ident] = name if suffix == '' else desc
            additions.append('\ttext = { trigger = { ' + gate + ' } localization_key = ' + ident + ' } # COLDWAR GRE LEADERSHIP PARTY')
        content = content.replace(anchor, anchor + '\n'.join(additions) + '\n', 1)
    if not content.startswith('# IMPERIA COLD WAR'):
        content = '# IMPERIA COLD WAR — Greek political leadership identity integration.\n' + content
    c.write(path.relative_to(c.root).as_posix(), content)
    c.write('localisation/english/COLDWAR_GRE_1970_leadership_parties_l_english.yml', 'l_english:\n' + HEADER
        + '\n'.join(' ' + k + ':0 "' + v + '"' for k, v in sorted(loc.items())) + '\n', True)


