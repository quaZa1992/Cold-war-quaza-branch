def block(name, body):
    return name + ' = {\n' + '\n'.join('\t' + s if s else '' for s in body.splitlines()) + '\n}'


def cond(test, body, otherwise=''):
    result = block('if', block('limit', test) + '\n' + body)
    return result + ('\n' + block('else', otherwise) if otherwise else '')


def configure_specs(existing):
    result = [dict(s) for s in existing]
    known = {s['key'] for s in result}
    for key, name, slots, trait, note in ADDITIONS:
        if key not in known:
            result.append(dict(key=key, kind='political', start='1970.1.1', end='2000.1.1',
                chief_start='1970.1.1', chief_end='2000.1.1', slots=list(slots), extra='', trait=trait, note=note))
    for s in result:
        if s['kind'] == 'political':
            s.update(start='1970.1.1', end='2000.1.1', chief_start='1970.1.1', chief_end='2000.1.1')
        if s['key'] in IDENTITY_NOTES:
            s['note'] = IDENTITY_NOTES[s['key']]
    return result


