def render_country(c, specs):
    """Write only GRE files; called both by this driver and the regional owner."""
    root = c.root
    data = c.ready['GRE']
    specs = configure_specs(specs)
    assert all(s['key'] in data for s in specs), 'Build the Greek portrait assets first.'
    loc, chars, recruit, roster, decisions, categories, gfx = {}, [], [], [], [], [], []
    effects = {}
    def write(path, text, bom=False):
        if not text.startswith('l_english:') and not path.endswith('.json'):
            text = HEADER + text
        c.write(path, text, bom)
    def text(key, value):
        loc[key] = value
        return key
    for s in specs:
        key = s['key']
        a = data[key]
        ident = P + key
        military = s['kind'] != 'political'
        text(ident, a['name'])
        text(ident + '_desc', s['note'].replace('\u2013', '-').replace('\u2014', ':'))
        body = 'name = ' + ident + '\n' + block('portraits', block('army' if military else 'civilian',
            f'large = "{a["portrait"]}"\nsmall = "{a["small"]}"'))
        if s['kind'] == 'army':
            body += '\n' + block('corps_commander', 'skill = 3\nattack_skill = 2\ndefense_skill = 3\nplanning_skill = 3\nlogistics_skill = 2')
        elif s['kind'] == 'navy':
            body += '\n' + block('navy_leader', 'skill = 3\nattack_skill = 2\ndefense_skill = 3\nmaneuvering_skill = 3\ncoordination_skill = 3')
        availability = CONTEXT
        if military:
            # Existing service eligibility is unchanged; political choices never use it.
            from datetime import date, timedelta
            def window(start, end):
                y, m, d = map(int, start.split('.'))
                before = date(y, m, d) - timedelta(days=1)
                return f'date > {before.year}.{before.month}.{before.day}\ndate < {end}'
            availability += '\n' + window(s['chief_start'], s['chief_end'])
        availability += f'\nNOT = {{ has_country_leader = {{ name = "{a["name"]}" ruling_only = yes }} }}'
        slot = {'army': 'army_chief', 'navy': 'navy_chief', 'air': 'air_chief'}.get(s['kind'], 'political_advisor')
        trait = s['kind'] if military else s['trait']
        body += '\n' + block('advisor', f'slot = {slot}\nidea_token = {ident}\ntraits = {{ COLDWAR_EASTMED_1970_{trait} }}\ncost = 75\n'
            + block('allowed', 'original_tag = GRE\nIMP_is_1970_scenario = yes') + '\n' + block('available', availability)
            + '\nai_will_do = { factor = 1 }')
        chars.append(block(ident, body))
        ready = CONTEXT + f'\nNOT = {{ has_character = {ident} }}'
        if military:
            ready += '\n' + window(s['start'], s['end'])
        recruit.append(cond(ready, f'recruit_character = {ident}\nset_country_flag = {P}recruited_{key}'))
        roster.append({'tag': 'GRE', 'id': ident, 'name': a['name'], **s, 'portrait': a['portrait'], 'small': a['small'],
                       'political_calendar_gates': False, 'political_selection_slots': s['slots']})
        # Native Sheep decision art: a 33 x 30 portrait tile, registered per candidate.
        icon_path = root / 'gfx/interface/decisions/leaders' / (P + key + '.dds')
        icon_path.parent.mkdir(parents=True, exist_ok=True)
        ImageOps.fit(Image.open(root / a['portrait']).convert('RGBA'), (33, 30),
                     method=Image.Resampling.LANCZOS, centering=(.5, .15)).save(icon_path, format='DDS')
        gfx.append(block('spriteType', f'name = "GFX_{P}{key}"\ntexturefile = "{icon_path.relative_to(root).as_posix()}"'))

    effects[P + 'refresh_roster'] = cond(CONTEXT, '\n'.join(recruit))
    native = (root / 'common/characters/GRE.txt').read_text(encoding='utf-8-sig')
    ids = re.findall(r'(?m)^\t(GRE_[A-Za-z0-9_]+)\s*=\s*\{', native)
    effects[P + 'retire_modern_roster'] = cond(CONTEXT, '\n'.join(cond('has_character = ' + ident, 'retire_character = ' + ident) for ident in ids))
    callbacks = []
    old_tree = root / 'common/scripted_effects/COLDWAR_GRE_1970_tree_effects.txt'
    if old_tree.exists() and P + 'reconcile_programmes_effect = {' in old_tree.read_text(encoding='utf-8'):
        callbacks.append(P + 'reconcile_programmes_effect = yes')
    effects[P + 'leadership_changed'] = '\n'.join(callbacks) or '# No active party-programme owner.'

    def appointment(key, ideology):
        a = data[key]
        # Real replacement, with no death/retirement calendar and no reward replay.
        return cond(f'NOT = {{ has_country_leader = {{ name = "{a["name"]}" ruling_only = yes }} }}',
            f'retire_country_leader = yes\ncreate_country_leader = {{ name = "{a["name"]}" picture = "{a["portrait"]}" desc = {P}{key}_desc ideology = {ideology} }}')

    branches = []
    clear_current = '\n'.join('clr_country_flag = ' + P + 'selected_' + s['key'] for s in specs)
    for idx, ideology in enumerate(IDEOLOGIES):
        candidates = [s for s in specs if idx in s['slots']]
        body, adopt = [], []
        memory_flags = ['has_country_flag = ' + P + 'preference_' + str(idx) + '_' + s['key'] for s in candidates]
        clear_memory = '\n'.join('clr_country_flag = ' + P + 'preference_' + str(idx) + '_' + s['key'] for s in candidates)
        for s in candidates:
            key, name = s['key'], data[s['key']]['name']
            memory = P + 'preference_' + str(idx) + '_' + key
            # Adopt explicit legacy focus selections and old saves. An inherited
            # active representative cannot erase another party's saved preference.
            requested = f'has_country_flag = {P}selected_{key}\n' + block('OR',
                'NOT = { OR = { ' + ' '.join(memory_flags) + ' } }\n'
                + f'NOT = {{ has_country_leader = {{ name = "{name}" ruling_only = yes }} }}')
            adopt.append(block('if' if not adopt else 'else_if', block('limit', requested) + '\n' + clear_memory + '\nset_country_flag = ' + memory))
            body.append(block('if' if not body else 'else_if', block('limit', 'has_country_flag = ' + memory)
                + f'\nset_country_flag = {P}selected_{key}\n' + appointment(key, ideology)))
        default = (f'set_country_flag = {P}selected_{DEFAULTS[idx]}\n'
            + f'set_country_flag = {P}preference_{idx}_{DEFAULTS[idx]}\n'
            + appointment(DEFAULTS[idx], ideology)) if idx in DEFAULTS else cond(
            f'NOT = {{ check_variable = {{ {P}leader_party = ruling_party }} }}',
            f'retire_country_leader = yes\ncreate_country_leader = {{ name = "Greek National Administration" picture = "{c.generic["GRE"]}" ideology = {ideology} }}')
        body.append(block('else', default)) if body else body.append(default)
        branches.append(block('if' if idx == 0 else 'else_if', block('limit', f'check_variable = {{ ruling_party = {idx} }}')
            + '\n' + '\n'.join(adopt) + '\n' + clear_current + '\n' + '\n'.join(body)))
        if not candidates:
            continue
        category = P + 'leader_candidates_' + str(idx)
        text(category, GROUPS[idx])
        text(category + '_desc', 'Choose the political representative of the governing party. All candidates in this list are available throughout the campaign.')
        gate = CONTEXT + '\nis_ai = no\n' + PARTY_TRIGGERS[idx] + ' = yes'
        categories.append(block(category, 'icon = GFX_decision_category_generic_political_actions\npriority = 2000\n'
            + block('allowed', 'original_tag = GRE\nIMP_is_1970_scenario = yes') + '\n' + block('visible', gate)))
        choices = []
        for s in candidates:
            key, name = s['key'], data[s['key']]['name']
            choice = P + 'choose_' + str(idx) + '_' + key
            text(choice, 'Select ' + name)
            text(choice + '_desc', s['note'].replace('\u2013', '-').replace('\u2014', ':'))
            # Only this party's selection changes; other party preferences survive.
            run = clear_current + '\n' + clear_memory + '\nset_country_flag = ' + P + 'preference_' + str(idx) + '_' + key
            run += '\nset_country_flag = ' + P + 'selected_' + key + '\n' + P + 'set_leader = yes'
            active = gate + '\nNOT = { has_country_leader = { name = "' + name + '" ruling_only = yes } }'
            effects[P + 'choose_' + str(idx) + '_' + key + '_effect'] = cond(active, run)
            choices.append(block(choice, f'icon = GFX_{P}{key}\ncost = 0\nfire_only_once = no\ndays_re_enable = 0\n'
                + block('allowed', 'original_tag = GRE\nIMP_is_1970_scenario = yes') + '\n' + block('visible', gate)
                + '\n' + block('available', active) + '\n' + block('complete_effect', P + 'choose_' + str(idx) + '_' + key + '_effect = yes')
                + '\nai_will_do = { factor = 0 }'))
        decisions.append(block(category, '\n\n'.join(choices)))
    effects[P + 'set_leader'] = cond(CONTEXT, 'update_set_politics = yes\n' + '\n'.join(branches)
        + '\nset_correct_ideology_trait = yes\nset_variable = { ' + P + 'leader_party = ruling_party }\n' + P + 'leadership_changed = yes')
    effects[P + 'initialize'] = cond(CONTEXT, P + 'retire_modern_roster = yes\n' + P + 'refresh_roster = yes\n'
        + cond(f'OR = {{ NOT = {{ has_country_flag = {P}undated_leadership_initialized }} NOT = {{ check_variable = {{ {P}leader_party = ruling_party }} }} }}',
            P + 'set_leader = yes\nset_country_flag = ' + P + 'undated_leadership_initialized'))
    # Retain the public legacy effect ID for event/focus compatibility. It has no daily hook.
    effects[P + 'daily_tick'] = P + 'initialize = yes'
    write('common/characters/COLDWAR_GRE_1970_regional_characters.txt', block('characters', '\n\n'.join(chars)) + '\n')
    write('common/scripted_effects/COLDWAR_GRE_1970_regional_effects.txt', '\n\n'.join(block(k, v) for k, v in effects.items()) + '\n')
    write('common/decisions/categories/COLDWAR_GRE_1970_leadership_categories.txt', '\n\n'.join(categories) + '\n')
    write('common/decisions/COLDWAR_GRE_1970_leadership_decisions.txt', '\n\n'.join(decisions) + '\n')
    write('common/decisions/COLDWAR_GRE_1970_regional_decisions.txt', '# Replaced by the party candidate selections.\n')
