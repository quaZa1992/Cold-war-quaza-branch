def freeze_approval():
    if not APPROVED.exists():APPROVED.write_bytes(DESIGN.read_bytes())
    d=load_design(APPROVED)
    assert len(d['nodes'])==184 and len(d['agreements'])==9
    return d

def build(include_modules=True):
    d=freeze_approval();out=build_core(d)
    if include_modules:
        for name in ('diplomacy','politics','event_art'):
            extras=load_module(name).build()
            assert not set(extras)&set(out),(name,set(extras)&set(out))
            out.update(extras)
        selected_art=load_module('event_art')
        pictures=selected_art.EVENT_PICTURES
        event_keys={'COLDWAR_CHL.'+str(i+1):e['id'] for i,e in enumerate(d['events'])}
        for rel in [key for key in out if key.startswith('events/')]:
            ast=parse(out[rel])
            for k,op,v in ast:
                if k!='country_event':continue
                eventid=first(v,'id');picture=selected_art.picture_for(eventid,pictures.get(event_keys.get(eventid),'GFX_treaty'))
                v[:]=[(ck,co,cv) for ck,co,cv in v if ck!='picture']+[('picture','=',picture)]
            out[rel]=emit(ast)
    result={}
    for rel,text in out.items():
        if rel.endswith('.yml'):
            assert text.startswith('l_english:'),rel
            lines=text.splitlines();body='\n'.join(line for line in lines[1:] if not line.startswith('# IMPERIA COLD WAR'))
            result[rel]='l_english:\n'+MARK+body+'\n'
        else:
            ast=polish_file(parse(text),scripted_triggers='/scripted_triggers/' in rel)
            result[rel]=MARK+format_code(emit(ast))
    return result

def write_outputs(out,base):
    manifest=[]
    for rel,text in out.items():
        target=base/rel;assert target.resolve().is_relative_to(base.resolve())
        target.parent.mkdir(parents=True,exist_ok=True)
        raw=text.encode('utf-8-sig' if rel.endswith('.yml') else 'utf-8')
        temporary=target.with_name(target.name+'.chile.tmp');temporary.write_bytes(raw);temporary.replace(target)
        manifest.append({'path':rel,'sha256':hashlib.sha256(raw).hexdigest(),'bytes':len(raw)})
    return manifest

