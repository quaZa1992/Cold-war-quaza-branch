def completion_guard(n):
    s=P+'is_scenario = yes\nNOT = { has_country_flag = '+receipt(n)+' }\n'
    for ps in n['prerequisites']:s+=block('OR','\n'.join('has_completed_focus = '+p for p in ps))
    for other in n['excludes']:s+='NOT = { has_completed_focus = '+other+' }\n'
    if n['key'] in ('pinochet_rescue','pinochet_losses'):s+='NOT = { has_country_flag = '+P+'financial_resolution_receipt }\n'
    return block('hidden_trigger',s)+requirements(n)

