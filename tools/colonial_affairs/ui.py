def font(size, family="cour", bold=False):
    names = {"label": "ARIALNB.TTF", "head": "impact.ttf", "serif": "timesi.ttf"}
    name = names.get(family, "courbd.ttf" if bold else "cour.ttf")
    return ImageFont.truetype(str(Path("C:/Windows/Fonts") / name), size)


def txt(draw, xy, text, size=11, color=INK, family="cour", bold=False):
    draw.text(xy, text, font=font(size, family, bold), fill=color)


def line(draw, y, x1=18, x2=492, color="#a78e69", dotted=False):
    if dotted:
        for x in range(x1, x2, 4):
            draw.line((x, y, x + 1, y), fill=color)
    else:
        draw.line((x1, y, x2, y), fill=color)


def paper(w, h, masthead, sub):
    rng = random.Random(1970 + w)
    im = Image.new("RGBA", (w, h))
    pix = im.load()
    for y in range(h):
        for x in range(w):
            edge = max(0, 1 - min(x, w - 1 - x, y, h - 1 - y) / 32)
            noise = rng.gauss(0, 1.8)
            wave = 1.8 * math.sin(y / 61) + 1.3 * math.cos(x / 89)
            shade = noise + wave - edge * 19
            pix[x, y] = (int(232 + shade), int(217 + shade), int(184 + shade), 255)
    d = ImageDraw.Draw(im)
    for y in range(62):
        v = y / 62
        d.line((0, y, w, y), fill=(int(133 - 37*v), int(58-19*v), int(39-11*v), 255))
    for x in range(2, w, 4):
        d.line((x, 0, x, 57), fill=(90, 39, 27, 45))
    d.line((0, 58, w, 58), fill=GOLD, width=2)
    d.line((0, 62, w, 62), fill="#b38a48")
    txt(d, (18, 5), masthead, 32 if w == 510 else 26, GOLD, "head")
    txt(d, (20, 43), sub, 10, "#eed5a1", "label")
    d.rectangle((1, 1, w-2, h-2), outline="#665136")
    return im


