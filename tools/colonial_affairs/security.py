# IMPERIA COLD WAR — Native English briefing text with a clear reading order.
def briefing_widgets(ui, page):
    prefix = 'COLDWAR_COL_' + ('territory' if page == 'territory' else page) + '_empty_'
    tooltip = 'COLDWAR_COL_tab_' + page + '_tt'
    body = ui.icon(prefix + 'page', 0, 0, 'briefing_' + page)
    body += ui.text(prefix + 'title', 28, 150, 450, 30, size=22)
    body += ui.text(prefix + 'intro' if page != 'internal' else prefix + 'note', 28, 190, 450, 36, tooltip=tooltip)
    body += ui.text(prefix + 'note' if page != 'internal' else prefix + 'scope', 28, 290, 454, 80, tooltip=tooltip)
    body += ui.text(prefix + 'help', 28, 416, 454, 76, tooltip=tooltip)
    body += ui.text(prefix + 'options', 28, 538, 454, 82, tooltip=tooltip)
    if page != 'contacts':
        body += ui.text(prefix + 'footer', 20, 666, 470, 18, tooltip=tooltip)
    return body


