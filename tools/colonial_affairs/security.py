def setval(rows, key, value):
    rows[:] = [(k, o, v) for k, o, v in rows if k != key]
    rows.append((key, '=', value))


def save(path, rows):
    (ROOT/path).write_text(MARK + emit(rows) + '\n', encoding='utf-8')


def append(path, code):
    with (ROOT/path).open('a', encoding='utf-8') as out:
        out.write('\n' + MARK + code.rstrip() + '\n')


def flags_and_portraits(ui):
    """A complete fixed-size picture, including after a political succession."""
    sources = {}
    powers = sorted({r['power'] for r in json.loads((HERE/'registry.json').read_text())['administrations']})
    for tag in powers + ['generic']:
        im = Image.new('RGBA', (90, 104), '#d7c5a2'); d = ImageDraw.Draw(im)
        d.rectangle((0, 0, 89, 103), outline='#8e7654', width=2)
        # The neutral institutional fallback also covers new occupying powers.
        d.ellipse((16, 13, 74, 71), outline='#87775c', width=2)
        d.ellipse((30, 13, 60, 71), outline='#87775c')
        d.line((16,42,74,42), fill='#87775c')
        candidates = [ROOT/f'gfx/flags/{tag}_1970.tga', ROOT/f'gfx/flags/{tag}.tga', ROOT/f'gfx/flags/{tag}_democratic.tga']
        source = next((p for p in candidates if p.is_file()), None)
        if tag != 'generic':
            if source is None: raise RuntimeError('Missing authority flag: '+tag)
            flag = Image.open(source).convert('RGBA').resize((76,48), Image.Resampling.LANCZOS)
            im.alpha_composite(flag, (7,21)); sources[tag] = source.relative_to(ROOT).as_posix()
        ui.txt(d, (12,81), tag if tag != 'generic' else 'STATE', 16, ui.INK, bold=True)
        ui.save_asset('authority_'+tag.lower(), im)
    leaders=[]
    for tag in powers:
        history=next((ROOT/'history/countries').glob(tag+' - *.txt'))
        ast=parse(history.read_text(encoding='utf-8-sig'))
        seen=set()
        for date in ('1970.1.1','1985.1.1'):
            for key,_,node in walk(first(ast,date,[])):
                if key!='create_country_leader':continue
                name=first(node,'name','').strip('"');path=first(node,'picture','').strip('"')
                if not name or not path or name in seen:continue
                seen.add(name)
                stem=f'authority_leader_{tag.lower()}_{len(seen)}'
                im=ImageOps.fit(Image.open(ROOT/path).convert('RGBA'),(90,104),Image.Resampling.LANCZOS)
                ui.save_asset(stem,im)
                leaders.append(dict(tag=tag,name=name,source=path,stem=stem))
    if {r['tag'] for r in leaders}!=set(powers):raise RuntimeError('Incomplete starting authority portrait coverage')
    (HERE/'authority_images.json').write_text(json.dumps(dict(powers=powers, sources=sources, leaders=leaders, fallback='authority_generic', size=[90,104]), indent=2)+'\n')


