def block(name: str, body: str) -> str:
    return f'{name} = {{\n' + '\n'.join('\t' + line if line else '' for line in body.strip().splitlines()) + '\n}\n'


def iff(guard: str, body: str, otherwise: str = '') -> str:
    result = block('if', block('limit', guard) + body)
    if otherwise:
        result += block('else', otherwise)
    return result


def num(value: float) -> str:
    return f'{value:.5f}'.rstrip('0').rstrip('.') or '0'


def normalize(registry):
    rows = registry.get('territories', registry.get('administrations', [])) if isinstance(registry, dict) else registry
    result = []
    for index, row in enumerate(rows, 1):
        r = dict(row)
        r['index'] = index
        r['id'] = re.sub(r'[^a-zA-Z0-9_]', '_', str(r['id']))
        r['states'] = list(dict.fromkeys(int(s) for s in r['states']))
        if not r['states']:
            raise ValueError(f"Empty administration: {r['id']}")
        r['anchor'] = r['states'][0]
        r['weekly_base'] = float(r.get('weekly_base', .001)) * 2
        r['profile'] = r.get('profile', 'quiet')
        result.append(r)
    return result


def state_guard(row, state):
    power = f'var:global.COLDWAR_COL_power_{row["id"]}'
    # A subject must actually own AND control the state.  Third-party conquest,
    # independent successor states and a merely historical power are excluded.
    return f'''IMP_is_1970_scenario = yes
NOT = {{ {row['anchor']} = {{ has_state_flag = COLDWAR_COL_inactive }} }}
owner = {{
    controls_state = {state}
    OR = {{ tag = {power} is_subject_of = {power} }}
}}'''


