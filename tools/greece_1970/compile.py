def compile_assets():
    assets = json.loads((ROOT / 'docs/greece_1970_design/MD_VIEW_ASSETS.json').read_text())['assets']
    sprites = []
    shines = []
    for key, a in assets.items():
        sprites += [block('spriteType', 'name = "GFX_' + P + key + '"\ntexturefile = "' + a['path'] + '"')]
        # Native focus completion animation, using the same source texture.
        shines += [block('spriteType', 'name = "GFX_' + P + key + '_shine"\ntexturefile = "' + a['path'] + '"\neffectFile = "gfx/FX/buttonstate.lua"\n' +
                         'animation = { animationmaskfile = "' + a['path'] + '" animationtexturefile = "gfx/interface/goals/shine_overlay.dds" animationrotation = -90.0 animationlooping = no animationtime = 0.75 animationdelay = 0.0 animationblendmode = "add" animationtype = "scrolling" animationrotationoffset = { x = 0.0 y = 0.0 } animationtexturescale = { x = 1.0 y = 1.0 } }\nlegacy_lazy_load = no')]
    for iid, (_, _, _, icon) in IDEAS.items():
        sprites += [block('spriteType', 'name = "GFX_idea_' + iid + '"\ntexturefile = "' + assets[icon]['path'] + '"')]
    for n in NODES:
        if n.get('state_programme'):
            sprites += [block('spriteType', 'name = "GFX_idea_' + n['id'] + '_local_programme"\ntexturefile = "' + assets[n['icon']]['path'] + '"')]
    sprites += [block('spriteType', 'name = "GFX_idea_' + P + 'uneven_regions"\ntexturefile = "' + assets['agriculture']['path'] + '"')]
    write('interface/COLDWAR_GRE_1970_goals.gfx', HEADER + block('spriteTypes', '\n'.join(sprites)))
    write('interface/COLDWAR_GRE_1970_goals_shine.gfx', HEADER + block('spriteTypes', '\n'.join(shines)))
    ideas = []
    for iid, (title, mods, note, _) in IDEAS.items():
        ideas += [block(iid, 'picture = ' + iid + '\nallowed = { original_tag = GRE }\nremoval_cost = -1\n' + block('modifier', '\n'.join(k + ' = ' + str(v) for k, v in mods.items())))]
        loc(iid, title, note or 'The implemented Greek programme, subject to the current government and policy settlement.')
    write('common/ideas/COLDWAR_GRE_1970_ideas.txt', HEADER + block('ideas', block('country', '\n'.join(ideas))))
    s = next(s for s in D['starting_spirits'] if s['key'] == 'uneven_regions')
    dynamic = [block(s['id'], 'icon = GFX_idea_' + s['id'] + '\n' + '\n'.join(k + ' = ' + str(v) for k, v in s['modifiers'].items()))]
    for n in NODES:
        if n.get('state_programme'):
            iid = n['id'] + '_local_programme'
            dynamic += [block(iid, 'icon = GFX_idea_' + iid + '\n' + '\n'.join(k + ' = ' + str(v) for k, v in n['state_programme']['modifiers'].items()))]
            loc(iid, n['title'], n['implementation_note'])
    write('common/dynamic_modifiers/COLDWAR_GRE_1970_modifiers.txt', HEADER + '\n'.join(dynamic))
    loc(s['id'], s['title'], s['note'])


