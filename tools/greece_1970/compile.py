def effect(key, code):
    EFFECTS.append(block(P + key, code))


def option(label, code, chance=50, trigger=''):
    key = P + 'option_' + re.sub(r'[^a-z0-9]+', '_', label.lower()).strip('_')
    loc(key, label)
    return block('option', 'name = ' + key + '\nai_chance = { factor = ' + str(chance) + ' }\n' + (block('trigger', trigger) if trigger else '') + code)


def event(num, title, desc, options, trigger=BASE):
    loc(P + 'event_' + str(num) + '_t', title)
    loc(P + 'event_' + str(num) + '_d', desc)
    EVENTS.append(block('country_event', 'id = COLDWAR_GRE_TREE.' + str(num) + '\ntitle = ' + P + 'event_' + str(num) + '_t\ndesc = ' + P + 'event_' + str(num) + '_d\nis_triggered_only = yes\n' + block('trigger', trigger) + '\n'.join(options)))


def decision(key, title, desc, visible, available, code, cost=0, days=30):
    loc(P + key, title, desc)
    DECISIONS.append(block(P + key, 'icon = GFX_decision_generic_political_discourse\nallowed = { ' + BASE.replace('\n', ' ') + ' }\n' + block('visible', visible) + block('available', available) + 'cost = ' + str(cost) + '\ndays_re_enable = ' + str(days) + '\n' + block('complete_effect', code) + 'ai_will_do = { factor = 1 }'))


def government(party, selected=None, election=False):
    code = '\n'.join(clearflag('selected_' + x) for x in ('papadopoulos', 'ioannidis', 'gizikis', 'karamanlis', 'kanellopoulos', 'mavros', 'andreas_papandreou', 'florakis', 'koligiannis', 'constantine_ii', 'angellis', 'bonanos', 'zoitakis'))
    if selected: code += '\n' + setflag('selected_' + selected)
    code += '\nset_temp_variable = { rul_party_temp = ' + str(party) + ' }\nset_temp_variable = { disable_elections = ' + ('0' if election else '1') + ' }\nchange_ruling_party_effect = yes\n' + P + 'reconcile_programmes_effect = yes'
    return code


