def compile_rewards():
    for n in NODES:
        k = n['key']
        payload = []
        if n['political_power']: payload += ['add_political_power = ' + str(n['political_power'])]
        if n['stability']: payload += ['add_stability = ' + str(n['stability'])]
        if n['xp']: payload += [n['xp'][0] + '_experience = ' + str(n['xp'][1])]
        for bonus in n.get('research_bonuses', []):
            name = n['id'] + '_' + bonus['category'] + '_bonus'
            loc(name, n['title'])
            payload += ['add_tech_bonus = { name = ' + name + ' uses = ' + str(bonus['uses']) + ' bonus = ' + str(bonus['bonus']) + ' category = ' + bonus['category'] + ' }']
        if n.get('state_programme'):
            for state in n['state_programme']['states']:
                payload += [str(state) + ' = { if = { limit = { is_owned_by = GRE is_controlled_by = GRE } add_dynamic_modifier = { modifier = ' + n['id'] + '_local_programme } } }']
        if n.get('corruption_reduction'):
            payload += ['if = { limit = { OR = { ' + ' '.join('has_idea = corruption_level_' + str(i).zfill(2) for i in range(2, 11)) + ' } } decrease_corruption = yes }']
        pkg = n.get('regime_package')
        if pkg or n.get('clear_regime_on_transfer'):
            payload += [P + 'clear_regime_programmes_effect = yes']
            if n.get('clear_regime_on_transfer'):
                payload += ['remove_ideas = ' + P + x for x in ('rule_by_decree', 'security_state', 'reserve_powers', 'restricted_public_life')]
                payload += ['add_ideas = ' + P + 'unresolved_victim_claims', setflag('civilian_transfer_implemented')]
            if pkg:
                payload += ['remove_ideas = ' + P + x for x in pkg.get('removes', [])]
                if pkg['key'] == 'military_order':
                    payload += ['remove_ideas = ' + P + x for x in ('reserve_powers', 'restricted_public_life')]
                    payload += ['add_ideas = ' + P + x for x in ('rule_by_decree', 'security_state')]
                payload += ['add_ideas = ' + P + pkg['key'], setflag(pkg['flag'])]
                payload += ['add_ideas = ' + P + a['key'] for a in pkg.get('adds', [])]
                if pkg['key'] == 'civilian_order': payload += [setflag('civilian_transfer_implemented')]
                if pkg['key'] != 'civilian_order': payload += [clearflag('current_electoral_mandate_verified')]
        t = n.get('transition_package')
        if t: payload += ['remove_ideas = ' + P + t['key'], 'add_timed_idea = { idea = ' + P + t['key'] + ' days = ' + str(t['duration_days']) + ' }']
        if n['modifiers']:
            if n['modifier_slot']:
                for other in SLOTS[n['modifier_slot']]:
                    payload += ['remove_ideas = ' + other['id'] + '_programme']
                    # Retain each former government's chosen funded policy so
                    # a legitimate return can restore it without charging again.
                    # Eligibility still permits only the current party/person.
                    if (other['section'] if other['party'] is not None else None) == (n['section'] if n['party'] is not None else None):
                        payload += [clearflag(other['key'] + '_selected')]
                payload += [setflag(k + '_selected')]
            if n.get('duration_days'):
                payload += ['add_timed_idea = { idea = ' + n['id'] + '_programme days = ' + str(n['duration_days']) + ' }']
            else: payload += ['add_ideas = ' + n['id'] + '_programme']
        for change in n.get('spirit_changes', []):
            if change['operation'] == 'replace': payload += ['swap_ideas = { remove_idea = ' + change['id'] + ' add_idea = ' + change['id'] + '_rationed }']
        payload += ['remove_ideas = ' + P + r for r in n['removes'] if r != 'uneven_regions']
        if n['building']:
            b = n['building']
            payload += [str(b['state']) + ' = { add_building_construction = { type = ' + b['type'] + ' level = ' + str(b['level']) + (' province = ' + str(b['province']) if 'province' in b else '') + ' instant_build = no } }']
        payload += [setflag(k + '_granted'), clearflag(k + '_awaiting_funding')]
        if k in POST: payload += [POST[k]]
        if k in PROPOSALS: payload += [proposal_implementation(k)]
        gates = availability(n)
        if k in PROPOSALS:
            gates += '\n' + '\n'.join(flag(k + '_accepted_' + tag) for tag in PROPOSALS[k])
            if n['section'] == 'cyprus' or k in ('ioa_15', 'ioa_16'):
                gates += '\ncheck_variable = { var = ' + P + k + '_offer_instance value = CYP.COLDWAR_CYP_1970_crisis_instance compare = equals }'
        cost = n['treasury_cost_gdp_percent'] / 100
        if cost:
            gates += '\ncheck_variable = { gdp_total > 0 }\ncheck_variable = { var = treasury value = ' + P + 'programme_cost compare = greater_than_or_equals }'
            payload.insert(0, 'set_temp_variable = { treasury_change = ' + P + 'programme_cost }\nmultiply_temp_variable = { treasury_change = -1 }\nmodify_treasury_effect = yes')
        # The lender and Greek entries use exactly the same positive amount.
        if k == 'credit_loan':
            gates += '\nUSA = { exists = yes check_variable = { var = treasury value = GRE.' + P + 'credit_amount compare = greater_than_or_equals } }'
            payload.insert(0, 'USA = { set_temp_variable = { treasury_change = GRE.' + P + 'credit_amount } multiply_temp_variable = { treasury_change = -1 } modify_treasury_effect = yes }\nset_temp_variable = { treasury_change = ' + P + 'credit_amount }\nmodify_treasury_effect = yes\nset_temp_variable = { debt_change = ' + P + 'credit_amount }\nmodify_debt_effect = yes')
        grant = 'set_temp_variable = { ' + P + 'programme_cost = gdp_total }\nmultiply_temp_variable = { ' + P + 'programme_cost = ' + str(cost) + ' }\n'
        grant += block('if', block('limit', BASE + '\nNOT = { ' + flag(k + '_granted') + ' }\n' + gates) + '\n'.join(payload))
        effect('grant_' + k, grant)
        if k in PROPOSALS:
            complete = P + 'send_' + k + ' = yes'
        else:
            complete = P + 'grant_' + k + ' = yes'
        effect('complete_' + k, block('if', block('limit', BASE + '\nNOT = { ' + flag(k + '_granted') + ' }') + complete + '\n' + block('if', block('limit', 'NOT = { ' + flag(k + '_granted') + ' }') + setflag(k + '_awaiting_funding'))))
        decision('retry_' + k, 'Implement: ' + n['title'], 'Retry a completed programme after funding, domestic prerequisites or an agreed contract become available. Grants and payments occur once.',
                 'has_completed_focus = ' + n['id'] + '\n' + flag(k + '_awaiting_funding') + '\nNOT = { ' + flag(k + '_granted') + ' }',
                 availability(n), P + 'complete_' + k + ' = yes', days=30)


def proposal_implementation(k):
    if k in ('cyprus_2', 'cyprus_4'):
        return setflag('civilian_control_protocol_implemented')
    if k in ('cyprus_3', 'cyprus_5', 'ioa_15'):
        return 'CYP = { if = { limit = { NOT = { has_country_flag = COLDWAR_CYP_1970_gre_sponsorship_accepted } } set_country_flag = COLDWAR_CYP_1970_gre_sponsorship_accepted add_to_variable = { COLDWAR_CYP_1970_coup_pressure = 10 } clamp_variable = { var = COLDWAR_CYP_1970_coup_pressure min = 0 max = 100 } } }'
    if k in ('cyprus_8', 'cyprus_10', 'cyprus_13', 'cyprus_15'):
        return setflag('crisis_diplomatic_status_recorded') + '\nCOLDWAR_CYP_1970_GRE_publish_response = yes'
    if k in ('aegean_2', 'aegean_3'):
        return setflag('aegean_response_recorded') + '\n' + setflag('aegean_negotiations_accepted')
    return ''


def compile_proposals():
    num = 100
    for k, targets in PROPOSALS.items():
        n = BY[k]
        sends = []
        crisis_offer = n['section'] == 'cyprus' or k in ('ioa_15', 'ioa_16')
        if crisis_offer:
            reset = '\n'.join(clearflag(k + suffix + tag) for tag in targets for suffix in ('_accepted_', '_pending_', '_live_'))
            sends += [block('if', block('limit', 'NOT = { check_variable = { var = ' + P + k + '_offer_instance value = CYP.COLDWAR_CYP_1970_crisis_instance compare = equals } }') + reset)]
            sends += ['set_variable = { ' + P + k + '_offer_instance = CYP.COLDWAR_CYP_1970_crisis_instance }']
        if k == 'credit_loan': sends += ['if = { limit = { NOT = { has_variable = ' + P + 'credit_amount } } set_variable = { ' + P + 'credit_amount = gdp_total } multiply_variable = { ' + P + 'credit_amount = 0.02 } }']
        for tag in targets:
            num += 1
            pending = k + '_pending_' + tag
            live = k + '_live_' + tag
            accept = k + '_accepted_' + tag
            sends += [block('if', block('limit', 'country_exists = ' + tag + '\nNOT = { ' + flag(accept) + ' }\nNOT = { ' + flag(live) + ' }') + setflag(pending) + '\nset_country_flag = { flag = ' + P + live + ' days = 90 value = 1 }\n' + clearflag(k + '_refused_' + tag) + '\n' + clearflag(k + '_timed_out_' + tag) + '\n' + tag + ' = { ' + eventcall(num) + ' }')]
            # Checking the current Greek political conditions rejects stale
            # event options after a government change. The live flag bounds it.
            guard = 'GRE = { exists = yes ' + flag(pending) + ' ' + flag(live) + '\n' + availability(n) + '\n}'
            if crisis_offer:
                guard = guard[:-1] + 'check_variable = { var = ' + P + k + '_offer_instance value = CYP.COLDWAR_CYP_1970_crisis_instance compare = equals }\n}'
            accepted = clearflag(pending) + '\n' + clearflag(live) + '\n' + setflag(accept) + '\n' + P + 'grant_' + k + ' = yes'
            declined = clearflag(pending) + '\n' + clearflag(live) + '\n' + setflag(k + '_refused_' + tag)
            if k.startswith('cyprus_'):
                declined += '\n' + setflag('mission_proposal_refused') + '\n' + setflag('crisis_diplomatic_status_recorded')
            if k.startswith('aegean_'): declined += '\n' + setflag('aegean_response_recorded')
            options = [option('Accept the named Greek proposal', 'GRE = { ' + accepted + ' }', 50, guard),
                       option('Refuse the proposal', 'GRE = { ' + declined + ' }', 25, guard),
                       option('Request revised terms', 'GRE = { ' + clearflag(pending) + '\n' + clearflag(live) + '\n' + setflag(k + '_negotiating_' + tag) + ' }', 15, guard),
                       option('Defer a decision', 'GRE = { ' + clearflag(pending) + '\n' + clearflag(live) + '\n' + setflag(k + '_deferred_' + tag) + ' }', 10, guard),
                       option('Close an obsolete proposal', '', 1, 'NOT = { ' + guard + ' }')]
            desc = 'Greece proposes: ' + n['title'] + '. ' + n['event_contract'] + '\nAcceptance authorises the stated domestic Greek programme only. No territory, alliance entry or equipment transfer is granted.'
            if k == 'credit_loan': desc += '\nCredit line: 2% of current Greek GDP, frozen at dispatch. On implementation the lender pays that exact sum and Greek treasury and debt rise by that sum.'
            event(num, 'Greek proposal: ' + n['title'], desc, options, 'original_tag = ' + tag + '\nexists = yes\nIMP_is_1970_scenario = yes\n' + guard)
        sends += [P + 'grant_' + k + ' = yes']
        effect('send_' + k, block('if', block('limit', BASE + '\n' + availability(n) + '\nNOT = { ' + flag(k + '_granted') + ' }') + '\n'.join(sends)))


def compile_reconcile():
    clear = []
    for key in ('military_order', 'controlled_order', 'civilian_order', 'socialist_executive_order', 'royal_executive_order'):
        clear += ['remove_ideas = ' + P + key]
    for key in ('military_government_active', 'controlled_government_active', 'civilian_government_active', 'civilian_transfer_implemented', 'socialist_executive_government_active', 'royal_executive_settlement_implemented'):
        clear += [clearflag(key)]
    for n in NODES:
        if n['modifiers'] and (n['modifier_slot'] in ('officer_compact', 'controlled_constitution', 'regime_development') or n['party'] is not None):
            clear += ['remove_ideas = ' + n['id'] + '_programme']
    effect('clear_regime_programmes_effect', '\n'.join(clear))
    reconcile = []
    for n in NODES:
        if n.get('state_programme'):
            for state in n['state_programme']['states']:
                reconcile += [str(state) + ' = { if = { limit = { is_owned_by = GRE is_controlled_by = GRE GRE = { ' + flag(n['key'] + '_granted') + ' } } add_dynamic_modifier = { modifier = ' + n['id'] + '_local_programme } } else = { remove_dynamic_modifier = ' + n['id'] + '_local_programme } }']
        if not n['modifiers']: continue
        gates = availability(n) + '\n' + flag(n['key'] + '_granted')
        if n['modifier_slot']: gates += '\n' + flag(n['key'] + '_selected')
        iid = n['id'] + '_programme'
        if n.get('duration_days'):
            # A suspended/expired timed programme never starts a new clock.
            reconcile += [block('if', block('limit', 'NOT = {\n' + gates + '\n}') + 'remove_ideas = ' + iid)]
        else:
            reconcile += [block('if', block('limit', gates) + 'add_ideas = ' + iid), 'else = { remove_ideas = ' + iid + ' }']
    effect('reconcile_programmes_effect', '\n'.join(reconcile))


