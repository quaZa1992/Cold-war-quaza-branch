def compile_tree():
    tree = ['id = ' + P + 'focus', 'default = no', 'reset_on_civilwar = no',
            'country = { factor = 0 modifier = { add = 100 original_tag = GRE IMP_is_1970_scenario = yes } }',
            'initial_show_position = { focus = ' + LAYOUT['initial_show_position']['focus'] + ' }',
            'continuous_focus_position = { x = ' + str(LAYOUT['continuous_focus_position']['x']) + ' y = ' + str(LAYOUT['continuous_focus_position']['y']) + ' }']
    for s in D['sections']:
        target = next(n for n in NODES if n['section'] == s['id'])['id']
        key = P + 'shortcut_' + s['id']
        loc(key, s['title'])
        tree += [block('shortcut', 'name = ' + key + '\ntarget = ' + target + '\nscroll_wheel_factor = 0.80')]
    for s in LAYOUT['extra_shortcuts']:
        key = P + s['key']
        loc(key, s['title'])
        tree += [block('shortcut', 'name = ' + key + '\ntarget = ' + s['target'] + '\nscroll_wheel_factor = 0.80')]
    for n in NODES:
        focus = ['id = ' + n['id'], 'icon = GFX_' + P + n['icon'], 'x = ' + str(n['x']), 'y = ' + str(n['y']),
                 'cost = ' + str(n['focus_cost']), 'cancel_if_invalid = yes', 'continue_if_invalid = no', 'available_if_capitulated = no']
        focus += [block('prerequisite', '\n'.join('focus = ' + p for p in group)) for group in n['prerequisite_groups']]
        # A completed predecessor may still be awaiting its payment/contract.
        # Gate ordinary edges on implemented outcomes, so bypass never pays it.
        gates = availability(n)
        for group in n['prerequisite_groups']:
            gates += '\nOR = { ' + ' '.join(flag(p.removeprefix(P) + '_granted') for p in group) + ' }'
        if n['excludes']: focus += [block('mutually_exclusive', '\n'.join('focus = ' + p for p in n['excludes']))]
        if n.get('search_filters'): focus += ['search_filters = { ' + ' '.join(n['search_filters']) + ' }']
        summary = reward_summary(n)
        reward = P + 'complete_' + n['key'] + ' = yes'
        if summary:
            loc(n['id'] + '_programme_effects_tt', 'Implemented programme effects:\n' + summary + '\nSubject to the stated funding, government and agreement conditions.')
            reward = 'custom_effect_tooltip = ' + n['id'] + '_programme_effects_tt\n' + reward
        focus += [block('available', gates), block('completion_reward', reward), 'ai_will_do = { factor = 10 }']
        tree += [block('focus', '\n'.join(focus))]
        desc = n['note'] or n['title'] + '.'
        if n.get('implementation_note'): desc += '\n\n' + n['implementation_note']
        if summary: desc += '\n\nProgramme effects:\n' + summary
        if n['requirements']: desc += '\n\nConditions: ' + n['requirements']
        if n['treasury_cost_gdp_percent']: desc += '\n\nImplementation costs ' + str(n['treasury_cost_gdp_percent']) + '% of current GDP from the treasury. Unfunded completion can be implemented later through decisions.'
        if n['key'] in PROPOSALS: desc += '\n\nProposal to ' + ', '.join(PROPOSALS[n['key']]) + ': accept, revised terms, defer or refuse. Silence expires after 90 days and never counts as agreement. Domestic effects require acceptance and funding.'
        if n.get('tradeoff'):
            for group in ('benefits', 'costs', 'lasting'):
                if n['tradeoff'].get(group): desc += '\n\n' + group.title() + ': ' + ' '.join(n['tradeoff'][group])
        loc(n['id'], n['title'], desc)
    write('common/national_focus/COLDWAR_GRE_1970_focus.txt', HEADER + block('focus_tree', '\n'.join(tree)))


