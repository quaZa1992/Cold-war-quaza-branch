def write(rel, data, bom=False):
    path = ROOT / rel
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text('\n'.join(line.rstrip() for line in data.splitlines()) + '\n', encoding='utf-8-sig' if bom else 'utf-8', newline='\n')
    GENERATED.append(rel)


def clean(code):
    return '\n'.join(s.rstrip() for s in code.splitlines() if s.strip() and not s.lstrip().startswith('#')).strip()


def block(key, code):
    return key + ' = {\n' + '\n'.join('\t' + line for line in code.splitlines()) + '\n}\n'


def flag(key):
    return 'has_country_flag = ' + P + key


def setflag(key):
    return 'set_country_flag = ' + P + key


def clearflag(key):
    return 'clr_country_flag = ' + P + key


def eventcall(num):
    return 'country_event = { id = COLDWAR_GRE_TREE.' + str(num) + ' days = 1 }'


def loc(key, title, desc=None):
    LOC[key] = title
    if desc is not None:
        LOC[key + '_desc'] = desc


