def availability(n, outcomes=True):
    code = clean(n['available_code'])
    # Remove inline documentation as well, while preserving native expressions.
    code = '\n'.join(s.split('#')[0].rstrip() for s in code.splitlines())
    # A separate revolution was only an extension contract in the draft. The
    # implemented KKE route uses an actual legal mandate and ratification.
    code = code.replace(' ' + flag('socialist_revolution_resolved'), '')
    if not outcomes and n.get('actual_outcome_flag'):
        code = code.replace(flag(n['actual_outcome_flag']), '')
    k = n['key']
    extra = []
    if n['section'] == 'regime' and k not in ('opening_handover', 'credible_election', 'constitutional_question', 'civilian_enterprise', 'civilian_reconstruction', 'civilian_settlement', 'civilian_accountability', 'civilian_retirement', 'open_courts', 'retirement_guarantees', 'civilian_institutions'):
        extra += ['check_variable = { ruling_party = 22 }']
    if k == 'army_6':
        extra += ['NOT = { has_idea = ' + P + 'security_compact_programme }',
                  'NOT = { has_idea = ' + P + 'ioa_2_programme }']
    if k == 'foreign_6':
        extra += ['has_completed_focus = ' + P + 'foreign_4', 'NOT = { has_idea = ' + P + 'security_state }',
                  'NOT = { has_idea = ' + P + 'restricted_public_life }']
    if k == 'energy_recovery':
        extra += ['check_variable = { imp_oil_factor_t < 76 }', 'NOT = { has_idea = imp_oil_shock }']
    if k == 'cyprus_6':
        code = code.replace(flag('mission_proposal_refused'), flag('mission_proposal_refused') + ' ' + flag('mission_proposal_timed_out'))
    if n['section'] == 'aegean':
        extra += [flag('aegean_dispute_active')]
        if k == 'aegean_4': extra += [flag('aegean_response_recorded')]
        if k == 'aegean_5': extra += [flag('aegean_negotiations_accepted')]
    if k in ('cyprus_7', 'cyprus_8', 'cyprus_9', 'cyprus_10', 'cyprus_11', 'cyprus_12', 'cyprus_13', 'cyprus_14', 'cyprus_15', 'cyprus_16', 'cyprus_17'):
        extra += ['CYP = { has_country_flag = COLDWAR_CYP_1970_crisis_active }']
    if k == 'cyprus_13': extra += ['CYP = { has_country_flag = COLDWAR_CYP_1970_ceasefire_proposal_accepted }']
    if k in ('cyprus_18', 'cyprus_19'): extra += [flag('civilian_harm_verified')]
    if k == 'credit_loan': extra += [flag('financing_gap_verified')]
    if n.get('required_settlement'):
        extra += ['CYP = { has_country_flag = COLDWAR_CYP_1970_final_settlement_implemented }']
    if n.get('state_programme'):
        extra += ['OR = { ' + ' '.join(str(s) + ' = { is_owned_by = GRE is_controlled_by = GRE }' for s in n['state_programme']['states']) + ' }']
    if n['building']:
        b = n['building']
        prov = ' province = ' + str(b['province']) if 'province' in b else ''
        extra += ['owns_state = ' + str(b['state']), 'controls_state = ' + str(b['state']),
                  str(b['state']) + ' = { free_building_slots = { building = ' + b['type'] + ' size > 0' + prov + ' } }']
    # Design funding gates referred to a shock which rationing replaces.
    if k == 'energy_ration':
        code = code.replace('has_idea = ' + P + 'oil_shock', 'OR = { has_idea = ' + P + 'oil_shock has_idea = ' + P + 'oil_shock_rationed }')
    return code + '\n' + '\n'.join(extra)


