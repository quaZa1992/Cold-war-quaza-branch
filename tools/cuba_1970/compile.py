def economic_guard(n):
    """Gameplay conditions remain visible; internal routing/receipts stay hidden."""
    parts = []
    for e in n['effects']:
        if e['kind'] == 'building':
            s, b = e['state'], e['building']
            province = f' province = {e["province"]}' if e.get('province') else ''
            parts += [f'owns_state = {s}', f'controls_state = {s}']
            if e.get('province'):
                parts.append(f'controls_province = {e["province"]}')
            # IMPERIA COLD WAR — Infrastructure uses MD's state level cap, not shared slots.
            if b == 'infrastructure':
                parts.append(f'{s} = {{ check_variable = {{ building_level@infrastructure < 6 }} }}')
            else:
                parts.append(cub_silo_queries(f'{s} = {{ free_building_slots = {{ building = {b} size > {e["level"]-1} include_locked = no{province} }} }}'))
        if e['kind'] == 'law':
            helper = e['helper']
            if helper == 'decrease_corruption':
                cond = tiers('corruption_level', 10)
                label = 'A functioning public oversight system'
            elif helper == 'increase_education_budget':
                cond, label = tiers('edu', 5), 'An established education budget'
            elif helper == 'increase_healthcare_budget':
                cond, label = tiers('health', 6), 'An established healthcare budget'
            else:
                raise ValueError('Unreviewed law helper '+helper)
            tooltip = loc(P+helper+'_valid_tt', label)
            parts.append(f'custom_trigger_tooltip = {{ tooltip = {tooltip} {cond} }}')
    return parts


