def law_code(helper):
    if helper == 'decrease_corruption':
        return ('if = { limit = { OR = { '+' '.join(f'has_idea = corruption_level_{i:02d}' for i in range(2, 11))+' } } decrease_corruption = yes }\n'
                'else_if = { limit = { has_idea = corruption_level_01 } add_ideas = COLDWAR_CUB_oversight_efficiency }')
