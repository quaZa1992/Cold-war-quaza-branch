def emit(rel, text, localisation=False):
    path = ROOT/rel
    path.parent.mkdir(parents=True, exist_ok=True)
    if not localisation:
        # IMPERIA COLD WAR — Country-event pictures use the native MD photo viewport.
        if rel.startswith('events/'):
            text = event_art.bind(text)
        text = HEADER+format_code(text)
    # IMPERIA COLD WAR — Replace a complete file; never truncate a live provider on a failed write.
    temporary = path.with_name(path.name+'.coldwar.tmp')
    temporary.write_text(text, encoding='utf-8-sig' if localisation else 'utf-8', newline='\n')
    temporary.replace(path)
    OUTPUTS.append(dict(project='IMPERIA COLD WAR', path=rel, sha256=hashlib.sha256(path.read_bytes()).hexdigest()))


def loc(key, text):
    # Repair legacy display decoding in names and separators, without changing
    # the immutable approved source or any gameplay values/identifiers.
    text = text.replace('\u00e2\u20ac\u201c', '\u2013').replace('\u00c2\u00b7', '\u00b7')
    text = re.sub(r'\u00c3[\u0080-\u00bf]',
                  lambda match: match[0].encode('latin-1').decode('utf-8'), text)
    text = text.replace(' \u2014 ', '. ').replace(' \u2013 ', ': ').replace('\u2014', ':').replace('\u2013', '-')
    if key in LOC and LOC[key] != text:
        raise ValueError('Conflicting localisation '+key)
    LOC[key] = text
    return key


