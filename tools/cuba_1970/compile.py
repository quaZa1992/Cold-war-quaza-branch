def make_tree():
    body = ['id = COLDWAR_CUB_1970_focus',
            'country = { factor = 0 modifier = { add = 40 tag = CUB IMP_is_1970_scenario = yes } }',
            'default = no', 'reset_on_civilwar = no',
            'initial_show_position = { focus = COLDWAR_CUB_popular_power }',
            'continuous_focus_position = { x = 50 y = 3600 }']
    body.append('shortcut = { name = COLDWAR_CUB_GEN_naval_reform target = COLDWAR_CUB_GEN_naval_reform scroll_wheel_factor = 0.8 }')
    for g in GROUPS:
        key = loc(P+'shortcut_'+g['id'], g['label'])
        body.append(f'shortcut = {{ name = {key} target = {g["nodes"][0]} scroll_wheel_factor = 0.8 }}')
    # IMPERIA COLD WAR — HOI4 resolves relative anchors at declaration time.
    ordered, seen, visiting = [], set(), set()
    def append_focus(n):
        if n['id'] in seen:
            return
        if n['id'] in visiting:
            raise ValueError('Cyclic relative focus anchor: '+n['id'])
        visiting.add(n['id'])
        if n['anchor']:
            append_focus(BY[n['anchor']])
        visiting.remove(n['id']); seen.add(n['id']); ordered.append(n)
    for n in NODES:
        append_focus(n)
    for n in ordered:
        loc(n['id'], n['native_title'])
        loc(n['id']+'_desc', n['description'])
        x, y = n['local_xy'] if n['anchor'] else n['xy']
        rows = [f'id = {n["id"]}', f'icon = {n["icon"]}', f'x = {x}', f'y = {y}', f'cost = {n["cost"]}',
                'cancel_if_invalid = yes', 'continue_if_invalid = no', 'available_if_capitulated = no']
        if n['anchor']:
            rows.append('relative_position_id = '+n['anchor'])
        rows += ['prerequisite = { '+' '.join('focus = '+p for p in ps)+' }' for ps in n['prerequisites']]
        if n['mutually_exclusive']:
            rows.append('mutually_exclusive = { '+' '.join('focus = '+p for p in n['mutually_exclusive'])+' }')
        rows.append('available = { '+P+'can_'+n['key']+' = yes }')
        filter_name = 'ECONOMIC' if n['group'] in ('economy', 'society') else 'ARMY' if n['group'] == 'defence' else 'POLITICAL'
        rows.append('search_filters = { FOCUS_FILTER_'+filter_name+' }')
        preview = '\n'.join([policy_preview(n)]+[direct(e, n, True) for e in n['effects']])
        # IMPERIA COLD WAR — Full prospective bilateral terms remain visible before consent.
        if n.get('partner'):
            preview += '\n'+foreign_contracts.preview(n)
        rows.append('completion_reward = { log = "[GetDateText]: [Root.GetName]: Focus '+n['id']+'"\neffect_tooltip = { '+preview+' }\nhidden_effect = { '+P+'apply_'+n['key']+' = yes } }')
        ai = 'base = 1'
        # Historical priorities shape AI without locking a player into history.
        if n['key'] in ('finish_zafra', 'sugar_exports', 'protected_enterprises', 'rectification', 'thaelmann_name'):
            ai = 'base = 3'
        rows.append('ai_will_do = { '+ai+' }')
        body.append(block('focus', '\n'.join(rows)))
    for key, text in generic_navy.localisation().items():
        loc(key, text)
    body += generic_navy.scripts()
    emit('common/national_focus/COLDWAR_CUB_1970_focus.txt', block('focus_tree', '\n'.join(body)))


def registry():
    reg = {}
    for provider in (GAME, MD, ROOT):
        for p in sorted((provider/'interface').glob('*.gfx')):
            for m in re.finditer(r'(?i)spritetype\s*=\s*\{([^{}]*)\}', p.read_text(encoding='utf-8-sig', errors='replace'), re.S):
                name = re.search(r'\bname\s*=\s*"([^"]+)"', m[1])
                tex = re.search(r'(?i)\btexturefile\s*=\s*"([^"]+)"', m[1])
                if name and tex:
                    reg[name[1]] = tex[1].replace('\\', '/')
    return reg


