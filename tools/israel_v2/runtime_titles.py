def _semantics(data):
    result = deepcopy(data)
    for node in result['nodes']:
        node.pop('label', None)
        node.pop('full_label', None)
    return result


def apply(data):
    """Deep-copy concise English titles, preserving every other catalogue field."""
    result = deepcopy(data)
    before = _semantics(data)
    for node in result['nodes']:
        node['full_label'] = node.get('full_label', node['label'])
        node['label'] = TITLES.get(node['id'].removeprefix('ISR2_'), node['full_label'])
        assert len(node['label']) <= 25, ('Native focus title needs editorial review', node['id'], node['label'])
        assert '\u2013' not in node['label'] and '\u2014' not in node['label']
    assert _semantics(result) == before, 'Title editing changed a policy or reward'
    return result
