        trigger_rows.append(block(P+'can_apply_'+n['key'],'\n'.join(live)))
        # Runtime guards retain the scenario, host and delivered-parent checks.
        # The graph already presents the parents; internal dispatch must not
        # expand into date bounds, country lists and receipt flags in hovers.
        availability=block('hidden_trigger',P+'can_apply_'+n['key']+' = yes')+'has_idea = idea_gcc_member_state\nis_subject = no'
        fields = ['id = '+n['id'],'icon = '+alias,'x = '+str(n['xy'][0]),'y = '+str(n['xy'][1]),f'cost = {n["cost"]:g}',
                  'cancel_if_invalid = yes','continue_if_invalid = no',block('available',availability),
                  'search_filters = { FOCUS_FILTER_POLITICAL FOCUS_FILTER_ECONOMY }','ai_will_do = { factor = 1 }']
        if n['key']==ROOT_KEY:
            fields += [block('allow_branch',P+'host = yes'),block('offset','x = 16\ny = 7\ntrigger = { tag = UAE }')]
        else: fields.append('relative_position_id = '+P+ROOT_KEY)
