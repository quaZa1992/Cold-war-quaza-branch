def install():
    outputs=build()
    changed=install_legacy()
    for relative,text in outputs.items():
        target=ROOT/relative
        target.parent.mkdir(parents=True,exist_ok=True)
        payload=text.encode('utf-8-sig' if target.suffix=='.yml' else 'utf-8')
        if not target.exists() or target.read_bytes()!=payload:
            target.write_bytes(payload);changed.append(relative)
    # The generic's advertised historical generator is absent from this
    # checkout. Preserve every node and existing shared attachment verbatim.
    generic=ROOT/'common/national_focus/mdcw_1970_generic_focus.txt'
    raw=generic.read_bytes();text=raw.decode('utf-8')
    begin='# COLDWAR GCC ATTACHMENT BEGIN'
    addition=begin+'\n\tshared_focus = '+P+ROOT_KEY+'\n\tshortcut = { name = '+P+'shortcut target = '+P+ROOT_KEY+' scroll_wheel_factor = 0.8 }\n\t# COLDWAR GCC ATTACHMENT END'
    if begin in text:
        text=re.sub(re.escape(begin)+r'.*?# COLDWAR GCC ATTACHMENT END',lambda _:addition,text,flags=re.S)
    else:
        text=text.replace('\tid = mdcw_1970_generic_focus','\t'+addition+'\n\tid = mdcw_1970_generic_focus',1)
    if text.encode('utf-8')!=raw:
        generic.write_bytes(text.encode('utf-8'));changed.append(str(generic.relative_to(ROOT)))
    record={'focuses':len(NODES),'founding_tags':TAGS,'outputs':{r:hashlib.sha256((ROOT/r).read_bytes()).hexdigest() for r in outputs},'nodes':NODES}
    (HERE/'manifest.json').write_text(json.dumps(record,indent=2)+'\n',encoding='utf-8')
