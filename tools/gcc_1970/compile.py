    native_text = ''.join(p.read_text(encoding='utf-8-sig') for p in [
        ROOT/'localisation/english/MD_dm_modifiers_l_english.yml',
        Path('E:/SteamLibrary/steamapps/common/Hearts of Iron IV/localisation/english/modifiers_l_english.yml')])
    formatters = set(re.findall(r'(?m)^\s*([^\s:#]+):',native_text))
    modifiers = sorted({key for n in NODES for key in n['modifiers']})
