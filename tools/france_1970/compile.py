def equipment_profiles(n):
    """Removable country ideas, using actual DLC-specific MD archetypes."""
    profiles = []
    for bba in (True, False):
        targets = {}
        for family, amount in n.get('equipment', {}).items():
            variants = D['equipment_families'][family]['targets']
            names = variants.get('all', variants.get('By Blood Alone' if bba else 'without By Blood Alone', []))
            for target in names:
                targets[target] = round(targets.get(target, 0) + amount, 5)
        profiles.append(targets)
    if not any(profiles):
        return []
    if profiles[0] == profiles[1]:
        return [(n['id'] + '_equipment', [], profiles[0])]
    return [(n['id'] + '_equipment_bba', ['has_dlc = "By Blood Alone"'], profiles[0]),
            (n['id'] + '_equipment_legacy', ['NOT = { has_dlc = "By Blood Alone" }'], profiles[1])]

