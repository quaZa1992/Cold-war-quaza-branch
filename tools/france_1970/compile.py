def num(v):
    return f'{v:.5f}'.rstrip('0').rstrip('.') if isinstance(v, float) else str(v)

def block(key, *rows):
    text = '\n'.join(str(x) for x in rows if x)
    return key + ' = {\n' + '\n'.join('\t' + line for line in text.splitlines()) + '\n}'

def write(rel, text):
    path = ROOT / rel
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(HEADER + text + '\n', encoding='utf-8', newline='\n')

def clean(s):
    # Repair legacy seed mojibake only when the entire round trip is valid.
    if any(x in s for x in ('\u00e2\u20ac', '\u00c3', '\u00c2')):
        try:
            s = s.encode('cp1252').decode('utf-8')
        except (UnicodeError, LookupError):
            s = s.replace('â€™', '’').replace('â€“', '–').replace('â€”', '—').replace('Â·', '·')
    return s

def loc(key, value):
    LOC[key] = clean(value)
    return key

def govt(g):
    return f'COLDWAR_FRA_{g}_government = yes'

def earned(n):
    return n['id'] + '_earned'

def variant_when(v):
    w = v.get('when', {})
    rows = []
    if w.get('has_dlc'):
        rows.append(f'has_dlc = "{w["has_dlc"]}"')
    if w.get('not_has_dlc'):
        rows.append(f'NOT = {{ has_dlc = "{w["not_has_dlc"]}" }}')
    return rows

def research_guard(effect):
    variants = []
    for v in effect.get('target_variants', []):
        rows = variant_when(v)
        rows += [f'is_special_project_completed = sp:{p}' for p in v.get('required_projects', [])]
        rows += [block('OR', *[f'NOT = {{ has_tech = {t} }}' for t in v['technologies']])]
        variants.append(block('AND', *rows))
    return block('OR', *variants) if variants else ''

def bonus_body(e, technologies=None):
    rows = [f'name = {e["name"]}', f'bonus = {num(e["bonus"])}', f'uses = {e["uses"]}']
    rows += [f'technology = {t}' for t in technologies or []]
    if e.get('category'):
        rows.append('category = ' + e['category'])
    return block('add_tech_bonus', *rows)

def one_time(e):
    if e['kind'] == 'doctrine':
        return block('add_doctrine_cost_reduction', f'cost_reduction = {num(e["bonus"])}', f'uses = {e["uses"]}', f'category = {e["branch"]}_doctrine')
    if e['kind'] != 'tech_bonus':
        return f'{e["kind"]} = {num(e["amount"])}'
    loc(e['name'], e.get('target_label') or next(n['title'] for n in NODES if e in n['one_time_effects']))
    variants = e.get('target_variants')
    if not variants:
        return bonus_body(e)
    # DLC selects the real technology IDs; project eligibility guards execution elsewhere.
    return '\n'.join(block('if', block('limit', *variant_when(v)), bonus_body(e, v['technologies'])) if variant_when(v) else bonus_body(e, v['technologies']) for v in variants)

def guards(n, include_research=True):
    rows = [govt(n['group']), f'NOT = {{ has_country_flag = {earned(n)} }}']
    for parents in n['parents']:
        rows.append(block('OR', *[f'has_country_flag = COLDWAR_FRA_{p}_earned' for p in parents]))
    rows += [f'NOT = {{ has_country_flag = COLDWAR_FRA_{p}_earned }}' for p in n['exclusive']]
    if include_research:
        rows += [research_guard(e) for e in n['one_time_effects'] if e['kind'] == 'tech_bonus']
    if n.get('offer_id'):
        rows.append(n['offer_id'] + '_can_send = yes')
    return rows

