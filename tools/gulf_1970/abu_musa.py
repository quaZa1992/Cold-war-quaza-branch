def block(key, body):
    body = re.sub(r'(?m)^ +', lambda m:'\t'*len(m[0]), body.strip())
    return key + ' = {\n' + '\n'.join('\t' + line if line else '' for line in body.splitlines()) + '\n}\n'


def localise(entries):
    return 'l_english:\n# IMPERIA CW — Cold War: gulf 1970 English localisation.\n' + ''.join(' ' + k + ':0 "' + v.replace('\\', '\\\\').replace('"', '\\"').replace('\n', '\\n') + '"\n' for k, v in entries.items())


def state_history():
    path = ROOT / 'history/states/1119-Abumusa.txt'
    text = path.read_text(encoding='utf-8-sig').replace('\r\n', '\n')
    if '# COLDWAR ABU MUSA HISTORY BEGIN' in text:
        return text
    match = re.search(r'(?m)^\t\t1970\.1\.1 = \{\n', text)
    assert match, 'Missing authored Abu Musa 1970 state snapshot'
    closing = text.index('\n\t\t}', match.end())
    snapshot = text[match.start():closing + len('\n\t\t}')]
    assert snapshot.count('owner = PER') == 1 and snapshot.count('controller = PER') == 1
    snapshot = snapshot.replace('owner = PER', 'owner = UAE').replace('controller = PER', 'controller = UAE')
    snapshot = snapshot.replace('\n\t\t\tadd_manpower', '\n\t\t\tremove_core_of = PER\n\t\t\tadd_claim_by = PER\n\t\t\tadd_manpower', 1)
    corrected = ('\t\t# IMPERIA CW — Cold War: gulf 1970 generated content.\n\t\t# COLDWAR ABU MUSA HISTORY BEGIN\n\t\t# Sharjah administers Abu Musa before the 1971 settlement; Iran contests sovereignty.\n'
                 + snapshot + '\n'
                 '\t\t# Preserve the native 2000 map without pre-enacting a 1971 outcome in this campaign.\n'
                 '\t\t2000.1.1 = {\n\t\t\towner = PER\n\t\t\tcontroller = PER\n'
                 '\t\t\tadd_core_of = PER\n\t\t\tremove_claim_by = PER\n\t\t}\n'
                 '\t\t# COLDWAR ABU MUSA HISTORY END')
    return text[:match.start()] + corrected + text[closing + len('\n\t\t}'):]


