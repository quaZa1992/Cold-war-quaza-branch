def install():
    outputs = build()
    for rel, text in outputs.items():
        path = ROOT / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        data = text.encode('utf-8-sig' if path.suffix == '.yml' else 'utf8')
        if not path.exists() or path.read_bytes() != data:
            path.write_bytes(data)
    manifest = {rel: hashlib.sha256((ROOT/rel).read_bytes()).hexdigest() for rel in outputs}
    (HERE/'abu_musa_manifest.json').write_text(json.dumps(manifest, indent=2)+'\n', encoding='utf8')
    print(json.dumps({'outputs': len(outputs), 'state':1119, 'decisions':2, 'engine_tested':False}))


if __name__ == '__main__':
    install()
