def research(rs,name):return ''.join('add_tech_bonus = { name = '+name+' category = '+r['category']+' bonus = '+num(r['bonus'])+' uses = '+str(r['uses'])+' }\n' for r in rs)
def leader(names):return block('OR','\n'.join('has_country_leader = { name = '+json.dumps(name,ensure_ascii=False)+' ruling_only = yes }' for name in names))
def owner(n):
    rows=[]
    if n.get('party') is not None:rows.append(TRIGGERS[n['party']]+' = yes')
    if n.get('leader_names'):rows.append(leader(n['leader_names']))
    if n.get('temporary')=='war':rows.append('has_war_with = ENG')
    if n.get('active_requirements'):rows.append(flag('corporate_constitution'))
    return '\n'.join(rows) or 'always = yes'

def runtime_design(approved):
    d=copy.deepcopy(approved)
    d['status']='IMPLEMENTED: approved Argentina national programme'
    # Pay when the physical mine is granted, avoiding a stranded prepaid project.
    mine=next(n for n in d['nodes'] if n['key']=='uranium_development')
    amount=mine['money'];mine['money']=0
    dec=next(a for a in d['decisions'] if a['key']=='uranium_mine');dec['money']=amount
    # These settlements replace the same coercive policy, rather than leaving its malus forever.
    for n in d['nodes']:
        if n['key'] in ('social_pact','collective_bargaining','cgta_mandate','union_mandate'):
            if P+'wage_freeze' not in n['remove']:n['remove'].append(P+'wage_freeze')
    d['implementation_adjustments']=[
      'The sponsored uranium mine costs 1% of live Argentine GDP, charged in its construction decision with the native capacity/ownership/slot grant transaction.',
      'Constitutional-election preparation does not remove the regime spirit before the elected government actually takes office.',
      'Independent party labor settlements remove the superseded wage-restraint spirit so its stated remedy is reachable.'
    ]
    return compact(annotate(d))

