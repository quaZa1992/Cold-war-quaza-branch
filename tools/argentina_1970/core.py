def num(v):return f'{v:.5f}'.rstrip('0').rstrip('.') if isinstance(v,float) else str(v)
def block(k,s):return k+' = {\n'+s+'\n}\n'
def iff(g,s,other=''):return block('if',block('limit',g)+s)+(block('else',other) if other else '')
def flag(s):return 'has_country_flag = '+P+s
def setflag(s,days=None):return ('set_country_flag = { flag = '+P+s+' days = '+str(days)+' }\n') if days else 'set_country_flag = '+P+s+'\n'
def receipt(n):return n['id']+'_applied'
