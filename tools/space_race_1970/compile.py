    dev+=block_if(cv(v('policy'),'=',1),sv('cw_sr_repair','cw_sr_fraction',True)+'multiply_temp_variable = { cw_sr_repair = -0.11538 }\n'+av(v('disruption'),'cw_sr_repair')+clamp(v('disruption'),0,10000))
    dev+=block_if(cv(v('work'),'>=',99.99)+' '+cv(v('months'),'>=',num(p['durationMonths']*.85)),sv(state,3)+sv(v('work'),100)+bulletin(n,5))
    month+=block_if(cv(state,'=',1),dev)
    investigation=sv('cw_sr_review_time',v('im'),True)+clamp('cw_sr_review_time',num(12/52),100000,True)+sv('cw_sr_due',v('ic'),True)+'divide_temp_variable = { cw_sr_due = cw_sr_review_time }\nmultiply_temp_variable = { cw_sr_due = 0.23076 }\n'+clamp('cw_sr_due',.001,100000,True)
    investigation+=block_if(cv(v('im'),'<=',num(12/52)),sv('cw_sr_due',v('ic'),True)+clamp('cw_sr_due',.001,100000,True))
    investigation+=sv('cw_sr_payment','cw_sr_allocation',True)+clamp('cw_sr_payment',0,'cw_sr_due',True)+clamp('cw_sr_payment',0,'treasury',True)
