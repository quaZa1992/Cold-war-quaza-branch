def bulletin_event(n, stage):
    # IMPERIA COLD WAR — Retain the actual lunar architecture's crew in special reports.
    prefix=''
    if stage==8 and 'lunar-landing' in PROGRAMMES[n-1]['grants']:
        prefix=sv('cw_sr_lunar_report_op',cooperation.field(n,'flight'))+sv('cw_sr_lunar_report_op_role',cooperation.field(n,'flight_role'))
        prefix+=''.join(sv(f'cw_sr_lunar_report_crew_{seat}',crew.field(n,seat,'flight') if seat in crew.slots(PROGRAMMES[n-1]) else 0) for seat in [1,2])
    if stage==8:
        if 'lunar-landing' in PROGRAMMES[n-1]['grants']:
            return prefix+block_if('original_tag = SOV','country_event = { id = cw_sr_report.8001 }\n',block_if('original_tag = FRA','country_event = { id = cw_sr_report.8002 }\n',block_if('original_tag = SAU','country_event = { id = cw_sr_report.8003 }\n',f'country_event = {{ id = cw_sr_report.{stage_id(n,stage)} }}\n')))
        if PROGRAMMES[n-1]['id']=='mars-crewed-landing':
            return block_if('original_tag = USA','country_event = { id = cw_sr_report.8004 }\n',block_if('original_tag = SOV','country_event = { id = cw_sr_report.8005 }\n',f'country_event = {{ id = cw_sr_report.{stage_id(n,stage)} }}\n'))
    return f'country_event = {{ id = cw_sr_report.{stage_id(n, stage)} }}\n'


