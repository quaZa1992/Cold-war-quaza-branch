    investigation+=block_if(cv(v('ic'),'<',.001)+' '+cv(v('im'),'<',.001),sv(v('ic'),0)+sv(v('im'),0)+sv(state,3)+av(v('corrective'),1)+bulletin(n,7))
    month+=block_if(cv(state,'=',6),investigation)
    out+=effect(f'cw_sr_p{n}_week',month)
    # All probability inputs are bounded and earned. Frozen copies are used in flight.
    odds=sv(v('lp'),num(p['pLaunch']*100))+sv(v('op'),num(p['pObjective']*100))+av(v('lp'),v('la'))+av(v('op'),v('oa'))
    odds+=sv('cw_sr_sl',0,True)+sv('cw_sr_so',0,True)
    for support in p.get('supportingProgrammes',[]):
        j=IDS.get(support if isinstance(support,str) else support['id'])
        if j:
            odds+=block_if(f'has_country_flag = cw_sr_p{j}_deployed',block_if(cv(var(j,'arrears'),'<',.001),av('cw_sr_sl',.5,True)+av('cw_sr_so',1,True),av('cw_sr_sl',-1,True)+av('cw_sr_so',-1.5,True)))
    odds+=clamp('cw_sr_sl',-3,2,True)+clamp('cw_sr_so',-4.5,4,True)+av(v('lp'),'cw_sr_sl')+av(v('op'),'cw_sr_so')
    odds+=sv('cw_sr_el',v('successes'),True)+'multiply_temp_variable = { cw_sr_el = 0.75 }\n'+sv('cw_sr_eo',v('successes'),True)+'multiply_temp_variable = { cw_sr_eo = 1 }\n'
    for j,other in enumerate(PROGRAMMES,1):
        if j!=n and other['missionFamily']==p['missionFamily'] and not other.get('commissioningOnly'):
            odds+=sv('cw_sr_related',var(j,'successes'),True)+clamp('cw_sr_related',0,2,True)+sv('cw_sr_related_o','cw_sr_related',True)+'multiply_temp_variable = { cw_sr_related = 0.3 }\nmultiply_temp_variable = { cw_sr_related_o = 0.5 }\n'+av('cw_sr_el','cw_sr_related',True)+av('cw_sr_eo','cw_sr_related_o',True)
    odds+=clamp('cw_sr_el',0,2.5,True)+clamp('cw_sr_eo',0,4,True)+av(v('lp'),'cw_sr_el')+av(v('op'),'cw_sr_eo')
    odds+=sv('cw_sr_disruption',v('disruption'),True)+f'divide_temp_variable = {{ cw_sr_disruption = {p["durationMonths"]} }}\n'+clamp('cw_sr_disruption',0,1,True)+sv('cw_sr_disruption_o','cw_sr_disruption',True)+'multiply_temp_variable = { cw_sr_disruption = -2 }\nmultiply_temp_variable = { cw_sr_disruption_o = -3 }\n'+av(v('lp'),'cw_sr_disruption')+av(v('op'),'cw_sr_disruption_o')
    odds+=sv('cw_sr_cl',v('corrective'),True)+'multiply_temp_variable = { cw_sr_cl = 0.4 }\n'+clamp('cw_sr_cl',0,1.2,True)+sv('cw_sr_co',v('corrective'),True)+'multiply_temp_variable = { cw_sr_co = 0.6 }\n'+clamp('cw_sr_co',0,1.8,True)+av(v('lp'),'cw_sr_cl')+av(v('op'),'cw_sr_co')
    odds+=sv('cw_sr_analysis','cw_sr_science',True)+'multiply_temp_variable = { cw_sr_analysis = 0.02 }\n'+clamp('cw_sr_analysis',0,2,True)+av(v('op'),'cw_sr_analysis')+block_if('has_country_flag = cw_sr_leader',av(v('op'),2))
