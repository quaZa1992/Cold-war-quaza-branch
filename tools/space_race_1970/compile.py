def programme_effects(n,p):
    v=lambda s:var(n,s)
    state=v('state')
    out=''
    start=block_if(cv(state,'=',2),bulletin(n,3),bulletin(n,1))+sv(state,1)+'cw_sr_recount = yes\n'
    out+=effect(f'cw_sr_p{n}_start',block_if(f'cw_sr_p{n}_start_allowed = yes',start))
    suspend=block_if(cv(state,'=',1),sv(state,2)+bulletin(n,2),f'clr_country_flag = cw_sr_p{n}_deployed\n'+block_if(cv(state,'=',5),sv(state,3))+bulletin(n,12))+'cw_sr_recount = yes\n'
    out+=effect(f'cw_sr_p{n}_pause',block_if(guard()+' OR = { '+cv(state,'=',1)+f' AND = {{ has_country_flag = cw_sr_p{n}_deployed NOT = {{ '+cv(state,'=',4)+' } } }',suspend))
    cancel=sv(state,7)+f'multiply_variable = {{ {v("work")} = 0.75 }}\nmultiply_variable = {{ {v("la")} = 0.75 }}\nmultiply_variable = {{ {v("oa")} = 0.75 }}\n'+bulletin(n,4)+'cw_sr_recount = yes\n'
    out+=effect(f'cw_sr_p{n}_cancel',block_if(guard()+' OR = { '+cv(state,'=',1)+' '+cv(state,'=',2)+' '+cv(state,'=',3)+' }',cancel))
    # Maintenance debt persists; only full payment restores qualification support.
    # Carry sub-million weekly accruals until they can be charged in MD treasury units.
    upkeep=sv('cw_sr_accrual',0,True)+block_if(f'has_country_flag = cw_sr_p{n}_deployed',sv('cw_sr_accrual',num(p['upkeepB']*1000/52),True)+block_if('has_country_flag = cw_sr_leader','multiply_temp_variable = { cw_sr_accrual = 0.95 }\n'))
    upkeep+=av(v('accrued_m'),'cw_sr_accrual')+sv('cw_sr_due',v('accrued_m'),True)+'divide_temp_variable = { cw_sr_due = 1000 }\n'+sv('cw_sr_whole_m','cw_sr_due',True)+'multiply_temp_variable = { cw_sr_whole_m = 1000 }\n'+f'subtract_from_variable = {{ {v("accrued_m")} = cw_sr_whole_m }}\n'+av('cw_sr_due',v('arrears'),True)
    upkeep+=sv('cw_sr_payment','treasury',True)+clamp('cw_sr_payment',0,'cw_sr_due',True)+charge('cw_sr_payment')+sv(v('arrears'),'cw_sr_due')+f'subtract_from_variable = {{ {v("arrears")} = cw_sr_payment }}\n'
    out+=effect(f'cw_sr_p{n}_upkeep',block_if(f'OR = {{ has_country_flag = cw_sr_p{n}_deployed '+cv(v('arrears'),'>',0)+' }',upkeep))
    # Monthly allocation is a ceiling, not a subsidy. No debt or money is created.
    month=sv('cw_sr_time',1,True)+sv('cw_sr_cost',1,True)+sv('cw_sr_launch_credit',0,True)+sv('cw_sr_objective_credit',0,True)
    policies=[(1,1.18,1.18,2.5,4),(2,.85,1.25,-4.5,-3.5),(3,1.35,.8,-2.5,-2)]
    for policy,time,cost,lc,oc in policies:
        month+=block_if(cv(v('policy'),'=',policy),sv('cw_sr_time',time,True)+sv('cw_sr_cost',cost,True)+sv('cw_sr_launch_credit',lc,True)+sv('cw_sr_objective_credit',oc,True))
    dev=sv('cw_sr_step',num(1200/(p['durationMonths']*52)),True)+'divide_temp_variable = { cw_sr_step = cw_sr_time }\n'
    dev+=sv('cw_sr_remaining',100,True)+f'subtract_from_temp_variable = {{ cw_sr_remaining = {v("work")} }}\n'+clamp('cw_sr_step',0,'cw_sr_remaining',True)
    dev+=sv('cw_sr_due','cw_sr_step',True)+f'multiply_temp_variable = {{ cw_sr_due = {num(p["totalCostB"])} }}\ndivide_temp_variable = {{ cw_sr_due = 100 }}\nmultiply_temp_variable = {{ cw_sr_due = cw_sr_cost }}\n'+clamp('cw_sr_due',.001,1000000,True)
    dev+=sv('cw_sr_payment','cw_sr_allocation',True)+clamp('cw_sr_payment',0,'cw_sr_due',True)+clamp('cw_sr_payment',0,'treasury',True)
    dev+=sv('cw_sr_fraction','cw_sr_payment',True)+'divide_temp_variable = { cw_sr_fraction = cw_sr_due }\n'+clamp('cw_sr_fraction',0,1,True)
    dev+=block_if(cv('cw_sr_payment','>',0),charge('cw_sr_payment')+av(v('spent'),'cw_sr_payment')+av('cw_sr_week_spent','cw_sr_payment'))
    dev+='multiply_temp_variable = { cw_sr_step = cw_sr_fraction }\n'+av(v('work'),'cw_sr_step')+clamp(v('work'),0,100)+av(v('months'),num(12/52))
    dev+=sv('cw_sr_weight','cw_sr_step',True)+'divide_temp_variable = { cw_sr_weight = 100 }\nmultiply_temp_variable = { cw_sr_launch_credit = cw_sr_weight }\nmultiply_temp_variable = { cw_sr_objective_credit = cw_sr_weight }\n'+av(v('la'),'cw_sr_launch_credit')+av(v('oa'),'cw_sr_objective_credit')
