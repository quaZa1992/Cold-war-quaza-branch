def bulletin_event(n, stage):
    if stage==8:
        if 'lunar-landing' in PROGRAMMES[n-1]['grants']:
            return block_if('original_tag = SOV','country_event = { id = cw_sr_report.8001 }\n',block_if('original_tag = FRA','country_event = { id = cw_sr_report.8002 }\n',block_if('original_tag = SAU','country_event = { id = cw_sr_report.8003 }\n',f'country_event = {{ id = cw_sr_report.{stage_id(n,stage)} }}\n')))
        if PROGRAMMES[n-1]['id']=='mars-crewed-landing':
            return block_if('original_tag = USA','country_event = { id = cw_sr_report.8004 }\n',block_if('original_tag = SOV','country_event = { id = cw_sr_report.8005 }\n',f'country_event = {{ id = cw_sr_report.{stage_id(n,stage)} }}\n'))
    return f'country_event = {{ id = cw_sr_report.{stage_id(n, stage)} }}\n'


def bulletin(n, stage):
    return sv(var(n,'last_report'),stage)+bulletin_event(n,stage)


def charge(amount):
    return sv('treasury_change', amount, True) + 'multiply_temp_variable = { treasury_change = -1 }\nmodify_treasury_effect = yes\n' + av('cw_sr_spent', amount)


def make_triggers():
    out = effect('cw_sr_player', guard())
    for n, p in enumerate(PROGRAMMES, 1):
        state = var(n, 'state')
        earliest = f'date > {p["minYear"] - 1}.12.31'
        common = guard() + ' ' + gates(p) + ' ' + earliest
        out += effect(f'cw_sr_p{n}_start_allowed', common + f'\n{cv("cw_sr_active", "<", 3)}\nOR = {{ {cv(state,"=",0)} {cv(state,"=",2)} {cv(state,"=",7)} }}\n')
        window = ''
        if 'fixedWindowStartMonth' in p:
            window = f'date > 1984.11.30 date < 1985.1.1\n'
        elif p.get('windowCycleMonths'):
            window = cv(f'global.cw_sr_window_{p["region"]}', '<', p['windowOpenMonths']) + '\n'
        out += effect(f'cw_sr_p{n}_launch_allowed', (common+' '+launch_gates(p['id'],IDS)).rstrip()+f'\nOR = {{ {cv(state,"=",3)} {cv(state,"=",5)} }}\n' + cv(var(n,'arrears'),'<',0.001) + '\n' + cv('treasury','>=',p['missionCostB']) + '\n' + cv(var(n,'im'),'<',.001)+'\n'+window)
    write('common/scripted_triggers/COLDWAR_space_race_triggers.txt', out)


def make_core():
    out = effect('cw_sr_touch', av('global.cw_sr_dirty', 1))
    cleanup='set_country_flag = cw_sr_antarctica_retired\n'
    for flag in ['antarctica_has_active_station','antarctica_station_setup_capacity_reserved','auto_resupply_antarctica_station','antarctica_post_treaty_station_violation','antarctica_treaty_join_pending','antarctica_atcp_application_pending']:
        cleanup+='clr_country_flag = '+flag+'\n'
    for name in ['var_open_MD_antarctica_gui','antarctica_station_total_upkeep_multiplier','antarctica_station_setup_in_progress','antarctica_station_dismantle_in_progress','research_station_module_repair_days_remaining']:
        cleanup+=sv(name,0)
    cleanup+=block_if('has_idea = at_member','remove_ideas = at_member\n')
    # Also repairs saves that already received the retirement receipt before this fix.
    out+=effect('cw_sr_retire_antarctica',block_if('NOT = { has_country_flag = cw_sr_antarctica_retired }',cleanup)+block_if('has_dynamic_modifier = antarctica_laboratory_dynamic_modifier','remove_dynamic_modifier = { modifier = antarctica_laboratory_dynamic_modifier }\n'))
    out+=effect('cw_sr_migrate_weekly',block_if('is_ai = no has_country_flag = cw_sr_initialized NOT = { has_country_flag = cw_sr_weekly_finance }','divide_variable = { cw_sr_budget = 52 }\nset_country_flag = cw_sr_weekly_finance\n'+sv('cw_sr_tab',1)))
    history=''.join(block_if('original_tag = '+tag,''.join('set_country_flag = cw_sr_heritage_'+str(IDS[item])+'\n' for item in entries)) for tag,entries in HERITAGE.items())+block_if('original_tag = USA','set_country_flag = cw_sr_cap_crewed_cislunar_operations\n')+'set_country_flag = cw_sr_flight_heritage\n'
    out+=effect('cw_sr_heritage',block_if('is_ai = no IMP_is_1970_scenario = yes NOT = { has_country_flag = cw_sr_flight_heritage }',history))
    init = 'set_country_flag = cw_sr_initialized\nset_country_flag = cw_sr_weekly_finance\n' + sv('cw_sr_budget',num(2/52)) + sv('cw_sr_selected',47) + sv('cw_sr_region',1) + sv('cw_sr_system',1) + sv('cw_sr_page',0)+sv('cw_sr_tab',1)
    for profile in DATA['profiles']:
        if profile['id'] == 'CUSTOM':
            continue
        body = sv('cw_sr_budget',num(profile['annualBudgetB']/52)) + ''.join('set_country_flag = '+cap(c)+'\n' for c in profile['capabilities'])
        for n,p in enumerate(PROGRAMMES,1):
            progress=p.get('initialProgress',{}).get(profile['id'],0)
            if progress:
                body += sv(var(n,'work'),progress) + sv(var(n,'months'),num(progress/100*p['durationMonths']))
        init += block_if(f'original_tag = {profile["id"]}',body)
    init += 'cw_sr_recount = yes\ncw_sr_refresh = yes\n'
    out += effect('cw_sr_initialize','cw_sr_migrate_weekly = yes\n'+block_if('is_ai = no IMP_is_1970_scenario = yes NOT = { has_country_flag = cw_sr_initialized }',init))
    seed = 'set_global_flag = cw_sr_world_initialized\n'
    for h in DATA['historicalFirsts']:
        seed += f'set_global_flag = cw_sr_first_{h["milestoneId"].replace("-","_")}\n'
    out += effect('cw_sr_seed_world',block_if('NOT = { has_global_flag = cw_sr_world_initialized }',seed))
    recount=sv('cw_sr_active',0)+sv('cw_sr_demand',0)+sv('cw_sr_flights',0)+sv('cw_sr_weekly_upkeep_m',0)
    for n,p in enumerate(PROGRAMMES,1):
        recount+=block_if(cv(var(n,'state'),'=',1),av('cw_sr_active',1))
        recount+=block_if('OR = { '+cv(var(n,'state'),'=',1)+' '+cv(var(n,'state'),'=',6)+' }',av('cw_sr_demand',1))
