def loc(key, value):
    value=str(value).translate(str.maketrans({'−':'-','–':'-','—':'-','‹':'<','›':'>','×':'X','’':"'",'‘':"'",'“':"'",'”':"'"}))
    LOC[key] = value.replace('"', "'").replace('\r', '').replace('\n', '\\n')
    return key


def write(path, content, bom=False):
    target = ROOT / path
    target.parent.mkdir(parents=True, exist_ok=True)
    data=(('' if bom else HEADER)+content).encode('utf-8-sig' if bom else 'utf-8')
    if not target.exists() or target.read_bytes()!=data:
        temporary=target.with_suffix(target.suffix+'.cw_sr_tmp');temporary.write_bytes(data);temporary.replace(target)
    OUTPUTS.append(path)


def num(value):
    return f'{value:.5f}'.rstrip('0').rstrip('.') if value else '0'


def cap(value):
    return 'cw_sr_cap_' + value.replace('-', '_')


def var(n, suffix):
    return f'cw_sr_p{n}_{suffix}'


def sv(name, value, temp=False):
    return f'set_{"temp_" if temp else ""}variable = {{ {name} = {value} }}\n'


def av(name, value, temp=False):
    return f'add_to_{"temp_" if temp else ""}variable = {{ {name} = {value} }}\n'


def cv(name, op, value):
    if op in ['>=','<=','!=']:
        return f'check_variable = {{ var = {name} value = {value} compare = '+{'>=':'greater_than_or_equals','<=':'less_than_or_equals','!=':'not_equals'}[op]+' }'
    return f'check_variable = {{ {name} {op} {value} }}'


def block_if(condition, body, otherwise=''):
    return 'if = { limit = { ' + condition + ' }\n' + body + '}\n' + ('else = {\n' + otherwise + '}\n' if otherwise else '')


def effect(name, body):
    return name + ' = {\n' + body + '}\n\n'


def clamp(name, lo, hi, temp=False):
    return f'clamp_{"temp_" if temp else ""}variable = {{ var = {name} min = {lo} max = {hi} }}\n'


def gates(p):
    return ' '.join('has_country_flag = ' + cap(c) for c in p['capabilityRequirements'])


def guard():
    return 'is_ai = no IMP_is_1970_scenario = yes has_country_flag = cw_sr_initialized'


def stage_id(n, stage):
    return n * 20 + stage


