def outcomes(n,p):
    v=lambda s:var(n,s)
    out=''
    success=sv(v('state'),5)+av(v('successes'),1)+sv('cw_sr_world_news',0,True)
    if p.get('majorNationalCapability'):
        success+=block_if(f'NOT = {{ has_country_flag = {cap(p["majorNationalCapability"])} }}',sv('cw_sr_world_news',1,True))
    success+='set_country_flag = cw_sr_p'+str(n)+'_deployed\n'
    # IMPERIA COLD WAR — A guest receives a forfeited part of the original pool.
    if crew.eligible(p) or cooperation.eligible(p):
        first=sv('cw_sr_remaining_award',p['prestige'],True)+f'subtract_from_temp_variable = {{ cw_sr_remaining_award = {v("partial_award")} }}\n'
        first+=crew.distribute(globals(),n,p,'cw_sr_remaining_award',p['rewardEffects']['researchPoints'],p['rewardEffects']['politicalCapital'],.10 if p['rewardEffects']['researchPoints']>=4 else 0,f'cw_sr_p{n}_name')+f'set_country_flag = cw_sr_p{n}_awarded\n'
    else:
        first=av('cw_sr_prestige',num(p['prestige']))+f'subtract_from_variable = {{ cw_sr_prestige = {v("partial_award")} }}\n'
        first+=av('cw_sr_science',p['rewardEffects']['researchPoints'])+f'add_political_power = {p["rewardEffects"]["politicalCapital"]}\nset_country_flag = cw_sr_p{n}_awarded\n'

    if p['rewardEffects']['researchPoints']>=4 and not (crew.eligible(p) or cooperation.eligible(p)):
        first+=research_award(ROOT,f'cw_sr_p{n}_name',.10)
    repeat=sv('cw_sr_award',num(p['prestige']*.15),True)+f'subtract_from_temp_variable = {{ cw_sr_award = {v("repeat_award")} }}\n'+clamp('cw_sr_award',0,num(min(2,p['prestige']*.03)),True)+av('cw_sr_prestige','cw_sr_award')+av(v('repeat_award'),'cw_sr_award')
    if p.get('commissioningOnly'):repeat=''
    # IMPERIA COLD WAR — Repeat ceilings apply to the complete joint pool.
    if crew.eligible(p) or cooperation.eligible(p):repeat=repeat.replace(av('cw_sr_prestige','cw_sr_award'),crew.distribute(globals(),n,p,'cw_sr_award',kind='repeat'))
    success+=block_if(f'NOT = {{ has_country_flag = cw_sr_p{n}_awarded }}',first,repeat)
    # IMPERIA COLD WAR — Retry a rejected native handover on a later accepted flight, without repeating awards.
    if p['id'] in PILOTS:success+=f'cw_sr_p{n}_native_pilot = yes\n'
    success+=''.join(f'set_country_flag = {cap(c)}\n' for c in p['grants'])
    for m, milestone in enumerate(DATA['milestones'],1):
        if milestone['capability'] not in p['grants']:
            continue
        flag='cw_sr_first_'+milestone['id'].replace('-','_')
        report=f'news_event = {{ id = cw_sr_world.{9000+m} }}\n'
        if milestone['id']=='first-crewed-mars-return':
            report=block_if('original_tag = USA','news_event = { id = cw_sr_world.9101 }\n',block_if('original_tag = SOV','news_event = { id = cw_sr_world.9102 }\n',report))
        # IMPERIA COLD WAR — One world-first pool, including research magnitude.
        rewards=crew.distribute(globals(),n,p,milestone['prestige'],milestone['researchPoints'],milestone['politicalCapital'],.20,f'cw_sr_milestone_{m}',kind='milestone') if crew.eligible(p) or cooperation.eligible(p) else av('cw_sr_prestige',milestone['prestige'])+av('cw_sr_science',milestone['researchPoints'])+f'add_political_power = {milestone["politicalCapital"]}\n'+research_award(ROOT,f'cw_sr_milestone_{m}',.20)
        award=f'set_global_flag = {flag}\nsave_global_event_target_as = cw_sr_first_holder_{m}\n'+sv(f'cw_sr_first_programme_{m}',n)+''.join(sv(f'cw_sr_first_crew_{m}_{seat}',crew.field(n,seat,'flight') if seat in crew.slots(p) else 0) for seat in [1,2])+sv(f'cw_sr_first_op_{m}',cooperation.field(n,'flight') if cooperation.eligible(p) else 0)+sv(f'cw_sr_first_op_role_{m}',cooperation.field(n,'flight_role') if cooperation.eligible(p) else 0)+rewards+report+sv('cw_sr_world_news',2,True)
        success+=block_if(f'NOT = {{ has_global_flag = {flag} }}',award)
    success+=bulletin(n,8)+block_if(cv('cw_sr_world_news','=',1),f'cw_sr_p{n}_major_news = yes\n')
    # IMPERIA COLD WAR — Release assignments after rewards and reports.
    if crew.eligible(p):success+=crew.finish(globals(),n,p,'success')
    if cooperation.eligible(p):success+=cooperation.finish(globals(),n,p,'success')
    out+=effect(f'cw_sr_p{n}_success',success)
    for kind,stage,months,fraction in [('partial',9,3,.08),('failure',10,6,.18),('catastrophic',11,12,.30),('abort',13,1,.02)]:
        body=sv(v('state'),6)+sv(v('im'),months)+sv(v('ic'),num(max(.005 if kind=='abort' else .025,p['missionCostB']*fraction)))
        if kind=='partial':
            # IMPERIA COLD WAR — Partial prestige uses the same conserved pool.
            partial=crew.distribute(globals(),n,p,v('partial_award'),kind='partial') if crew.eligible(p) or cooperation.eligible(p) else av('cw_sr_prestige',v('partial_award'))
            body+=block_if(f'NOT = {{ has_country_flag = cw_sr_p{n}_awarded }} '+cv(v('partial_award'),'=',0),sv(v('partial_award'),num(p['prestige']*.1))+partial)
        if kind=='catastrophic':
            body+=av('cw_sr_prestige',num(-max(1,p['prestige']*.08)))+clamp('cw_sr_prestige',0,100000)
            if p['crewSize']:
                # IMPERIA COLD WAR — National losses exclude an unassigned foreign pilot in legacy missions.
                fatalities=av('cw_sr_fatalities',p.get('nationalCrewSize',p['crewSize']))+av(v('fatalities'),p['crewSize'])+f'add_manpower = {-p.get("nationalCrewSize",p["crewSize"])}\nadd_political_power = {-4*p.get("nationalCrewSize",p["crewSize"])}\nnews_event = {{ id = cw_sr_world.{stage_id(n,11)} }}\n'
                # IMPERIA COLD WAR — Losses belong to each astronaut's home country.
                if crew.eligible(p):fatalities=crew.deaths(globals(),n,p)+f'news_event = {{ id = cw_sr_world.{stage_id(n,11)} }}\n'
                body+=block_if(cv(v('phase'),'=',1) if p.get('crewAtLaunch') is False else 'always = yes',fatalities)
        body+=bulletin(n,stage)
        # IMPERIA COLD WAR — Abort, failure and loss release every signed seat.
        if crew.eligible(p):body+=crew.finish(globals(),n,p,kind)
        if cooperation.eligible(p):body+=cooperation.finish(globals(),n,p,kind)
        out+=effect(f'cw_sr_p{n}_{kind}',body)
    # Special national illustrations are routed only for accepted crewed expeditions.
    major=f'news_event = {{ id = cw_sr_world.{stage_id(n,8)} }}\n'
    if 'lunar-landing' in p['grants']:
        major=block_if('original_tag = SOV','news_event = { id = cw_sr_world.8001 }\n',block_if('original_tag = FRA','news_event = { id = cw_sr_world.8002 }\n',block_if('original_tag = SAU','news_event = { id = cw_sr_world.8003 }\n',major)))
    if p['id']=='mars-crewed-landing':
        major=block_if('original_tag = USA','news_event = { id = cw_sr_world.8004 }\n',block_if('original_tag = SOV','news_event = { id = cw_sr_world.8005 }\n',major))
    out+=effect(f'cw_sr_p{n}_major_news',major)
    return out


