def make_triggers():
    out = effect('cw_sr_player', guard())
    for n, p in enumerate(PROGRAMMES, 1):
        state = var(n, 'state')
        earliest = f'date > {p["minYear"] - 1}.12.31'
        common = guard() + ' ' + gates(p) + ' ' + earliest
        if p.get('commissioningOnly'):common += f' NOT = {{ has_country_flag = cw_sr_institution_{n} }}'
        out += effect(f'cw_sr_p{n}_start_allowed', common + f'\n{cv("cw_sr_active", "<", 3)}\nOR = {{ {cv(state,"=",0)} {cv(state,"=",2)} {cv(state,"=",7)} }}\n')
        window = ''
        if 'fixedWindowStartMonth' in p:
            window = f'date > 1984.11.30 date < 1985.1.1\n'
        elif p.get('windowCycleMonths'):
            window = cv(f'global.cw_sr_window_{p["region"]}', '<', p['windowOpenMonths']) + '\n'
        repeat_guard=f' NOT = {{ AND = {{ has_country_flag = cw_sr_p{n}_awarded has_country_flag = cw_sr_p{n}_deployed }} }}' if p.get('commissioningOnly') else ''
        # IMPERIA COLD WAR — Signed crews and net national appropriation.
        funds=cooperation.funds(globals(),n,p) if cooperation.eligible(p) else (crew.funds(globals(),n,p) if crew.eligible(p) else cv('treasury','>=',p['missionCostB']))
        crew_gate=(f'cw_sr_p{n}_crew_ready = yes\n' if crew.eligible(p) else '')+(f'cw_sr_p{n}_operations_ready = yes\n' if cooperation.eligible(p) else '')
        out += effect(f'cw_sr_p{n}_launch_allowed', (common+repeat_guard+' '+launch_gates(p['id'],IDS)).rstrip()+f'\ncw_sr_p{n}_technology = yes\nOR = {{ {cv(state,"=",3)} {cv(state,"=",5)} }}\n' + cv(var(n,'arrears'),'<',0.001) + '\n' + funds + '\n' + cv(var(n,'im'),'<',.001)+'\n'+window+crew_gate)
    write('common/scripted_triggers/COLDWAR_space_race_triggers.txt', out)


