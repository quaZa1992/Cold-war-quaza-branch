def routes(id,memo=None):
    """DNF of selected policy ancestors, respecting AND/OR prerequisite groups."""
    if memo is None:memo={}
    if id in memo:return memo[id]
    n=BY[id];result={frozenset()}
    for group in n['prerequisites']:
        options=set().union(*(routes(p,memo) for p in group))
        result={a|b for a in result for b in options}
    if n['mutually_exclusive']:result={r|{id} for r in result}
    result={r for r in result if not any(set(pair)<=r for pair in PAIRS[n['group']])}
    memo[id]=result;return result
def policy_gate(n,active=False):
    paths=routes(n['id'])
    if frozenset() in paths:return ''
    def selected(p):
        rows=[flag(selection(p))]
        if active:
            if p in POLICY_CONTRACT_GATES:rows.append(POLICY_CONTRACT_GATES[p])
            if p in PROGRAMME_CONTRACT_GATES:rows.append(PROGRAMME_CONTRACT_GATES[p])
        return '\n'.join(rows)
    return block('OR','\n'.join(block('AND','\n'.join(selected(p) for p in sorted(path))) for path in sorted(paths,key=lambda s:sorted(s))))

