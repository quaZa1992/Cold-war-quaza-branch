"""Compile the approved Vietnam campaign extension; importing has no side effects.

The supplied callbacks own writes/localisation.  No shared game files are edited.
Native CW assistance remains donor initiated and paid through its own UI.
"""
from collections import defaultdict
from pathlib import Path
import sys
import re
from script_ast import parse, emit, first
sys.path.append(str(Path(__file__).resolve().parents[1]))
from focus_prerequisite_ui import hide_redundant_prerequisites

P = 'COLDWAR_VIE_'
C = P + 'campaign_'
HEADER = '## COLDWAR | Approved Vietnam campaign extension. Generated by campaigns.py.\n'
FOCUS_DESCRIPTIONS = {
    P+'guerrilla_lessons': 'The long war has bound local political cadres, village networks and regular formations into a single struggle. Preserve that experience as the army prepares for the campaigns still ahead.'
}


def build(spec, root, write, loc):
    localize = loc
    localized = set()
    def loc(key, text, desc=None):
        localized.add(key)
        if desc is not None: localized.add(key + '_desc')
        localize(key, text, desc)
    nodes = {n['id']: n for n in spec['nodes']}
    decisions = {q['id']: q for q in spec['decisions']}
    triggers, effects, ideas, events, technologies = [], [], [], [], []
    families = defaultdict(list)
    policy_nodes = {}
    idea_art = {}
    event_number = 100
    namespace = 'COLDWAR_VIE_CAMPAIGN'

    def b(key, body): return key + ' = {\n' + body + '\n}\n'
    def f(key): return 'has_country_flag = ' + key
    def sf(key, days=None):
        return ('set_country_flag = ' + key if days is None else
                f'set_country_flag = {{ flag = {key} days = {days} value = 1 }}') + '\n'
    def cf(key): return 'clr_country_flag = ' + key + '\n'
    def applied(key): return f(key + '_reward_applied')
    def named(name): return C + name + ' = yes'
    def funded(amount):
        key=P+'treasury_'+f'{amount:g}'.replace('.','_')+'_tt'
        loc(key,f'Treasury is at least §Y{amount:g} billion§! (current: §Y[?treasury|3] billion§!)')
        return b('custom_trigger_tooltip','tooltip = '+key+'\n'+f'check_variable = {{ var = treasury value = {amount:g} compare = greater_than_or_equals }}')
    def pay(amount):
        return '' if not amount else f'set_temp_variable = {{ treasury_change = {-amount:g} }}\nmodify_treasury_effect = yes\n'
    def cond(test, body): return b('if', b('limit', test) + body)
    def predicate(name, body, label):
        key = C + name
        triggers.append(b(key, b('custom_trigger_tooltip', 'tooltip = ' + key + '_tt\n' + b('hidden_trigger', body))))
        loc(key + '_tt', label)
        return key + ' = yes'
    def effect(key, body): effects.append(b(key, body)); return key + ' = yes\n'
    def all_states(states, test): return '\n'.join(b(str(s), test) for s in states)
    def no_divisions(tag, states):
        return b(tag, b('num_divisions_in_states', 'count = 0\nstates = { ' + ' '.join(map(str, states)) + ' }'))
    def native_program(donor, target):
        return b(donor, 'exists = yes\nNOT = { has_war_with = ' + target + ' }\nOR = {\n' +
                 '\n'.join(b('AND', f'check_variable = {{ mdcw_cw_p{i}_state@{target} = 1 }}\n'
                             f'check_variable = {{ mdcw_cw_p{i}_size@{target} > 0 }}\n'
                             f'check_variable = {{ mdcw_cw_p{i}_end@{target} > global.num_days }}') for i in (6, 7)) + '}')
    def new_event(title, description, options):
        nonlocal event_number
        event_number += 1
        eid = namespace + '.' + str(event_number)
        key = C + 'event_' + str(event_number)
        loc(key + '_title', title); loc(key + '_desc', description)
        body = f'id = {eid}\ntitle = {key}_title\ndesc = {key}_desc\nis_triggered_only = yes\n'
        for index, (label, gate, action) in enumerate(options):
            opt = key + '_option_' + str(index)
            loc(opt, label)
            body += b('option', 'name = ' + opt + '\n' + (b('trigger', gate) if gate else '') +
                      (cond(gate, action) if gate and action else action) + '\nai_chance = { factor = 1 }')
        events.append(b('country_event', body))
        return 'country_event = { id = ' + eid + ' }\n'

    base = 'COLDWAR_VIE_is_1970 = yes\ntag = VIE'
    triggers.append(b(C+'eligible',b('hidden_trigger',base)))
    south_control = 'OR = { ' + ' '.join(b(str(s), 'is_controlled_by = VIE') for s in (519, 520, 521)) + ' }'
    south_owned = all_states((519, 520, 521), 'is_owned_and_controlled_by = VIE')
    occupation = 'OR = { ' + ' '.join(b(str(s), 'is_controlled_by = VIE\nNOT = { is_core_of = VIE }') for s in (511, 512, 513, 514)) + ' }'
    predicate('cbd_occupation', occupation, 'Vietnam controls actual Cambodian non core territory')
    predicate('cbd_native_assistance', native_program('VIE', 'CBD'), 'An active funded Vietnamese training or arms production programme in Cambodia exists')
    predicate('sov_native_assistance', native_program('SOV', 'VIE'), 'An active funded Soviet training or arms production programme in Vietnam exists')
    predicate('south_control', south_control, 'Vietnam actually governs southern territory')
    predicate('south_owned', south_owned, 'Vietnam owns and controls all three southern states')
    predicate('cbd_hostility', 'CBD = { exists = yes }\nOR = { has_war_with = CBD CBD = { has_wargoal_against = VIE } }',
              'Cambodia is at war with Vietnam or has a real hostile war goal')
    predicate('china_confrontation', 'CHI = { exists = yes }\nOR = { has_war_with = CHI CHI = { has_wargoal_against = VIE } ' + f(C + 'frontier_emergency') + ' }',
              'Actual Chinese war, hostile war preparations or a recorded recent frontier emergency')
    friendly = 'CBD = { exists = yes controls_state = 514 }\nNOT = { has_war_with = CBD }\nOR = { CBD = { is_subject_of = VIE } is_in_faction_with = CBD ' + f(C + 'security_agreement') + ' }'
    predicate('friendly_cbd', friendly, 'An existing Cambodian government controls Phnom Penh and is a lawful ally, subject or current consenting security partner')
    withdrawal = no_divisions('VIE', (511, 512, 513, 514)) + '\nNOT = { has_military_access_to = CBD }'
    predicate('cbd_land_drawdown', withdrawal, 'No Vietnamese divisions remain in the four Cambodian states and Vietnamese military access has ended')
    standdown = 'NOT = { has_war_with = CHI }\n' + no_divisions('VIE', (574, 578)) + no_divisions('CHI', (522, 523, 524))
    predicate('china_standdown', standdown, 'Actual peace with China and reciprocal absence of national land divisions across the frontier')
    grievance = f(C + 'war_seen') + '\n' + south_control + '\nstability < 0.55\nNOT = { has_war = yes }'
    predicate('domestic_grievance', grievance, 'Real postwar administrative strain: governed southern territory and national stability below 55 percent')
    commitment = 'OR = { ' + named('cbd_occupation') + ' ' + named('cbd_native_assistance') + ' }'
    predicate('cbd_commitment', commitment, 'An actual Cambodian occupation or active funded military assistance commitment continues')
    victory = f(C + 'cbd_war_seen') + '\n' + f(C + 'cbd_capital_taken') + '\nNOT = { has_war_with = CBD }\nOR = { AND = { CBD = { exists = no } controls_state = 514 } ' + named('friendly_cbd') + ' }'
    predicate('cbd_victory', victory, 'A recorded real Cambodian campaign captured Phnom Penh and ended with a lawful friendly settlement or actual territorial victory')
    predicate('secured_southwest', named('cbd_victory') + '\n' + named('friendly_cbd') + '\n' + named('south_owned') + '\n' + f(C + 'security_agreement') + '\nNOT = { ' + named('cbd_hostility') + ' }',
              'The won campaign, lawful Cambodian partnership and actually controlled southern homeland remain secure')
    predicate('partner_ready', named('friendly_cbd') + '\n' + named('cbd_native_assistance') + '\nCBD = { num_divisions > 0 }\n' + no_divisions('VIE', (514,)),
              'Active funded native assistance, real Cambodian divisions and Cambodian responsibility for the capital')
    predicate('limited_settlement', f(C + 'limited_terms') + '\nNOT = { has_war_with = CBD }\nNOT = { ' + named('cbd_occupation') + ' }\n' + named('cbd_land_drawdown'),
              'Current accepted limited terms, actual peace and a verified Vietnamese land drawdown')

    # The human-readable approval conditions are translated into live native predicates.
    semantic = {}
    def setgate(suffixes, test):
        for suffix in suffixes.split(): semantic[P + suffix] = test
    setgate('guerrilla_endure', 'has_war = yes')
    setgate('guerrilla_offensive', 'has_war = yes')
    setgate('guerrilla_review', f(C + 'war_seen'))
    setgate('guerrilla_guarantees guerrilla_services', named('south_control') + '\nNOT = { has_war = yes }')
    setgate('guerrilla_security guerrilla_screening', named('domestic_grievance'))
    setgate('guerrilla_settlement', named('south_control') + '\nNOT = { has_war = yes }')
    setgate('guerrilla_reserve guerrilla_civilian guerrilla_rotation guerrilla_veterans guerrilla_record guerrilla_aftermath', 'NOT = { has_war = yes }')
    setgate('cambodia_question cambodia_frontier cambodia_staff cambodia_channel cambodia_mandate', 'CBD = { exists = yes }')
    setgate('cambodia_civilians', named('cbd_hostility') + '\n' + named('south_control'))
    setgate('cambodia_limited', 'OR = { has_war_with = CBD ' + f(C + 'border_commission') + ' }')
    setgate('cambodia_intervene', named('cbd_hostility') + '\nNOT = { is_in_faction_with = CBD }\nNOT = { CBD = { is_subject_of = VIE } }')
    setgate('cambodia_monitor', f(C + 'border_commission'))
    setgate('cambodia_capital', 'has_war_with = CBD')
    setgate('cambodia_aftermath', named('cbd_victory'))
    setgate('cambodia_partner', named('secured_southwest') + '\n' + f(C + 'victory_verified'))
    setgate('cambodia_direct cambodia_dry', named('cbd_victory') + '\n' + named('cbd_occupation'))
    setgate('cambodia_train', named('friendly_cbd') + '\n' + named('cbd_native_assistance'))
    setgate('cambodia_burden', named('cbd_commitment'))
    setgate('cambodia_stay', named('cbd_occupation'))
    setgate('cambodia_leave', named('cbd_commitment') + '\nCBD = { exists = yes }')
    setgate('cambodia_restore', named('cbd_occupation'))
    setgate('cambodia_verify', f(C + 'withdrawal_terms'))
    setgate('cambodia_border_settlement cambodia_limited_commitment', named('limited_settlement'))
    setgate('cambodia_talks cambodia_limits', 'OR = { ' + named('cbd_victory') + ' AND = { ' + named('limited_settlement') + ' ' + f(C + 'limited_verified') + ' } }')
    semantic[P+'cambodia_limits'] += '\n' + f(C+'regional_process')
    setgate('china_frontier china_talks china_survey china_citizens china_liaison', 'CHI = { exists = yes }')
    setgate('china_crisis china_hold china_counter china_depth china_objectives', 'has_war_with = CHI')
    setgate('china_long', f(C + 'chi_war_seen'))
    setgate('china_soviet', f(C + 'chi_war_seen') + '\nSOV = { exists = yes }')
    setgate('china_assistance', f(C + 'soviet_response'))
    setgate('china_self china_rotation china_twofront', f(C + 'chi_war_seen'))
    setgate('china_mobilise china_hills', named('china_confrontation'))
    setgate('china_opening', f(C + 'chi_war_seen') + '\nCHI = { exists = yes }')
    setgate('china_standdown', f(C + 'china_terms'))
    setgate('china_rebuild', all_states((522, 523, 524), 'is_owned_and_controlled_by = VIE') + '\nNOT = { has_war_with = CHI }')
    setgate('china_security', f(C + 'chi_war_seen') + '\nNOT = { has_war_with = CHI }')

    def focus_gate(n, money=True, parents=True):
        out = named('eligible') + '\n' + semantic.get(n['id'], '')
        if money and n.get('cash'): out += '\n' + funded(n['cash'])
        if parents:
            for group in n['prerequisites']:
                out += '\n' + b('OR', '\n'.join(applied(x) for x in group))
        return out

    for n in nodes.values():
        for pol in [x for x in n['effects'] if x['type'] == 'idea']:
            families[pol['family']].append(n['id'])
            policy_nodes[n['id']] = pol
    def policy_live(n):
        # Relevant institutions can survive their original crisis; operating wars cannot.
        key = n['id']
        if key.endswith(('guerrilla_guarantees', 'guerrilla_services', 'guerrilla_security', 'guerrilla_screening')):
            return named('eligible') + '\n' + named('south_control') + '\nNOT = { has_war = yes }'
        if key.endswith('cambodia_train'): return named('eligible') + '\n' + named('friendly_cbd') + '\n' + named('cbd_native_assistance')
        return focus_gate(n, money=False, parents=False)

    for key, pol in policy_nodes.items():
        n = nodes[key]; iid = key + '_policy'
        definition = parse(n['idea_definitions'])
        rows = first(definition, iid)
        rows = [(k, op, (iid if k == 'picture' else v)) for k, op, v in rows]
        rows += parse('allowed = { original_tag = VIE }\nremoval_cost = -1\n' + b('cancel', 'NOT = { ' + policy_live(n) + ' }'))
        terrain=n.get('terrain_training')
        if terrain:
            tid=terrain['id']
            # Native timed-terrain pattern: the idea owns and removes its hidden tech.
            rows += parse(b('on_remove',b('hidden_effect',b('set_technology',tid+' = 0\npopup = no'))))
            technologies.append(b(tid,'allow = { always = no }\n'+b('category_army',
                b('forest','defence = '+str(terrain['defence']))+
                b('jungle','defence = '+str(terrain['defence'])))))
            loc(tid,terrain['label'],'Temporary army defence training in forest and jungle, owned by the corresponding active national policy.')
            loc(key+'_terrain_tt',f'Army defence in forest and jungle: §G+{terrain["defence"]:.0%}§! while this policy is active.')
        ideas.append(b(iid, emit(rows)))
        scope_note=(' Entrenchment applies across fronts. '+('Homeland defence applies on Vietnamese core territory. ' if 'army_core_defence_factor' in pol['modifiers'] else '')+
                    ('Terrain defence applies to army units in forest and jungle against any opponent while this policy is active. ' if terrain else '')) if key in {P+'china_'+s for s in ('survey','liaison','hold','depth')} else ' National modifiers apply to Vietnam as a whole. Opponent modifiers apply against that named country on every front. '
        loc(iid, pol['title'], n['description'] + scope_note +
            (f'This funded policy expires after {pol["duration"]} days and must be renewed.' if pol['duration'] else 'This earned strategic dividend remains active only while its actual security conditions hold.'))
        idea_art[iid] = 'gfx/interface/ideas/army/' + ('revolutionary_army' if n['group'] == 'guerrilla' else 'planning_bonus') + '.dds'
        remove = ''.join('remove_ideas = ' + other + '_policy\n' + cf(other + '_campaign_selected') for other in families[pol['family']])
        add = (f'add_timed_idea = {{ idea = {iid} days = {pol["duration"]} }}\n' if pol['duration'] else 'add_ideas = ' + iid + '\n')
        if terrain:add+=b('hidden_effect',b('set_technology',terrain['id']+' = 1\npopup = no'))
        effect(key + '_activate', remove + add + sf(key + '_campaign_selected'))

    focuses = ''
    for n in nodes.values():
        key = n['id']; helper = C + 'apply_' + key.removeprefix(P)
        # Replace only policy attachment; all approved numerical transactions remain exact.
        runtime = []
        for k, op, value in parse(n['raw_reward_code']):
            if k in ('add_timed_idea', 'add_ideas'):
                runtime += parse(key + '_activate = yes')
            else: runtime.append((k, op, value))
        action = emit(runtime) + '\n' + sf(key + '_reward_applied') + cf(key + '_pending')
        effects.append(b(helper, cond('NOT = { ' + applied(key) + ' }',
                       cond(focus_gate(n), action) + 'else = { ' + sf(key + '_pending') + ' }')))
        body = f'id = {key}\nicon = GFX_{key}\nx = {n["emitted_x"]}\ny = {n["emitted_y"]}\ncost = {n["days"]/7:g}\n'
        if n.get('anchor'): body += 'relative_position_id = ' + n['anchor'] + '\n'
        for group in n['prerequisites']: body += b('prerequisite', '\n'.join('focus = ' + x for x in group))
        if n['exclusive']: body += b('mutually_exclusive', '\n'.join('focus = ' + x for x in n['exclusive']))
        body += 'cancel_if_invalid = yes\ncontinue_if_invalid = no\nsearch_filters = { FOCUS_FILTER_ARMY FOCUS_FILTER_POLITICAL }\n'
        body += b('available', hide_redundant_prerequisites(focus_gate(n),n['prerequisites']))
        body += b('completion_reward', 'log = "[GetDateText]: [Root.GetName]: Focus ' + key + '"\n' + b('effect_tooltip', n['raw_reward_code']) + b('hidden_effect', helper + ' = yes'))
        body += 'ai_will_do = { base = 1 }\n'
        focuses += b('focus', body)
        loc(key, n['label'], FOCUS_DESCRIPTIONS.get(key,n['description']))
        loc(key + '_reward_applied', 'Has implemented $' + key + '$')
        loc(key + '_pending', 'Implementation of $' + key + '$ awaits its real conditions or funding')

    # Native UI handoffs are honest instructions plus a real native panel/preselection.
    native_ui = 'set_country_flag = mdcw_cw_open\nset_variable = { mdcw_cw_tab = 3 }\nmdcw_cw_refresh_player_view = yes\nmdcw_cw_touch_gui = yes\n'
    native_init = 'has_global_flag = mdcw_cw_initialized'
    ui_note = C + 'native_assistance_tt'
    loc(ui_note, 'The existing Cold War overview opens. To send a funded mission, open the recipient country diplomacy and choose Assistance, then Military Training or Arms Production. The donor pays native costs and the recipient must accept. This does not create a mission automatically.')
    support_note = C + 'native_support_tt'
    loc(support_note, 'The existing Cold War overview opens with communist party index 4 selected. Open South Vietnam diplomacy and choose Public Political Support. Native capacity, 50 political power, cooldown and target access rules apply. This changes party support, not weapons or units.')
    rebuild_note = C + 'native_rebuilding_tt'
    loc(rebuild_note, 'Select the named state on the map and open its native state investments. Improve Rebuilding Efforts costs the native cash contribution and 75 political power, lasts 180 days and respects project caps. In owned core territory use ordinary reconstruction and construction projects; occupation compliance has no effect on normal Vietnamese cores.')

    decision_gates, decision_actions = {}, {}
    offer_specs = {}
    # Paid programme renewal opens a real selection event; nothing is charged on opening.
    def selection(q, family, extra='', choices=None):
        opts = []
        for key in (choices or families[family]):
            n = nodes[key]; pol = policy_nodes[key]
            earned = 'OR = { ' + applied(key) + ' ' + f(key + '_campaign_selected') + ' }'
            gate = q['id'] + '_eligible = yes\n' + earned + '\n' + policy_live(n) + '\n' + extra + '\n' + funded(q.get('cash') or n.get('cash') or 0)
            if q['id'].endswith('local_conference'):
                gate = q['id'] + '_eligible = yes\n' + named('south_control') + '\nNOT = { has_war = yes }\n' + funded(q['cash'])
            action = pay(q.get('cash') or n.get('cash') or 0) + key + '_activate = yes\n'
            if family == 'internal_policy': action += sf(C + 'domestic_settlement', pol['duration'] or 180)
            opts.append((pol['title'], gate, action))
        # Ending a deployment is an actual removal, with no refund or free renewal.
        if family in ('internal_policy', 'occupation_policy', 'demobilisation'):
            opts.append(('End this funded policy', named('eligible'), ''.join('remove_ideas = ' + x + '_policy\n' for x in families[family])))
        opts.append(('Keep the present policy', '', ''))
        return new_event(q['label'], 'Choose one eligible funded programme. Its complete displayed term and native effects replace the previous programme in this family. Opening this review costs nothing; only the selected funded programme is charged.', opts)

    def offer(q, target, success, extra='', recipient_extra='', recipient_action=''):
        key = q['id']; pending = key + '_offer_pending'; inbox = key + '_inbox'
        budget_gate = '\n' + funded(q['cash']) if q.get('cash') and q['cash'] > 0 else ''
        accept_gate = 'tag = ' + target + '\n' + recipient_extra + '\n' + f(inbox) + '\nVIE = { ' + named('eligible') + '\n' + f(pending) + '\n' + decision_gates[key] + budget_gate + ' }'
        clear = cf(pending) + cf(key + '_awaiting_response')
        accepted = pay(q.get('cash') or 0) + clear + sf(key + '_accepted', 180) + success
        accepted += 'add_opinion_modifier = { target = ' + target + ' modifier = mdcw_cw_program_partner }\n'
        notice_accepted = new_event('Campaign Proposal Accepted', q['label'] + ' has been accepted. Only its defined current contribution has been charged. Native war, equipment and assistance systems still require their own actions.', [('We have been informed','','')])
        notice_declined = new_event('Campaign Proposal Declined', q['label'] + ' was declined or closed without an eligible agreement. No contribution was charged.', [('We have been informed','','')])
        effect(key + '_accept', cond(accept_gate, cf(inbox) + 'VIE = { ' + accepted + notice_accepted + ' }\nadd_opinion_modifier = { target = VIE modifier = mdcw_cw_program_partner }\n' + recipient_action))
        decline_gate = 'tag = ' + target + '\n' + f(inbox)
        refusal = clear + sf(key + '_refused')
        if key.endswith('soviet_assistance'): refusal += sf(C + 'soviet_response')
        effect(key + '_decline', cond(decline_gate, cf(inbox) + 'VIE = { ' + refusal + notice_declined + ' }'))
        text = q['result'] + ' ' + q['cost_risk'] + ' Acceptance records the stated agreement only. It never ends war, moves armies, installs a government or transfers equipment. The sender contribution is charged only on a current eligible acceptance.'
        close_gate = 'tag = ' + target + '\n' + f(inbox) + '\nNOT = { ' + accept_gate + ' }'
        close = cond(close_gate, cf(inbox) + 'VIE = { ' + refusal + notice_declined + ' }')
        invitation = new_event(q['label'], text, [
            ('Accept this current proposal', accept_gate, key + '_accept = yes\n'),
            ('Decline this invitation', 'tag = ' + target + '\n' + f(inbox) + '\nVIE = { ' + f(pending) + ' }', key + '_decline = yes\n'),
            ('Close the expired or invalid invitation', close_gate, close),
            ('This invitation does not belong to this government', 'NOT = { tag = ' + target + ' ' + f(inbox) + ' }', '')])
        send_gate = decision_gates[key] + budget_gate + '\n' + target + ' = { exists = yes NOT = { ' + f(inbox) + ' } }\nNOT = { ' + f(pending) + ' }\n' + extra
        effect(key + '_send', cond(send_gate, sf(pending, 90) + sf(key + '_awaiting_response') + target + ' = { ' + sf(inbox) + invitation + ' }'))
        offer_specs[key] = {'target': target, 'pending': pending, 'inbox': inbox, 'gate': send_gate}
        decision_actions[key] = key + '_send = yes\n'

    # Every approved decision is connected to a substantive action below.
    for key, q in decisions.items():
        decision_gates[key] = named('eligible') + '\n' + applied(q['focus'])
    def dg(suffix, test): decision_gates[P + suffix] += '\n' + test
    def da(suffix, body): decision_actions[P + suffix] = body
    for suffix, family in [('guerrilla_decision_renew_posture','war_method'),('guerrilla_decision_land_review','internal_policy'),
                           ('guerrilla_decision_security_review','internal_policy'),('guerrilla_decision_local_conference','internal_policy'),
                           ('guerrilla_decision_reserve_review','demobilisation'),('cambodia_decision_renew_border','cambodia_posture'),
                           ('cambodia_decision_occupation_review','occupation_policy'),('china_decision_renew_readiness','china_posture'),
                           ('china_decision_civil_review','civil_relief')]:
        q = decisions[P + suffix]; da(suffix, selection(q, family))
    dg('guerrilla_decision_renew_posture','has_war = yes')
    dg('guerrilla_decision_land_review','520 = { is_controlled_by = VIE }\n' + named('domestic_grievance'))
    dg('guerrilla_decision_security_review',named('domestic_grievance'))
    dg('guerrilla_decision_local_conference',named('south_control') + '\nNOT = { has_war = yes }')
    dg('guerrilla_decision_reserve_review','NOT = { has_war = yes }')
    dg('cambodia_decision_renew_border','CBD = { exists = yes }')
    dg('cambodia_decision_occupation_review',named('cbd_commitment'))
    dg('china_decision_renew_readiness','CHI = { exists = yes }')
    dg('china_decision_civil_review','stability < 0.55\nOR = { 523 = { is_controlled_by = VIE } 524 = { is_controlled_by = VIE } }')
    dg('guerrilla_decision_doctrine_review','NOT = { ' + f(C + 'exercise_completed') + ' }')
    da('guerrilla_decision_doctrine_review',pay(0.01) + 'army_experience = 10\n' + sf(C + 'exercise_completed'))
