def joint_file():
    L = [HEADER_U, "# Joint foci (Saadabad style): whoever completes a focus completes it for Moscow and every Union republic in the Union plan.",
         "# completion_reward runs for every member in its own scope (positive only); _joint_originator only for the one who completed it.",
         "# Attached with 'shared_focus = COLDWAR_UNI_the_union_plan' in COLDWAR_SOV_1970_focus and mdcw_1970_generic_focus.", ""]
    for f in JF:
        fid = f["id"]
        L += ["joint_focus = {", f"id = {fid}", f"icon = {f['icon']}"]
        if f["who"] == "sov":
            L.append("text_icon = JOINT_SOV_focus_style")
        if fid == ROOT:
            L += [f"x = {FO.UNION_ROOT[0]}", f"y = {FO.UNION_ROOT[1]}",
                  "offset = {", f"x = {FO.UNION_GENERIC[0] - FO.UNION_ROOT[0]}", f"y = {FO.UNION_GENERIC[1] - FO.UNION_ROOT[1]}",
                  "trigger = { has_focus_tree = mdcw_1970_generic_focus }", "}"]
        else:
            L += [f"x = {f['x']}", f"y = {f['y']}", f"relative_position_id = {ROOT}"]
        L += [f"cost = {f['cost']}"]
        if f["prereq"]:
            L.append(f"prerequisite = {{ focus = {f['prereq']} }}")
        if fid == ROOT:
            L += ["allow_branch = {", f"{PU}union_tag = yes", f"NOT = {{ has_country_flag = {PU}left_union }}", "}"]
        L += ["search_filters = { FOCUS_FILTER_INDUSTRY FOCUS_FILTER_POLITICAL }", f"joint_trigger = {{ {PU}is_member = yes }}"]
        who = {"all": utrig("who_all", "We take part in the Union plan (Moscow or a Union republic without a Declaration of Sovereignty).",
                            [f"{PU}is_member = yes"]),
               "sov": utrig("who_sov", "Only §YMoscow§! can take this focus (for the whole Union).", ["original_tag = SOV", f"{PU}is_member = yes"]),
               "rep": utrig("who_rep", "Only a §YUnion republic§! in the Union plan can take this focus (for the whole Union).",
                            [f"{PU}is_republic = yes"])}[f["who"]]
        L += ["available = {"] + who + f["extra_avail"] + ["}"]
        L += [f"select_effect = {{ set_global_flag = {{ flag = {fid}_in_progress days = {f['cost'] * 7 + 7} }} }}"]
        L += ["completion_reward = {", f'log = "[GetDateText]: [Root.GetName]: Focus {fid}"'] + f["every"] + ["}"]
        L += ["completion_reward_joint_originator = {", f'log = "[GetDateText]: [Root.GetName]: Focus {fid} (originator)"'] + f["originator"] + \
             [f"custom_effect_tooltip = {PU}joint_all_tt", "}"]
        if f["member"]:
            L += ["completion_reward_joint_member = {", f'log = "[GetDateText]: [Root.GetName]: Focus {fid} (member)"'] + f["member"] + ["}"]
        L += ["ai_will_do = {", f"base = {f['ai']}", "modifier = {", "factor = 0", f"has_global_flag = {fid}_in_progress", "}", "}", "}", ""]
        LOC[fid] = f["name"]
        LOC[fid + "_desc"] = f["desc"]
    LOC[f"{PU}joint_all_tt"] = TT_ALL
    return "\n".join(block(L)) + "\n"


