def sl(name, entries, fallback=None):
    L = ["defined_text = {", f"name = {name}"]
    for trig, key, text in entries:
        LOC[key] = text
        L += ["text = {", "trigger = {"] + trig + ["}", f"localization_key = {key}", "}"]
    if fallback:
        key, text = fallback
        LOC[key] = text
        L += ["text = {", f"localization_key = {key}", "}"]
    L.append("}")
    return L


