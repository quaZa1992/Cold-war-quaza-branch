def events_file():
    L = [HEADER_U, f"add_namespace = {NSU}", ""]
    for e in sorted(UEV, key=lambda x: x["n"]):
        eid = f"{NSU}.{e['n']}"
        kind = "news_event" if e.get("kind") == "news" else "country_event"
        L += [f"{kind} = {{", f"id = {eid}", f"title = {eid}.t", f"desc = {eid}.d", f"picture = {e['pic']}", ""]
        if e.get("major"):
            L.append("major = yes")
            if e.get("show_major"):
                L += ["show_major = {"] + e["show_major"] + ["}"]
        L.append("is_triggered_only = yes")
        if e.get("timeout"):
            L.append(f"timeout_days = {e['timeout']}")
        if e.get("hidden"):
            L.append("hidden = yes")
        if e.get("immediate"):
            L += ["", "immediate = {", f'log = "[GetDateText]: [Root.GetName]: event {eid}"'] + e["immediate"] + ["}"]
        L.append("")
        for i, (t, code, ai, trig) in enumerate(e["options"]):
            L += ["option = {", f"name = {eid}.{OPT_LETTERS[i]}"]
            if trig:
                L += ["trigger = {"] + trig + ["}"]
            L += ["ai_chance = {"] + ai.split("\n") + ["}"] + code + ["}"]
        L += ["}", ""]
        LOC[f"{eid}.t"] = e["title"]
        LOC[f"{eid}.d"] = e["desc"]
        for i, (t, *_rest) in enumerate(e["options"]):
            LOC[f"{eid}.{OPT_LETTERS[i]}"] = t
    return "\n".join(block(L)) + "\n"


