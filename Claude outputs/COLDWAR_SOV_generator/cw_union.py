def goal_trigger(fam, k):
    """the visible part of a mission's 'available'"""
    tid = f"goal_{fam}_{k}"
    goal = (GOAL if fam == "t" else D_GOAL)[k]
    if k in BV:
        parts = "; ".join(f"{BLABEL[v]} §Y[?{v}|0]§!, needed more than §Y[?{PU}{fam}_b{i}|0]§!" for i, v in enumerate(BV[k], start=1))
        body = ["OR = {"] + [f"check_variable = {{ {v} > {PU}{fam}_b{i} }}" for i, v in enumerate(BV[k], start=1)] + ["}"]
        return utrig(tid, f"Built: {goal}.\n{parts}.", body)
    if k == "roads":
        return utrig(tid, f"Built: {goal}.", ["any_owned_state = {", f"has_variable = {PU}{fam}_infra",
                                              f"check_variable = {{ building_level@infrastructure > {PU}{fam}_infra }}", "}"])
    if k == "deliver":
        return utrig(tid, f"Delivered: {goal} (decision §YDeliver to the Union Fund§!).", [f"has_country_flag = {PU}{fam}_delivered"])
    if k == "komsomol":
        return utrig(tid, f"Sent: {goal} (decision §YSend the Komsomol Brigades§!).", [f"has_country_flag = {PU}{fam}_komsomol"])
    if k == "discipline":
        return utrig(tid, f"{goal[0].upper()}{goal[1:]} (checked when the time runs out).", ["always = no"])
    raise KeyError(k)


