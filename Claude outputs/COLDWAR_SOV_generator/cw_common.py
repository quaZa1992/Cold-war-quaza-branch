def slug(s):
    s = s.lower().replace("'", "").replace("’", "")
    return re.sub(r"[^a-z0-9]+", "_", s).strip("_")


def fmt(v):
    if isinstance(v, str):
        return v
    if abs(v - round(v)) < 1e-9:
        return str(int(round(v)))
    return f"{v:.4f}".rstrip("0").rstrip(".")


def block(lines, base=0):
    """indent code lines by brace depth (lines may contain several statements on one line)"""
    out, d = [], base
    for raw in "\n".join(lines).split("\n"):
        line = raw.strip()
        if not line:
            if out and out[-1] != "" and not out[-1].endswith("{"):
                out.append("")
            continue
        opens, closes = line.count("{"), line.count("}")
        if line.startswith("}"):
            d -= 1
            out.append("\t" * d + line)
            d += opens - (closes - 1)
        else:
            out.append("\t" * d + line)
            d += opens - closes
    assert d == base, ("unbalanced", lines[:4], d)
    while out and out[-1] == "":
        out.pop()
    return out


def write(path, text, bom=False):
    full = os.path.join(OUT, path)
    os.makedirs(os.path.dirname(full), exist_ok=True)
    with open(full, "w", encoding="utf-8-sig" if bom else "utf-8", newline="\n") as fh:
        fh.write(text.replace("\r\n", "\n"))


def date_hoi(s):
    """'01.03.1971' -> '1971.3.1'"""
    d, m, y = s.split(".")
    return f"{int(y)}.{int(m)}.{int(d)}"


def date_minus_one(s):
    """date >= X is written as date > X-1 day"""
    import datetime
    d, m, y = [int(x) for x in s.split(".")]
    t = datetime.date(y, m, d) - datetime.timedelta(days=1)
    return f"{t.year}.{t.month}.{t.day}"


