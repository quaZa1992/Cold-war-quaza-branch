_MD_LOC_KEYS = None


def md_loc_keys():
    """every loc key of the mod (English), without our own Soviet file"""
    global _MD_LOC_KEYS
    if _MD_LOC_KEYS is None:
        import glob
        _MD_LOC_KEYS = set()
        for f in glob.glob(os.path.join(MOD, "localisation/english/**/*.yml"), recursive=True):
            if "COLDWAR_SOV" in f:
                continue
            for line in open(f, encoding="utf-8-sig", errors="replace"):
                m = re.match(r"^\s+([^\s:#]+):\d*\s", line)
                if m:
                    _MD_LOC_KEYS.add(m.group(1))
    return _MD_LOC_KEYS


def _vanilla_modifier_label(mod):
    """the game's own modifier text ($MODIFIER_X$ or MD's $modifier$) when we have no English label of our own"""
    keys = md_loc_keys()
    for key in ("MODIFIER_" + mod.upper(), "MODIFIER_" + mod, mod):
        if key in keys:
            return f"${key}$"
    return None


def modifier_loc(mod):
    """modifiers the game cannot name (idea-category cost factors without MD text) get a loc key = the modifier name"""
    if mod in NEEDS_LOC and mod not in md_loc_keys():
        LOC[mod] = MOD_EN[mod]


def mod_tt_key(mod):
    """custom tooltip key for add_to_variable on a dynamic-modifier variable"""
    k = f"COLDWAR_SOV_mod_{mod}_tt"
    if k not in LOC:
        modifier_loc(mod)
        label = MOD_EN.get(mod) or _vanilla_modifier_label(mod)
        assert label, f"no English label for modifier {mod}: add it to cw_common.MOD_EN"
        if mod == "interest_rate_multiplier_modifier":
            LOC[k] = f"{label}: $RIGHT|-=2$ percentage points"
            return k
        if mod in COUNT_KEYS:
            fmtc = "+=0"
        elif mod in FLAT_KEYS:
            fmtc = "+=2" if mod not in COST_KEYS else "-=2"
        else:
            fmtc = "+=%1" if mod not in COST_KEYS else "-=%1"
        LOC[k] = f"{label}: $RIGHT|{fmtc}$"
    return k
