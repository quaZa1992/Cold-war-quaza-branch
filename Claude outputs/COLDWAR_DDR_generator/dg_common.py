def mod_tt_key(mod):
    """tooltip of add_to_variable on a dynamic-modifier variable: MD's <modifier>_tt where MD has one,
    otherwise COLDWAR_<modifier>_tt in the shared tooltip file (MD format, coloured by the good direction)"""
    if f"{mod}_tt" in MD_TT and mod not in MD_TT_WRONG:
        return f"{mod}_tt"
    k = f"COLDWAR_{mod}_tt"
    if k not in SHARED_TT:
        modifier_loc(mod)
        # the game's own modifier name first (MD writes $MODIFIER_X$), our English label only where the game has none
        label = _vanilla_modifier_label(mod) or MOD_EN.get(mod)
        assert label, f"no English label for modifier {mod}: add it to dg_common.MOD_EN"
        if mod in COUNT_KEYS:
            fmtc = "+=0"
        elif mod in FLAT_KEYS:
            fmtc = "+=2" if mod not in COST_KEYS else "-=2"
        else:
            fmtc = "+=%1" if mod not in COST_KEYS else "-=%1"
        SHARED_TT[k] = f"{label}: $RIGHT|{fmtc}$"
    return k
