def slug(s):
    s = s.lower().replace("'", "").replace("’", "")
    return re.sub(r"[^a-z0-9]+", "_", s).strip("_")


def fmt(v):
    if isinstance(v, str):
        return v
    if abs(v - round(v)) < 1e-9:
        return str(int(round(v)))
    return f"{v:.4f}".rstrip("0").rstrip(".")


# MD writes these blocks always over several lines (05_russia.txt: add_power_balance_value 52x, swap_ideas 53x, add_tech_bonus)
MULTI_KEYS = ("add_power_balance_value", "swap_ideas", "add_tech_bonus")
_TOK = re.compile(r'"[^"]*"|<=|>=|[{}=<>]|[^\s{}=<>"]+')


def _parse(tokens, i=0):
    items = []
    while i < len(tokens) and tokens[i] != "}":
        t = tokens[i]
        if i + 1 < len(tokens) and tokens[i + 1] in ("=", "<", ">", "<=", ">="):
            op = tokens[i + 1]
            if tokens[i + 2] == "{":
                sub, i = _parse(tokens, i + 3)
                items.append((t, op, sub))
                i += 1
            else:
                items.append((t, op, tokens[i + 2]))
                i += 3
        else:
            items.append((t, None, None))
            i += 1
    return items, i


def _render(items):
    out = []
    for k, op, v in items:
        if op is None:
            out.append(k)
        elif isinstance(v, list):
            if k not in MULTI_KEYS and not any(isinstance(x[2], list) and (x[0] in MULTI_KEYS or _has_multi(x[2])) for x in v):
                out.append(f"{k} {op} {{ " + " ".join(_render(v)) + " }")
            else:
                out += [f"{k} {op} {{"] + _render(v) + ["}"]
        else:
            out.append(f"{k} {op} {v}")
    return out


def _has_multi(items):
    return any(isinstance(v, list) and (k in MULTI_KEYS or _has_multi(v)) for k, op, v in items)


def md_expand(line):
    """one-line add_power_balance_value / swap_ideas / add_tech_bonus (also inside an if) -> MD's multi-line form"""
    if "#" in line or not any(k + " = {" in line for k in MULTI_KEYS):
        return [line]
    toks = _TOK.findall(line)
    if toks.count("{") != toks.count("}"):
        return [line]
    items, _ = _parse(toks)
    return _render(items)


def block(lines, base=0):
    """indent code lines by brace depth (lines may contain several statements on one line)"""
    out, d = [], base
    exp = []
    for raw in "\n".join(lines).split("\n"):
        exp += md_expand(raw.strip()) if raw.strip() else [raw]
    for raw in exp:
        line = raw.strip()
        if not line:
            if out and out[-1] != "" and not out[-1].endswith("{"):
                out.append("")
            continue
        opens, closes = line.count("{"), line.count("}")
        if line.startswith("}"):
            d -= 1
            out.append("\t" * d + line)
            d += opens - (closes - 1)
        else:
            out.append("\t" * d + line)
            d += opens - closes
    assert d == base, ("unbalanced", lines[:4], d)
    while out and out[-1] == "":
        out.pop()
    return out


def write(path, text, bom=False):
    full = os.path.join(OUT, path)
    os.makedirs(os.path.dirname(full), exist_ok=True)
    with open(full, "w", encoding="utf-8-sig" if bom else "utf-8", newline="\n") as fh:
        fh.write(text.replace("\r\n", "\n"))


def date_hoi(s):
    """'01.03.1971' -> '1971.3.1'"""
    d, m, y = s.split(".")
    return f"{int(y)}.{int(m)}.{int(d)}"


def date_minus_one(s):
    """date >= X is written as date > X-1 day"""
    import datetime
    d, m, y = [int(x) for x in s.split(".")]
    t = datetime.date(y, m, d) - datetime.timedelta(days=1)
    return f"{t.year}.{t.month}.{t.day}"


