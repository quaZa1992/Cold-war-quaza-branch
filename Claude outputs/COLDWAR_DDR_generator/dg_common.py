def _md_tt_keys():
    """tooltip keys that are DEFINED in MD's (and the mod's) localisation - a key MD's trees merely use is not enough"""
    keys = set()
    files = glob.glob(os.path.join(MOD, "localisation/english/**/*.yml"), recursive=True) + \
        glob.glob("/mnt/user-data/uploads/2777392649/localisation/english/**/*.yml", recursive=True)
    for p in files:
        if "COLDWAR_DDR" in os.path.basename(p) or os.path.basename(p) == os.path.basename(SHARED_TT_FILE):
            continue
        for line in open(p, encoding="utf-8-sig", errors="replace"):
            m = re.match(r"^\s+([A-Za-z0-9_]+_tt):\d*\s", line)
            if m:
                keys.add(m.group(1))
    assert "political_power_factor_tt" in keys, "MD tooltip keys not found (MD_dm_modifiers_l_english.yml)"
    return keys


