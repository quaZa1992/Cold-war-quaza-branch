# IMPERIA CW — Cold War: Generic 1970 national focus content generator.
"""COLDWAR | write mdcw_1970_generic_focus.txt: header kept, party paths + trunks from the design,
domain blocks moved to floor 2 and re-emitted in MD field order (rewards verbatim)."""
import re
from gen_common import (P, num, FIRST_ENTRY_X, PARTY_ROW, FLOOR2_ROW, FLOOR2_X, BLOCK_GAP, CONTINUOUS_FOCUS_POSITION,
                        DOMAIN_ORDER, POLITICAL_SECTIONS, OUTLOOK_GOV, CHAMPIONS, ALLOW_BRANCH, AI_BASE_NEW, AI_OVERRIDE)
from gen_load import abs_positions, simple

MD_ORDER = [['id', 'icon'], ['x', 'y', 'relative_position_id'], ['cost'], ['allow_branch'],
            ['prerequisite', 'mutually_exclusive', 'will_lead_to_war_with'], ['search_filters'], ['available'],
            ['bypass'], ['cancel', 'cancel_if_invalid', 'continue_if_invalid', 'available_if_capitulated', 'select_effect'],
            ['completion_reward'], ['ai_will_do']]
KNOWN = {k for g in MD_ORDER for k in g}

HEADER_NOTE = ('# IMPERIA CW — Cold War: Generic 1970 national focus content generator.\n## COLDWAR | Party paths, outlook trunks and the two-floor layout are generated by Claude outputs/COLDWAR_GEN_generator (gen_build.py); run it again after tools/generate_1970_generic_focus_tree.py.\n')


def collapse(raw):
    """'{\\n\\t\\t\\tx = y\\n\\t\\t}' -> '{ x = y }' when the block holds one simple line (MD style)"""
    if not raw.startswith('{'):
        return raw
    inner = raw[1:-1].strip()
    if '\n' not in inner and '{' not in inner and len(inner) < 90:
        return '{ ' + inner + ' }' if inner else '{ }'
    if inner.count('\n') == 0 and len(inner) < 90:
        return '{ ' + inner + ' }'
    return raw


def emit_block(fields):
    """fields: list of (key, value) where value is a scalar or a raw block text with 2-tab base indentation"""
    for k, _ in fields:
        if k not in KNOWN:
            raise ValueError(f'unknown focus field {k}')
    lines = ['\tfocus = {']
    first = True
    for grp in MD_ORDER:
        items = [(k, v) for g in grp for k, v in fields if k == g]
        if not items:
            continue
        if not first:
            lines.append('')
        first = False
        for k, v in items:
            lines.append(f'\t\t{k} = {v}')
    lines.append('\t}')
    return '\n'.join(lines)


def block(lines, base=2):
    """list of relative lines -> raw '{ ... }' text at the given base indentation (focus fields = 2 tabs)"""
    ind = '\t' * (base + 1)
    return '{\n' + '\n'.join((ind + l) if l else '' for l in lines) + '\n' + '\t' * base + '}'


# ---------------------------------------------------------------- search filters for party and trunk foci
def filters(node):
    fx = node['fx']
    f = ['FOCUS_FILTER_POLITICAL']
    cand = []
    if any(e[0] == 'build' and any(x in e[1] for x in ('industrial', 'arms_factory', 'dockyard', 'office', 'infrastructure',
                                                         'agriculture', 'refinery', 'energy', 'powerplant', 'reactor'))
           for e in fx):
        cand.append('FOCUS_FILTER_INDUSTRY')
    if any(e[0] == 'tech' for e in fx) or any(e[0] == 'build' and 'facility' in e[1] for e in fx):
        cand.append('FOCUS_FILTER_RESEARCH')
    if any(e[0] == 'xp' and e[1] == 'army' for e in fx):
        cand.append('FOCUS_FILTER_ARMY_XP')
    if any(e[0] == 'xp' and e[1] == 'navy' for e in fx):
        cand.append('FOCUS_FILTER_NAVY_XP')
    if any(e[0] == 'xp' and e[1] == 'air' for e in fx):
        cand.append('FOCUS_FILTER_AIRCRAFT')
    if any(e[0] == 'law' and 'military' in e[1] for e in fx):
        cand.append('FOCUS_FILTER_MILITARY_LAWS')
    if any(e[0] == 'law' and 'military' not in e[1] for e in fx):
        cand.append('FOCUS_FILTER_EXPENDITURE')
    if any(e[0] == 'prog' and e[1] in ('foreign_influence_modifier', 'mdcw_cw_support_effectiveness') and e[2] > 0 for e in fx):
        cand.append('FOCUS_FILTER_INFLUENCE')
    if any(e[0] == 'ws' for e in fx) or any(e[0] == 'prog' and e[1] == 'war_support_factor' and e[2] > 0 for e in fx):
        cand.append('FOCUS_FILTER_WAR_SUPPORT')
    if any(e[0] == 'stab' and e[1] > 0 for e in fx) or any(e[0] == 'prog' and e[1] == 'stability_factor' and e[2] > 0 for e in fx):
        cand.append('FOCUS_FILTER_STABILITY')
    if any(e[0] == 'fac' and e[2] > 0 for e in fx):
        cand.append('FOCUS_FILTER_INTERNAL_FACTION')
    for c in cand:
        if c not in f and len(f) < 3:
            f.append(c)
    return '{ ' + ' '.join(f) + ' }'


def cost_txt(c):
    return str(int(c)) if float(c).is_integer() else str(c)


# ---------------------------------------------------------------- political sections
def political_sections(design, ctx, icons, old, meta, compile_focus, resolve_md, guarded, programme_vars):
    """returns {outlook: text} with the trunk and all party trees of that outlook"""
    nodes = design['nodes']
    by_id = {n['id']: n for n in nodes}
    trunk_x = {t['o']: t['x'] for t in design['trunks']}
    party_x = {p['key']: p['x'] for p in design['parties']}
    texts = {}
    for o in POLITICAL_SECTIONS:
        parts = []
        t_nodes = [n for n in nodes if n['grp'] == 'trunk' and n['o'] == o]
        t0 = next(n for n in t_nodes if n['slot'] == 'T0')
        groups = [('trunk', None, t_nodes)]
        for p in sorted([p for p in design['parties'] if p['o'] == o], key=lambda p: p['idx']):
            groups.append(('party', p, [n for n in nodes if n['grp'] == 'party' and n['party'] == p['key']]))
        for kind, p, ns in groups:
            if kind == 'party':
                parts.append(f'\t#Start of {p["party"]} Branch')
            for n in ns:
                parts.append(emit_block(focus_fields(n, t0, trunk_x, party_x, by_id, ctx, icons, old, meta,
                                                     compile_focus, resolve_md, guarded, programme_vars)))
                parts.append('')
        texts[o] = '\n'.join(parts)
    return texts


def focus_fields(n, t0, trunk_x, party_x, by_id, ctx, icons, old, meta, compile_focus, resolve_md, guarded, programme_vars):
    fid = P + n['id']
    fields = [('id', fid), ('icon', icons[n['id']])]
    # position
    if n['grp'] == 'trunk':
        if n['slot'] == 'T0':
            fields += [('x', str(trunk_x[n['o']])), ('y', '0')]
        else:
            fields += [('x', str(n['x'] - t0['x'])), ('y', str(n['y'] - t0['y'])), ('relative_position_id', P + t0['id'])]
    else:
        if n['slot'] == 'E':
            fields += [('x', str(n['x'] - t0['x'])), ('y', str(n['y'] - t0['y'])), ('relative_position_id', P + t0['id'])]
        else:
            e = next(x for x in by_id.values() if x['grp'] == 'party' and x['party'] == n['party'] and x['slot'] == 'E')
            fields += [('x', str(n['x'] - e['x'])), ('y', str(n['y'] - e['y'])), ('relative_position_id', P + e['id'])]
    fields.append(('cost', cost_txt(n['cost'])))
    # religion gates
    gate = ALLOW_BRANCH.get(n['id']) or (ALLOW_BRANCH.get(n['party']) if n['slot'] == 'E' else None)
    if gate:
        fields.append(('allow_branch', f'{{ {P}{gate} = yes }}'))
    for g in n['pre']:
        fields.append(('prerequisite', '{ ' + ' '.join(f'focus = {P}{x}' for x in g) + ' }'))
    if n['mx']:
        fields.append(('mutually_exclusive', '{ ' + ' '.join(f'focus = {P}{x}' for x in n['mx']) + ' }'))
    fields.append(('search_filters', filters(n)))
    # availability
    if n['grp'] == 'party':
        trig = meta[n['party']]['trigger']
        fields.append(('available', f'{{ {trig} = yes }}'))
    elif n['slot'] == 'T0':
        others = [CHAMPIONS[x] for x in CHAMPIONS if x != n['o']]
        lines = ['OR = {', '\tNOT = {'] + [f'\t\thas_completed_focus = {P}{x}' for x in others] + \
                ['\t}', f'\thas_government = {OUTLOOK_GOV[n["o"]]}', '}']
        fields.append(('available', block(lines)))
    elif n['slot'] == 'T3':
        fields.append(('available', f'{{ has_government = {OUTLOOK_GOV[n["o"]]} }}'))
    # reward
    prog = programme_vars.get(n['party']) if n['party'] else None
    lines = compile_focus(ctx, n, prog[0] if prog else None, prog[1] if prog else None)
    lines = resolve_md(lines, guarded)
    reward = [f'log = "[GetDateText]: [Root.GetName]: Focus {fid}"'] + lines
    fields.append(('completion_reward', block(reward)))
    # AI
    base = old.get(fid, {}).get('ai_base', AI_BASE_NEW)
    if n['slot'] == 'E':
        base = AI_BASE_NEW
    base = AI_OVERRIDE.get(n['id'], base)
    if n['grp'] == 'party':
        mod = f'modifier = {{ factor = 0 {meta[n["party"]]["trigger"]} = no }}'
    else:
        mod = f'modifier = {{ factor = 0 NOT = {{ has_government = {OUTLOOK_GOV[n["o"]]} }} }}'
    fields.append(('ai_will_do', block([f'base = {base}', mod])))
    return fields


# ---------------------------------------------------------------- domain blocks
def domain_moves(sections):
    """translation (dx, dy) per domain section so that the blocks sit on floor 2 in DOMAIN_ORDER (idempotent)"""
    secd = dict(sections)
    all_foci = {}
    for name, foci in sections:
        for f in foci:
            d = simple(f['fields'])
            all_foci[f['id']] = dict(x=int(d['x']), y=int(d['y']), rel=d.get('relative_position_id'), sec=name)
    pos = abs_positions(all_foci)
    moves = {}
    x = FLOOR2_X
    for name in DOMAIN_ORDER:
        ids = [f['id'] for f in secd[name]]
        for i in ids:
            r = all_foci[i]['rel']
            if r and all_foci[r]['sec'] != name:
                raise ValueError(f'{i} is placed relative to {r} in another block')
        xs = [pos[i][0] for i in ids]
        ys = [pos[i][1] for i in ids]
        moves[name] = (x - min(xs), FLOOR2_ROW - min(ys), (x, max(xs) - min(xs) + x))
        x = x + (max(xs) - min(xs)) + BLOCK_GAP
    return moves, pos, all_foci


TENSION_RE = re.compile(r'(\t*)set_temp_variable = \{ GEN_1970_tension_change = (-?\d+) \}\n\t*GEN_1970_change_tension = yes')


def tension_sub(m):
    i, v = m.group(1), m.group(2)
    return (f'{i}if = {{\n{i}\tlimit = {{ has_variable = global.mdcw_cw_tension }}\n'
            f'{i}\tset_temp_variable = {{ mdcw_cw_tension_delta = {v} }}\n{i}\tmdcw_cw_add_tension = yes\n{i}}}')


def domain_text(name, foci, move):
    dx, dy, _ = move
    out = []
    for f in foci:
        fields = []
        d = simple(f['fields'])
        for k, v in f['fields']:
            if k == 'x' and not d.get('relative_position_id'):
                v = str(int(v) + dx)
            elif k == 'y' and not d.get('relative_position_id'):
                v = str(int(v) + dy)
            elif k == 'completion_reward':
                v = TENSION_RE.sub(tension_sub, v)
            elif k in ('available', 'allow_branch', 'bypass'):
                v = collapse(v)
            fields.append((k, v))
        out.append(emit_block(fields))
        out.append('')
    return '\n'.join(out)


def government_text(foci):
    out = []
    for f in foci:
        fields = [(k, collapse(v) if k in ('available', 'allow_branch', 'bypass') else v) for k, v in f['fields']]
        out.append(emit_block(fields))
        out.append('')
    return '\n'.join(out)


def header_text(header):
    h = header
    if 'COLDWAR_GEN_generator' not in h:
        i = h.index('focus_tree = {')
        h = h[:i] + HEADER_NOTE + h[i:]
    x, y = CONTINUOUS_FOCUS_POSITION
    h, n = re.subn(r'continuous_focus_position = \{[^}]*\}', f'continuous_focus_position = {{ x = {x} y = {y} }}', h)
    assert n == 1, 'continuous_focus_position not found'
    return h


def write_focus_file(loaded, pol_texts, moves):
    secd = dict(loaded['sections'])
    out = [header_text(loaded['header'])]
    out.append('\t### Government ###\n' + government_text(secd['Government']))
    for o, name in POLITICAL_SECTIONS.items():
        out.append(f'\t### {name} ###\n' + pol_texts[o])
    for name in DOMAIN_ORDER:
        out.append(f'\t### {name} ###\n' + domain_text(name, secd[name], moves[name]))
    text = '\n'.join(x.rstrip('\n') + '\n' for x in out)
    text = text.rstrip('\n') + '\n}\n'
    return text
