# ---------------------------------------------------------------- national spirits (Russian.txt style)
def ideas_file(ideas, pictures, meta):
    L = ['## COLDWAR | National spirits of the party paths and outlook trunks in the 1970 generic tree (mdcw_1970_generic_focus).',
         GEN_NOTE.rstrip('\n'),
         '## Bound spirits (regime institutions) are cancelled when their party loses power; the others are lasting reforms.',
         '', 'ideas = {', '\tcountry = {']
    for iid, d in ideas.items():
        L.append(f'\t\t{iid} = {{')
        L.append(f'\t\t\tpicture = {pictures[iid]}')
        L.append('\t\t\tallowed_civil_war = { always = yes }')
        cw = any(k in CW_KEYS for k in d['mods'])
        market = any(k in MARKET_KEYS for k in d['mods'])
        if d['bound']:
            L.append(f'\t\t\tcancel = {{ {meta[d["party"]]["trigger"]} = no }}')
        if d['bound'] or cw:
            L.append('\t\t\ton_remove = {')
            L.append(f'\t\t\t\tlog = "[GetDateText]: [Root.GetName]: Idea {iid} removed"')
            if cw:
                L += ['\t\t\t\thidden_effect = {', '\t\t\t\t\tif = {', '\t\t\t\t\t\tlimit = { has_country_flag = mdcw_cw_initialized }',
                      '\t\t\t\t\t\tmdcw_cw_recalculate_country = yes']
                if market:
                    L.append('\t\t\t\t\t\tmdcw_cw_update_world_market = yes')
                L += ['\t\t\t\t\t}', '\t\t\t\t}']
            L.append('\t\t\t}')
        L.append('\t\t\tmodifier = {')
        for k, v in d['mods'].items():
            L.append(f'\t\t\t\t{k} = {num(v)}')
        L.append('\t\t\t}')
        L.append('\t\t}')
    L += ['\t}', '}', '']
    return '\n'.join(L)


# ---------------------------------------------------------------- party programmes (99_SOV_dynamic_modifiers style)
def old_programme_icons(text):
    return dict(re.findall(r'^(GEN_1970_\w+_programme) = \{\s*icon = (\S+)', text, re.M))


def dynmod_file(design, meta, old_icons):
    L = ['## COLDWAR | Party programmes of the 1970 generic tree. Each is active only while its party governs (enable),',
         '## so a programme returns when the party returns to power. Values live in country variables GEN_1970_<party>_<modifier>.',
         GEN_NOTE.rstrip('\n'), '']
    keys_by_party = {}
    for n in design['nodes']:
        if n['grp'] != 'party':
            continue
        for e in n['fx']:
            if e[0] == 'prog':
                ks = keys_by_party.setdefault(n['party'], [])
                if e[1] not in ks:
                    ks.append(e[1])
    for p in sorted(design['parties'], key=lambda p: p['idx']):
        k = p['key']
        name = f'{P}{k}_programme'
        L.append(f'{name} = {{')
        L.append(f'\ticon = {old_icons.get(name, "GFX_idea_political_establishment")}')
        L.append('')
        L += ['\tenable = {', '\t\tIMP_is_1970_scenario = yes', f'\t\t{meta[k]["trigger"]} = yes', '\t}', '']
        for key in keys_by_party.get(k, []):
            L.append(f'\t{key} = {P}{k}_{key}')
        L.append('}')
        L.append('')
    return '\n'.join(L), keys_by_party


# ---------------------------------------------------------------- localisation
def esc(t):
    return t.replace('\\', '').replace('"', '\\"').replace('\n', ' ')


def loc_keys(text):
    return re.findall(r'^ ([A-Za-z0-9_.\-]+):\d* "', text, re.M)


def old_loc_transform(text, owned_prefix_ids):
    """drop the lines of keys we now own (focus names/descs and old programme tooltips of party and trunk foci)"""
    drop = set()
    for i in owned_prefix_ids:
        drop |= {i, i + '_desc', i + '_programme_tt'}
    out = []
    removed = []
    for line in text.split('\n'):
        m = re.match(r'^ ([A-Za-z0-9_.\-]+):\d* "', line)
        if m and m.group(1) in drop:
            removed.append(m.group(1))
            continue
        out.append(line)
    return '\n'.join(out), removed


def new_loc_file(design, ctx, old_keys):
    L = ['l_english:\n# IMPERIA CW — Cold War: COLDWAR GEN generator English localisation.',
         ' # COLDWAR | Party paths and outlook trunks of the 1970 generic tree (Claude outputs/COLDWAR_GEN_generator).',
         ' # Focus descriptions are the historical precedents of the approved design (claude/mdcw_1970_generic_party_paths_design.md).']
    seen = {}
    def add(k, v):
        if k in seen:
            if seen[k] == v:
                return          # an idea that shares id and name with its focus uses the focus key
            raise ValueError('duplicate loc key ' + k)
        if k in old_keys:
            raise ValueError(f'loc key {k} already exists in the old generic loc file')
        seen[k] = v
        L.append(f' {k}: "{esc(v)}"')
    order = 'WESNR'
    pidx = {p['key']: p['idx'] for p in design['parties']}
    nodes = sorted(design['nodes'], key=lambda n: (order.index(n['o']), 0 if n['grp'] == 'trunk' else 1, pidx.get(n['party'], -1)))
    cur = None
    for n in nodes:
        grp = n['party'] or n['o']
        if grp != cur:
            L.append(f' # {OUTLOOK_LABEL[n["o"]]} outlook' if n['grp'] == 'trunk' else f' # {n["party"]}')
            cur = grp
        add(P + n['id'], n['name'])
        add(P + n['id'] + '_desc', n['why'])
    L.append(' # National spirits')
    for iid, d in ctx.ideas.items():
        add(iid, d['name'])
    L.append(' # Tooltips')
    for k, v in sorted(ctx.loc.items()):
        if k in old_keys:
            continue           # reuse the existing key of the old generic loc file
        add(k, v)
    return '\n'.join(L) + '\n', seen


# same header and order as the GDR generator (dg_build.shared_tooltips): every generator writes this file identically
SHARED_TT_HEAD = [' # COLDWAR | Modifier tooltips of the COLDWAR focus trees for keys without an MD tooltip (or with a wrong MD colour).',
                  ' # MD format: <Label>: $RIGHT|+=%1$ (green when it rises) / -=%1 (green when it falls). Shared by all trees: reuse keys, add missing ones.']


def shared_tt_file(existing_text, coldwar_tt, loc):
    """merge: every existing key stays as it is (other trees use it), missing ones are added; sorted (idempotent)"""
    have = {}
    for line in (existing_text or '').split('\n'):
        m = re.match(r'^\s+([A-Za-z0-9_.]+):\d*\s+"(.*)"\s*$', line)
        if m:
            have[m.group(1)] = m.group(2)
    added = []
    for key, (label, fmt) in sorted(coldwar_tt.items()):
        k = f'COLDWAR_{key}_tt'
        if k not in have:
            have[k] = f'{game_label(key, label, loc)}: $RIGHT|{fmt}$'
            added.append(k)
    out = ['l_english:\n# IMPERIA CW — Cold War: COLDWAR GEN generator English localisation.'] + SHARED_TT_HEAD + [f' {k}: "{have[k]}"' for k in sorted(have)]
    return '\n'.join(out) + '\n', added


# ---------------------------------------------------------------- scripted effects: tension helper -> Cold War helper
TENSION_HELPER = '''# Changes the global Cold War tension (MDCW, 0-100). Input: GEN_1970_tension_change.
# COLDWAR | wrapper around mdcw_cw_add_tension, the only allowed way to change tension (kept for older callers).
GEN_1970_change_tension = {
	if = {
		limit = { has_variable = global.mdcw_cw_tension }
		set_temp_variable = { mdcw_cw_tension_delta = GEN_1970_tension_change }
		mdcw_cw_add_tension = yes
	}
}'''


def effects_patch(text):
    i = text.find('GEN_1970_change_tension = {')
    assert i >= 0, 'GEN_1970_change_tension not found'
    # include the comment lines directly above
    start = text.rfind('\n\n', 0, i) + 2
    e = block_end(text, i)
    return text[:start] + TENSION_HELPER + text[e + 1:]
